/**
 * **ボタンの色を、1か所で決める**(第5.242節・2026-09-23 利用者の指摘)。
 *
 *   > ボタンが全て白なのも分かりにくい要因の一つです
 *
 * 共通ルール(`.claude/rules/common.md`)に3つだけ決めてある。
 *
 *   | 色 | 何に使うか |
 *   |---|---|
 *   | **青(塗りつぶし)** | **次に進む**もの。1つの画面に1つだけ |
 *   | **灰(塗りつぶし)** | **ならぶ**もの(一覧・選ぶもの) |
 *   | **枠線だけ** | 控えめなもの(送る・戻す・開く) |
 *
 * **既定のボタン(地の色のまま)は、白い紙の上で「押せるもの」に見えない。**
 * ところが 6Steps の練習は**紙の上**に出る。`.lesson-sheet .btn` が
 * どのボタンも紙の白にそろえていたので、色を書いても効かず、
 * **結果として全部が白**になっていた(styles.css の同じ節で直してある)。
 *
 * 【なぜ表にするのか】
 *   押している / いないで色を変えるボタンが3つある
 *   (`SpeakButton` / `SpeakCheckButton` / `RepeatToggle`)。
 *   3つとも `on ? ' btn--primary' : ''` と**書き写していた**ので、
 *   **押す前が白**になっていた —— 押せるものに見えないのは、こちら側である。
 *   **置く場所の数だけ食い違う**(CLAUDE.md)。判断はここ1か所に持つ。
 */

/** **次に進む。** 1つの画面に1つだけ。押している最中の印にも使う */
export const TONE_GO = 'btn--primary'
/** **ならぶもの。** 行ごとに1つずつ出るもの(Listen・くり返し) */
export const TONE_ROW = 'btn--quiet'
/** **控えめなもの。** 送る・戻す・開く・消す */
export const TONE_SIDE = 'btn--ghost'

/** 3つの色。**一覧はここだけ**(2か所に書くと、片方が必ず古くなる) */
const TONES = [TONE_GO, TONE_ROW, TONE_SIDE]

/**
 * その class 名が、もう色を持っているか。
 *
 * **語の一部で見ない。** `btn--primary` は `btn--primary-x` を
 * 巻き込むので、空白で割ってから突き合わせる。
 */
export const hasTone = (cls) => String(cls ?? '').split(/\s+/).some((c) => TONES.includes(c))

/**
 * 押している / いないで色を替えるボタンの色。
 *
 * **押していないときも、必ず色を持つ。** ここが `''` だと白いままになる。
 *
 * **呼ぶ側が色を決めているときは、そちらを立てる**(`cls` に色があれば
 * 休んでいるときは何も足さない)。両方が付くと、**1つのボタンに色が2つ**
 * 乗ることになり、どちらが効くかは styles.css に書いた順で決まる ——
 * **色を2か所に書かない**(CLAUDE.md)。
 * **押している最中だけは、呼ぶ側の指定より優先して青**にする。
 * 「いま鳴っている / 聞いている」は見た目ではなく**状態**だからである。
 *
 * @param {boolean} on いま押している(鳴っている・聞いている)か
 * @param {string} cls 呼ぶ側が渡してきた class 名
 * @returns {string} 付ける class 名
 */
export const toneOn = (on, cls = '') => {
  if (on) return TONE_GO
  return hasTone(cls) ? '' : TONE_ROW
}
