/**
 * 顔の一覧。**増やすなら、ここだけ。**
 *
 * | 顔 | いつ | 何を伝えるか |
 * |---|---|---|
 * | `rest`   | 何もしていない | 居る。息をしている |
 * | `listen` | 音が鳴っている | 一緒に聞いている |
 * | `think`  | 待たせている | 動いている(止まっていない) |
 * | `glad`   | 合っていた | できた |
 * | `cheer`  | 違っていた | **責めない。** 知らないことは失敗ではない |
 * | `proud`  | やり切った | ここまで来た |
 */
export const BUDDY_FACES = ['rest', 'listen', 'think', 'glad', 'cheer', 'proud']

/** 迷ったときの顔。**既定は「居るだけ」** */
export const BUDDY_DEFAULT = 'rest'

/**
 * ★ **顔を決めるのは、ここ1か所。**
 *
 * 画面の中で `score >= 80 ? '…' : '…'` と書かない ——
 * 置く場所の数だけ食い違う(CLAUDE.md「判断は1か所に持つ」)。
 *
 * **見る順番に意味がある。**
 *   ①やり切った …「終わった」は、ほかの何より強い
 *   ②合っていた / 違っていた … その瞬間の返り
 *   ③待たせている … 音より先。待たせていることを隠さない
 *   ④音が鳴っている
 *   ⑤それ以外 … 居るだけ
 *
 * @param {object} s
 * @param {boolean} [s.done]    やり切ったか
 * @param {number}  [s.score]   そのときの点(0〜100)。`done` のときだけ見る
 * @param {boolean} [s.ok]      いまの答えが合っていたか(`null` なら見ない)
 * @param {boolean} [s.busy]    待たせているか(生成・支度)
 * @param {boolean} [s.playing] 音が鳴っているか
 */
export const buddyFace = ({
  done = false, score = null, ok = null, busy = false, playing = false,
} = {}) => {
  /* ① やり切った。**点が低くても `cheer` にしない** ——
       やり切ったことそのものを受け取る。点の話は声かけの役目である */
  if (done) {
    /* ★ **0 と `null` を取り違えない**(CLAUDE.md)。
         `Number(null)` は **0** になるので、点を渡していないだけの場面が
         「0 点だった」と読まれ、やり切ったのに励まされていた
         (作った日に踏んで、測って気づいた)。
         **点が無いなら、点の話はしない** */
    const 点あり = score !== null && score !== undefined && score !== ''
    const n = Number(score)
    return 点あり && Number.isFinite(n) && n < 50 ? 'cheer' : 'proud'
  }
  /* ② その瞬間の返り */
  if (ok === true) return 'glad'
  if (ok === false) return 'cheer'
  /* ③ 待たせている。**音より先に出す** —— 待っていることを隠さない */
  if (busy) return 'think'
  /* ④ 一緒に聞いている */
  if (playing) return 'listen'
  return BUDDY_DEFAULT
}

/**
 * その顔は、**息をしているか**(ゆっくり上下する)。
 *
 * 止まっている絵は死んで見える。けれども**何かを待っている顔**
 * (`think`)は別の動きを持っているので、二重に動かさない。
 */
export const buddyBreathes = (face) => face === 'rest' || face === 'listen'

/**
 * **読み上げに伝える言葉。**
 *
 * 絵だけだと、画面を読む人には何も届かない。
 * **目に見える文字は増やさない**(`aria-label` にだけ入れる)。
 */
export const BUDDY_ALT = {
  rest: '相棒',
  listen: '相棒(一緒に聞いています)',
  think: '相棒(考えています)',
  glad: '相棒(よろこんでいます)',
  cheer: '相棒(励ましています)',
  proud: '相棒(やり切りました)',
}

export const buddyAlt = (face) => BUDDY_ALT[face] ?? BUDDY_ALT[BUDDY_DEFAULT]
