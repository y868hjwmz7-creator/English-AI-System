/**
 * ============================================================================
 * **「この英文は避けて」と渡す本数**(第5.261節)
 *
 * 2026-09-26 利用者の問い。
 *
 *   > 弱点タグで指定した時に出てくる単語や表現、決まり文句、つなぎことば、
 *   > 言い換え表現、イディオムや句動詞、コロケーションです。
 *   > これは数に限りはあるのですか？
 *
 * 調べたところ、**出てくる表現そのものに上限は無い**(AI がその場で作る)。
 * 限りがあったのは「**同じものが出ない**」の保証のほうだった。
 *
 * ── **集めた本数と、渡す本数が食い違っていた** ─────────────────
 *
 *   | どこ | 本数 |
 *   |---|---|
 *   | そのタグの教材から集める | **120 本** |
 *   | 教材を作るとき、窓口へ渡す | **40 本** ← ここで 2/3 を捨てていた |
 *   | 足りない演習を足すとき | 120 本 |
 *   | 窓口が受け取れる | 150 本 |
 *
 *   **窓口は 150 本まで受けられるのに、画面は 40 本しか送っていなかった。**
 *   しかも捨て方が「後ろから 40 本」で、**新しい順でも何でもない**
 *   (集めるところに並び順が無い)。つまり
 *   **どの 80 本が捨てられるかは、そのときの取り出し順しだい**だった。
 *
 * ── **数え方を2通り持たない**(CLAUDE.md)─────────────────────
 *
 *   同じ数が4か所に書いてあった。**1か所に持つ。**
 *   集める本数と渡す本数を同じにすれば、**捨てる段が消える。**
 *
 * ── **窓口の 150 は余白である。埋めない** ───────────────────
 *
 *   ここを 150 にすると、窓口はぴったりで受け取る ——
 *   1本でも増えた日に、**黙って切り捨てられる**(しかも画面からは見えない)。
 *   **余白を残しておけば、切り捨ては起こらない。**
 *   `npm run test:play` が「窓口の上限 ≧ ここ」を見張っている。
 *
 * ── 費用 ────────────────────────────────────────────────
 *
 *   増えるのは**入力側**で、1回あたり 80 文 ≒ 1,100 トークンほど。
 *   画面が生成のあとに出している実費(`estimateCost`)は
 *   **窓口が返した実測値**なので、ここを変えても**ひとりでに正しく出る**
 *   (見積もりを別に持っていないので、食い違いようがない)。
 * ============================================================================
 */

/**
 * **画面が窓口へ渡す英文の本数。集める本数でもある。**
 *
 * **2つを別の数にしない** —— 別にすると、集めたうちのいくつかを
 * 捨てることになり、**どれが捨てられるかを誰も決めていない**状態になる。
 */
export const AVOID_MAX = 120

/**
 * **窓口が受け取れる本数**(`supabase/functions/generate-material`)。
 *
 * **あちらの数をここに写している。** 窓口は Deno の中にいるので
 * 分け合えない(`textMix.js` の `REVIEW_MAX` とまったく同じ形)。
 * だから `npm run test:play` が**窓口のソースと突き合わせる** ——
 * 片方を変えたら赤くなる。
 */
export const AVOID_GATE = 150

/** 窓口に切り捨てられずに届くか。**余白が要る**(ぴったりにしない) */
export const avoidFits = (n = AVOID_MAX) => Number(n) < AVOID_GATE
