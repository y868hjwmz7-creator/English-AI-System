/**
 * **調べるための控えを、画面にも出すか。**
 *
 * **普段は `false`。** ずれの報告が来たら、ここを `true` にして
 * 配り直し、実機の数字を「この数字をコピー」で送ってもらう。
 * 直ったら**必ず `false` に戻す**(戻し忘れると、また羅列が居座る)。
 */
export const PROBE_ON_SCREEN = false

/** 調べるための控えか。**印は頭の `[調査中`** で、ここ1か所が決める */
export const isProbeNote = (note) => /^\[調査中/.test(String(note ?? ''))

/**
 * その知らせを、画面へ渡すか。
 *
 * **既定は「出す」側**である —— 見分けの付かないものを黙って消すと、
 * 失敗の知らせまで落ちる(**黙って落ちない**・CLAUDE.md)。
 * 落とすのは「調べるための控え」と分かっているものだけ。
 */
export const showsOnScreen = (note) => !isProbeNote(note) || PROBE_ON_SCREEN
