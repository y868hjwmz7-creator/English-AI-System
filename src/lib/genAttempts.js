/**
 * ============================================================================
 * **足りない問を、何回まで作り直すか**(第5.347節・2026-10-02 利用者の指定)
 *
 *   > 応答問題において、自分で入れたい表現を選んだ場合は、
 *   > 問題数はその2倍になるという仕様でお願いいたします。
 *   > つまり、問題数に制限はないということです。
 *
 * ── なぜ、ここが効くのか ────────────────────────────────────
 *
 *   窓口は **1回に 30 問まで**しか作らない(`generate-material` が
 *   `Math.min(…, 30)` で切っている)。足りないぶんは
 *   `generateSectionUnique` が**作り直して埋める。**
 *
 *   ところが作り直しは **5回まで**と決め打ちしてあった。
 *   30 問 × 5 回 = **150 問が天井**で、しかも重複で落ちたぶんも
 *   その5回を食う。**「上限は無い」と言いながら、黙って足りなくなる。**
 *
 * ── 決め方 ──────────────────────────────────────────────
 *
 *   **頼まれた問数から出す。** いちばん少ない呼び出しの回数
 *   (`問数 ÷ 1回あたり` を切り上げ)に、**落ちたぶんの予備を2回**足す。
 *
 *   ・**止まる条件は残す**(CLAUDE.md)。何回でも回すことはしない
 *   ・**頼まれた数に比例する。** 10 問なら 5 回、300 問なら 12 回。
 *     費用は「作る問数」で決まるので、**比例するのが筋**である
 *
 * **何も取り込んでいない**(素の node でそのまま確かめられる)。
 * ============================================================================
 */

/**
 * **窓口が1回に作る問数の上限。**
 *
 * **ここは窓口の `Math.min(…, 30)` と同じ数でなければならない。**
 * 小さすぎると呼び出しが余り、大きすぎると足りなくなる。
 * `npm run test:response` が、**窓口のコードから読み取って**突き合わせる
 * (第5.340節と同じ作法。**こちらの数を書き写して終わりにしない**)。
 */
export const GEN_PER_CALL = 30

/** 落ちたぶんのための予備。**止まる条件を残すための、小さな数** */
const SPARE = 2

/**
 * その問数を作るのに、作り直しを何回まで許すか。
 *
 * @param {number} wanted 作りたい問数
 */
export const genAttempts = (wanted) => {
  const n = Math.max(1, Number(wanted) || 0)
  return Math.max(5, Math.ceil(n / GEN_PER_CALL) + SPARE)
}
