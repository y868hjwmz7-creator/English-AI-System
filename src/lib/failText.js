/**
 * **失敗の知らせを、空にしない**(第5.295節・2026-09-28 実機)。
 *
 *   > 1、2回目はただの「作成できませんでした」だか「失敗しました」
 *   > という表示でした
 *
 * 【何が起きていたか】
 *   知らせの箱は、見出しと中身の2段でできている。
 *
 *     <strong>作れませんでした。</strong>
 *     <div>{error}</div>          ← ここが空だと、見出しだけが残る
 *
 *   `generateJob.js` は理由をこう取っていた。
 *
 *     error: e?.message ?? String(e)
 *
 *   **`??` は「空っぽの文字」を素通りさせる。**
 *   `e.message` が `''` のとき、`??` は**左が `null` でも `undefined` でもない**
 *   ので右へ行かない —— そのまま `''` が入る。
 *   利用者の画面には**「作れませんでした。」だけ**が出て、
 *   **何が起きたのか、こちらにも本人にも分からない。**
 *
 * 【0 と `null` を取り違えない、の仲間】
 *   CLAUDE.md の「**黙って消さない・黙って落ちない**」そのものである。
 *   **理由が無いなら「無い」と書く。** 見出しだけで終わらせない。
 *
 * 【ここに DOM も Supabase も置かない】
 *   **素の node で走らせられる形に切り出す**(CLAUDE.md)。
 *   `npm run test:gen` が、この関数を実際に呼んで確かめる。
 */

/**
 * 理由が1文字も返らなかったときに出す文。
 *
 * **推測を書かない。** 「通信が切れた」「時間切れ」と書きたくなるが、
 * **こちらは確かめていない**(CLAUDE.md「分かっていないことを、
 * 分かったように書かない」)。言えるのは「返ってこなかった」ことと、
 * **次にできること**だけである。
 */
export const FAIL_UNKNOWN = '理由が返ってきませんでした。'
  + 'もう一度お試しください。同じところで止まるようなら、'
  + 'この画面をそのまま見せてください。'

/** 中身の無い文字(`undefined` や `null` がそのまま文字になったものも含む) */
const 空っぽ = (t) => !t || t === 'undefined' || t === 'null' || t === '[object Object]'

/**
 * 失敗の理由を、**必ず中身のある文**にする。
 *
 * @param {unknown} e 例外・文字列・なんでも
 * @returns {string} 空にならない
 */
export function failText(e) {
  const t = String(
    typeof e === 'string' ? e : (e && typeof e === 'object' && 'message' in e ? e.message : e),
  ).trim()
  return 空っぽ(t) ? FAIL_UNKNOWN : t
}
