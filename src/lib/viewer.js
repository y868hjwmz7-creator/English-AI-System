/**
 * いま画面を見ているのは誰か。
 *
 * 【なぜ要るか】(2026-08 利用者の指定)
 *   > ゲスト側で「残高不足」と表示されるのはまずいです。
 *
 *   仕組みの内側の事情(Claude の残高、鍵の設定)は、
 *   **ゲストに見せるものではない。** ゲストにできることは何も無く、
 *   スクールの内側の話でしかない。トレーナー・管理者には、
 *   直し方まで含めて見せたい。同じ断りでも、出す言葉を変える。
 *
 * 【なぜ props で渡さないか】
 *   語の吹き出しは、画面の深いところ(EnglishText)に出る。
 *   そこまで役割を手渡しで運ぶと、途中の部品すべてに関係のない
 *   引数が増える。**役割は画面全体で1つ**なので、ここに置く。
 *
 * 役割そのものの判断は `App.jsx` が持っている。ここは覚えるだけで、
 * 判定の規則を二重に書かない(`role` の値は DB のまま: learner / trainer / owner)。
 */
let viewerRole = null

/** 画面を開いた人の役割を覚える。App が profile を読んだときに1回呼ぶ */
export function setViewerRole(role) {
  viewerRole = role ?? null
}

/**
 * 仕組みの内側の事情まで見せてよい相手か。
 *
 * **既定は「見せない」。** 役割が分からないうちは、
 * 内側の話を出さないほうが安全である。
 */
export function canSeeSystemDetail() {
  return viewerRole === 'trainer' || viewerRole === 'owner'
}
