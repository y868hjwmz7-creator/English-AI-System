/**
 * ============================================================================
 * **開いた冊が空なら、中身のある冊へ移る**(第5.200節)
 *
 * 2026-09 実機・利用者の指摘。
 *
 *   > ゲストログインして単語帳にいくと、「ビジネス必須チャンク」
 *   > 「基礎単語」「コロケーション」などが全くないので直してください。
 *   > また、ゲストログインだと単語帳とクイックレスポンス帳に
 *   > トップ画面がいまだにあります。それぞれ排除してください
 *
 * ── **2つは、同じ1つの原因だった** ──────────────────────────
 *
 *   第5.167節で「開いた瞬間に1問目」にしたとき、**例外を1つ置いた。**
 *
 *     1語も無ければ入らない。空の画面(いまの一覧)をそのまま使う
 *
 *   既定の冊は**自分の単語帳**で、**入りたてのゲストはここが 0 語**である。
 *   だから開くたびに例外へ落ち、**昔のトップ画面がそのまま出ていた。**
 *   そして冊をえらぶ場所は `冊名 ▾` の中なので、
 *   **押さないかぎりチャンク集は1つも見えない** ——
 *   利用者から見れば「**冊が全く無い**」である。
 *
 *   **ゲストが悪いのでも、冊が消えたのでもない。**
 *   測ると、`▾` の中にはちゃんと2冊とも並んでいた。
 *   **降りる場所を間違えていた**だけである。
 *
 * ── どう直すか ────────────────────────────────────────────
 *
 *   **空の冊に降ろさない。中身のある冊へ移って、そのまま始める。**
 *   そうすると
 *
 *     ・トップ画面は出ない(**排除**)
 *     ・開いた瞬間にチャンク集が目の前に出る(**全く無い、が消える**)
 *
 *   **「自分の単語帳が空のときだけ」**である。1語でも入れた人は、
 *   これまでどおり自分の単語帳から始まる。
 *
 * ── 数えられない冊へは移らない ────────────────────────────
 *
 *   **`null`(数えられなかった)を 0 とも 1 とも読まない**(CLAUDE.md
 *   「**0 と `null` を取り違えない**」)。業種べつの棚は数が**あとから**
 *   届くので、届いていなければ**移らない。**
 *   **既定は「移らない」側**にしてある —— 移った先がまた空だと、
 *   利用者から見れば**押していないのに画面が変わって、しかも空**になる。
 *
 * ── 試した冊には、二度と戻らない ──────────────────────────
 *
 *   **数えた数と、実際に出る数は別物である。**
 *   名簿は「Native Flow に 690 問ある」と言うが、その人の復習の記録が
 *   1つも無ければ、出題は 0 問になる(**実測した**)。
 *   だから**移った先がまた空になることはありうる。**
 *
 *   そこで呼ぶ側は「**もう試した冊**」を控えておき、ここへ渡す。
 *   空だった冊は次から飛ばされるので、
 *
 *     ・**同じ冊を行ったり来たりしない**(止まる条件・CLAUDE.md「費用」)
 *     ・**移る回数は、多くても冊の数まで**
 *     ・どれも空なら、これまでどおり一覧の画面に残す
 *       (**行き止まりを作らない**)
 *
 *   **「1回だけ」では足りなかった。** 1回で止めると、
 *   たまたま最初に当たった冊が空だったときに、
 *   **中身のある冊が後ろに控えているのに、空の画面で終わる。**
 *
 * ── Supabase を引き連れない ──────────────────────────────
 *
 *   ここは**並びを1つ選ぶだけ**で、`import.meta.env` が付いてこない。
 *   だから**素の node で走らせられる**
 *   (CLAUDE.md「素の node で走らせられる形に切り出す」)。
 * ============================================================================
 */

/**
 * **いまの冊が空のとき、代わりに開く冊。**
 *
 * **並びのまま、上から探す。** 並べ替えない —— 冊の並びは
 * 画面が決めており(`books`)、**ここで良し悪しを決めない。**
 *
 * @param {Array<{id: string}>} books 冊の一覧(画面が持っているもの)
 * @param {string} now  いま開いている冊の id
 * @param {(id: string) => (number|null|undefined)} sizeOf
 *        冊の id → 中身の数。**数えられない冊は `null`**
 *        (**0 を返さない** —— 0 は「数えたら空だった」の意味である)
 * @param {{has?: (id: string) => boolean}} tried
 *        **もう試した冊**(`Set`)。空だった冊が入っている。
 *        渡さなければ、何も飛ばさない
 * @returns {string|null} 代わりに開く冊の id。無ければ `null`
 */
export function nextFilledBook(books, now, sizeOf, tried = null) {
  for (const b of books ?? []) {
    if (!b || b.id === now) continue
    /* **空だった冊へは、二度と行かない。** 行くと、2冊のあいだを
       行ったり来たりして**画面が止まらない** */
    if (tried?.has?.(b.id)) continue
    const n = sizeOf?.(b.id)
    /* **数でないものは、そこに何かある証拠にならない。**
       `null` も `undefined` も文字列も、ぜんぶ「分からない」側に置く */
    if (typeof n === 'number' && n > 0) return b.id
  }
  return null
}
