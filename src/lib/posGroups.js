/**
 * 品詞のまとめ方 — **単語帳の絞り込みで使う**(2026-09 利用者の指定)。
 *
 * ============================================================================
 * 【なぜ要るか】
 *
 *   > 全ての単語に対して効くようにして欲しいのが
 *   > 品詞ごとに分ける絞り込み機能です。
 *
 *   「動詞だけをさらいたい」「前置詞が苦手だから、そこだけ」は、
 *   単語帳が育つほど効いてくる絞り方である。
 *
 * 【難しいのは、品詞の言葉が**2通りある**こと】
 *
 *   | どこから来る語 | `pos` に入っている文字 |
 *   |---|---|
 *   | 教材・手入力(`lookup-word` が引いた控え) | **日本語1語**(「名詞」「動詞」…) |
 *   | 基礎単語(`basicWords.js`) | **短い印**(`n` / `v` / `adj` …) |
 *
 *   窓口の指示は「品詞(日本語で1語)」なので、**閉じた一覧ではない。**
 *   「句動詞」「イディオム」「助動詞」など、こちらが決めていない言葉も来る。
 *
 *   だから**そろえ方をここ1か所に置く。**
 *   画面で `pos === '名詞'` と書くと、基礎単語(`n`)で必ず抜ける
 *   (`kind === 'dialogue'` と書いて会議で抜けたのと、まったく同じ落とし穴)。
 *
 * 【何にも依存しない形にしてある】
 *   `playMark.js` と同じ考え方。`npm run test:play` が素の node で確かめる。
 */

/**
 * 絞り込みに出す品詞。**閉じた一覧**である。
 *
 * 【なぜこの9つか】
 *   基礎単語 1,200 語の中身で数えると、名詞 410 / 動詞 390 /
 *   形容詞 162 / 副詞 108 / 代名詞 35 / 前置詞 35 / 冠詞など 25 /
 *   数 19 / 接続詞 13 / 熟語 3 だった。
 *   **どれも「そこだけ練習したい」と言える塊**なので、まとめずに並べる。
 *
 * 【`その他` を作らない】
 *   知らない言葉が来たら **`''`(分からない)** を返し、
 *   その語は品詞では絞れない。**当てずっぽうで「その他」に入れない** ——
 *   入れると「その他」を選んだ人に、名詞と助動詞が混ざって出る。
 *
 * @property id    絞り込みの値。**変えない**(覚えている値ではないが、
 *                 検証と画面の両方が使う)
 * @property label 画面に出す名前
 * @property words そろえる前の言葉。**日本語と短い印の両方**を並べる
 */
export const POS_GROUPS = [
  { id: 'noun', label: '名詞', words: ['n', 'noun', '名詞'] },
  {
    id: 'verb',
    label: '動詞',
    // **助動詞もここへ入れる。** 数が少なく(be / can / will)、
    // 「動詞だけ」を選んだ人が can を外したいとは考えにくい
    words: ['v', 'verb', '動詞', '自動詞', '他動詞', '助動詞', 'aux'],
  },
  { id: 'adj', label: '形容詞', words: ['adj', 'adjective', '形容詞'] },
  { id: 'adv', label: '副詞', words: ['adv', 'adverb', '副詞'] },
  { id: 'prep', label: '前置詞', words: ['prep', 'preposition', '前置詞'] },
  { id: 'conj', label: '接続詞', words: ['conj', 'conjunction', '接続詞'] },
  { id: 'pron', label: '代名詞', words: ['pron', 'pronoun', '代名詞'] },
  {
    id: 'det',
    label: '冠詞・数',
    words: ['det', 'determiner', 'num', 'number', 'article',
      '冠詞', '限定詞', '数詞', '数'],
  },
  {
    id: 'interj',
    label: '間投詞',
    // **基礎単語には1語も無い**が、窓口は `Wow` `Oh` にこれを返す。
    // 出す値が1つも無ければ選択肢に出ない(効かない操作を見せない)
    words: ['int', 'interj', 'interjection', '間投詞', '感嘆詞'],
  },
  {
    id: 'phrase',
    label: '熟語・言い回し',
    // **`phr` は基礎単語の印。** ほかは窓口が返してくる日本語である
    words: ['phr', 'phrase', '熟語', '成句', '慣用句', 'イディオム',
      '句動詞', '言い回し', 'フレーズ'],
  },
]

/** そろえる。**前後の空白と大文字小文字、末尾の「。」を落とすだけ** */
const norm = (pos) => String(pos ?? '').trim().toLowerCase().replace(/[.。]+$/, '')

/** 言葉 → まとまり の対応表。**画面で作り直さない** */
const BY_WORD = new Map()
for (const g of POS_GROUPS) for (const w of g.words) BY_WORD.set(w, g.id)

/**
 * その `pos` は、どのまとまりか。
 *
 * **知らない言葉なら空**(`''`)。当てずっぽうで振り分けない ——
 * 「動詞」を選んだ人に、知らない品詞の語が混ざるほうが害が大きい
 * (`abbrevAt` で「見落としは長い1文になるだけだが、取り違えは
 *  文をつなげてしまう」と書いたのと同じ考え方)。
 *
 * @param pos `word_reviews` / `basicWords.js` の品詞
 * @returns {string} `POS_GROUPS` の id、または `''`
 */
export function posGroupOf(pos) {
  const s = norm(pos)
  if (!s) return ''
  const hit = BY_WORD.get(s)
  if (hit) return hit
  /* **「名詞・動詞」のように2つ書いてあることがある**(窓口は
     「日本語で1語」と指示しているが、守られるとは限らない)。
     区切りで割って、**最初に当たったもの**を採る */
  for (const part of s.split(/[・,、\/|]+/)) {
    const one = BY_WORD.get(part.trim())
    if (one) return one
  }
  return ''
}

/** 画面に出す名前。**知らないものは空**(対応表を画面に書き写さない) */
export const posLabel = (id) => POS_GROUPS.find((g) => g.id === id)?.label ?? ''
