/**
 * **聞き流しのボタンの文字**(第5.445節・③・2026-10-10)。
 *
 * ============================================================================
 * 【なぜ1か所に置くか】
 *
 *   同じ言葉が**4か所**に出る ——
 *   単語帳の上の帯 / 単語帳の一覧の下 / Quick Response の復習の上の帯 /
 *   教材の中の Quick Response の上の帯。
 *   **書き写すと、必ずどこかだけ古くなる**(CLAUDE.md)。
 *
 *   `speakLabel.js`(1文ずつの「聴く」)・`wholePlay.js`(全体を聴く)と
 *   **まったく同じ作法**である。
 *
 * 【「とめる」とセットで持つ】
 *
 *   押すと流れ始め、もう一度押すと止まる。**同じボタンの表と裏**なので、
 *   **同じ1か所**に置く。
 *
 *   ★ **幅は、2つのうち広いぶんを先に取っておく**(共通ルール
 *   「押しても、まわりの物が動かない」)。「聞き流し」(4文字)が
 *   「とめる」(3文字)に縮むと、**帯に並んでいるものが動く** ——
 *   取っておく言葉も、出す言葉も、**この一覧から**組む
 *   (`RADIO_WORDS` を `SteadyLabel` に渡す)。
 *
 * 【ここに DOM を置かない】
 *
 *   **素の node で走らせられる形に切り出す**(CLAUDE.md)。
 *   見張りの側も**ここから読む** —— `'聞き流し'` と書き写さない。
 */

/** 流し始める(流れていないときの文字) */
export const RADIO_LISTEN = '聞き流し'

/** 止める(流れているあいだの文字) */
export const RADIO_STOP = 'とめる'

/**
 * **起こりうる言葉のぜんぶ。** 場所を取っておくのに使う。
 * **呼ぶ側が2つを並べ直さない** —— 言葉を1つ足した日も、ここだけで済む。
 */
export const RADIO_WORDS = [RADIO_LISTEN, RADIO_STOP]

/**
 * **Quick Response の前置き**(2026-09)。
 *
 * あちらの聞き流しは**聞き流しだけの場所ではない** —— 読み方に
 * 「日本語 → 英語」(言う練習)があり、そちらで入る人もいる。
 * **言葉と中身を食い違わせない**ために前に付ける。
 * **単語帳には付けない**(あちらは「英語だけ」1つきりである)。
 */
export const RADIO_SAY_LEAD = '言う練習・'

/**
 * **数まで出すぶん**(一覧の下に置く、幅に余裕のあるボタン)。
 *
 * **数は書き写さない** —— 呼ぶ側が数えたものを、そのまま入れる。
 * `lead` は前置き(Quick Response だけ `RADIO_SAY_LEAD` を渡す)。
 */
export const radioCountLabel = (n, unit = '語', lead = '') => (
  `${lead}${RADIO_LISTEN}(${n} ${unit})`
)
