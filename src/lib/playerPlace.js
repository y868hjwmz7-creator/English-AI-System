/**
 * 読み上げの操作盤を、どこに置くか。**判断はここ1か所**(2026-09 利用者の指定)。
 *
 * ============================================================================
 * 【なぜ「画面の下の黒帯」を足したか】
 *
 *   > スマホの再生プレーヤーがダサいですね。。。いっそのこと画面の下部に
 *   > 黒帯にした中に固定にした方がスタイリッシュな気がします。
 *   > パッドでもデフォルトは同じ仕様で、任意でフロート型にして移動できる
 *   > ように。PCの画面でもフロートにした時は端っこにドラッグできる部分を
 *   > 作って移動させれるようにしたいです
 *
 *   これまで狭い画面では**右下に浮く錠剤**だった。押すものが増えるたびに
 *   `useFitRow` で言葉を削って収めており、**削るほど何のボタンか
 *   分からなくなる**ところまで来ていた。
 *   横いっぱいの帯にすれば、削る理由がそもそも無くなる。
 *
 * ============================================================================
 * 【置き場所は3つ】
 *
 *   | id | どこ | いつ向くか |
 *   |---|---|---|
 *   | `bar`   | 上の帯の中 | 画面共有。相手にも見える。**広い窓だけ** |
 *   | `dock`  | **画面の下の黒帯** | スマホ・パッドの既定。親指が届く |
 *   | `float` | 浮かせる。**つまんで動かせる** | 紙の見たいところを空けたいとき |
 *
 * 【`bar` は広い窓にしか置けない】
 *   上の帯は 1380px より狭いと1行に収まらない(`fitsInBar`・実測)。
 *   だから狭い窓では **`dock` か `float` のどちらか**にする。
 *   覚えている値が `bar` でも、狭い窓では `dock` として扱う ——
 *   **行き止まりを作らない**(戻す道が無くなる)。
 */

/** 覚えてよい値。**これ以外は既定に落とす** */
export const PLACES = ['bar', 'dock', 'float']

/** 画面に出す名前。**1か所に置く** */
export const PLACE_LABEL = {
  bar: '上の帯',
  dock: '画面の下',
  float: '浮かせる',
}

/**
 * 切り替えのボタンに出す言葉。**行き先を、そのまま文にする。**
 * 「浮かせるに出す」のような読みにくい継ぎ足しにしない
 * (名前を組み合わせて文を作らない・実測して気づいた)。
 */
export const PLACE_TO = {
  bar: '上の帯に入れる',
  dock: '画面の下に出す',
  float: '浮かせて動かす',
}

/**
 * いま実際にどこへ出すか。
 *
 * @param saved      覚えている値
 * @param fitsInBar  上の帯に入る広さか(1380px 以上)
 */
export function placeFor(saved, fitsInBar) {
  const v = PLACES.includes(saved) ? saved : 'bar'
  if (fitsInBar) return v
  // 狭い窓に「上の帯」は無い。**既定は画面の下**(利用者の指定)
  return v === 'float' ? 'float' : 'dock'
}

/**
 * 次の置き場所(切り替えのボタンは1つ。押すたびに移る)。
 *
 * **4つ並べない。** めったに触らないものが帯の場所を食う
 * (`Stepper` を作ったときと同じ話)。多くても3回で戻る。
 */
export function nextPlace(place, fitsInBar) {
  const now = placeFor(place, fitsInBar)
  if (!fitsInBar) return now === 'dock' ? 'float' : 'dock'
  if (now === 'bar') return 'dock'
  if (now === 'dock') return 'float'
  return 'bar'
}
