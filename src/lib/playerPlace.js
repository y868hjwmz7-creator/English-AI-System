/**
 * 読み上げの操作盤を、どこに置くか。**判断はここ1か所**(2026-09 利用者の指定)。
 *
 * ============================================================================
 * 【なぜ「画面の下の黒帯」を足したか】
 *
 *   > スマホの再生プレーヤーがダサいですね。。。いっそのこと画面の下部に
 *   > 黒帯にした中に固定にした方がスタイリッシュな気がします。
 *   > パッドでもデフォルトは同じ仕様で、任意でフロート型に
 *
 *   これまで狭い画面では**右下に浮く錠剤**だった。押すものが増えるたびに
 *   `useFitRow` で言葉を削って収めており、**削るほど何のボタンか
 *   分からなくなる**ところまで来ていた。
 *   横いっぱいの帯にすれば、削る理由がそもそも無くなる。
 *
 * ============================================================================
 * 【置き場所は2つ】(**浮かせるは廃止した**・第5.311節)
 *
 *   | id | どこ | いつ向くか |
 *   |---|---|---|
 *   | `bar`   | 上の帯の中 | 画面共有。相手にも見える。**広い窓だけ** |
 *   | `dock`  | **画面の下の黒帯** | それ以外ぜんぶ。親指が届く |
 *
 * 【`bar` は広い窓にしか置けない】
 *   上の帯は 1380px より狭いと1行に収まらない(`fitsInBar`・実測)。
 *   だから狭い窓では **`dock`**。覚えている値が `bar` でも、
 *   狭い窓では `dock` として扱う —— **行き止まりを作らない**。
 *
 * ============================================================================
 * 【**浮かせるのは廃止した**】(2026-09-29 利用者の指定・第5.311節)
 *
 *   > そして浮くプレーヤーは廃止で。結局今まで使ったことがないです。
 *
 *   下の「スマホには出さない」の経緯は**残してある** —— そこで学んだこと
 *   (行き止まりを作らない・効かない操作を見せない)は、いまも効いている。
 *   **使われないものを、作りだけ残さない。** 浮かせるのをやめたことで
 *   つまんで動かす仕組み(`dragBox`)・元の場所へ戻す ⌖・
 *   `.player--float` の見た目が、まとめて要らなくなった。
 */

/** 覚えてよい値。**これ以外は既定に落とす** */
export const PLACES = ['bar', 'dock']

/** 画面に出す名前。**1か所に置く** */
export const PLACE_LABEL = {
  bar: '上の帯',
  dock: '画面の下',
}

/**
 * 切り替えのボタンに出す言葉。**行き先を、そのまま文にする。**
 * 「浮かせるに出す」のような読みにくい継ぎ足しにしない
 * (名前を組み合わせて文を作らない・実測して気づいた)。
 */
export const PLACE_TO = {
  bar: '上の帯に入れる',
  dock: '画面の下に出す',
}

/**
 * 【スマホには「浮かせる」を出さない】(2026-09 実機・利用者の指定)
 *
 *   > フロートさせると下に変な隙間ができる、しかも戻せない。
 *   > フロートさせると機能を無くしてくださいと先ほど頼みませんでしたか?
 *
 * **一度読み違えている。経緯ごと残す。**
 *
 *   > 移動式のプレーヤーは、PCやパッドでは残しましょう。
 *   > スマホでは狭すぎて意味がありません。
 *
 * これを「**つまんで動かす**のをスマホでやめる」と読み、`dragBox` の
 * つまみだけを外した。ところが利用者が言っていたのは
 * **浮かせること自体**である。「狭すぎて意味がない」のは、
 * つまみではなく**浮いた錠剤そのもの**だった。実際こうなっていた。
 *
 *   ・押すものが画面の幅に入りきらず、**置き場所のボタンが画面の外**へ出る
 *     → **黒帯へ戻す道が無くなる**(行き止まり)
 *   ・浮いた錠剤の下に、黒帯のぶんの余白だけが残って**変な隙間**になる
 *
 * だから**スマホでは `float` を持たせない。** そうすれば
 * `nextPlace()` が `null` を返し、**切り替えのボタンごと出なくなる**
 * (効かない操作を見せない)。行き止まりも隙間も、根から消える。
 */

/**
 * いま実際にどこへ出すか。
 *
 * @param saved      覚えている値
 * @param fitsInBar  上の帯に入る広さか(1380px 以上)
 * @param padUp      パッド以上か(768px 以上)。**スマホは黒帯だけ**
 */
export function placeFor(saved, fitsInBar, padUp = true) {
  const v = PLACES.includes(saved) ? saved : 'bar'
  if (fitsInBar) return v
  /* 狭い窓に「上の帯」は無い。**画面の下だけ**(浮かせるは廃止・第5.311節)。
     `padUp` は受け取るが、もう答えを変えない —— **呼ぶ側を1つも
     書き換えずに済ませる**ため、口だけ残してある */
  return 'dock'
}

/**
 * 次の置き場所(切り替えのボタンは1つ。押すたびに移る)。
 *
 * **4つ並べない。** めったに触らないものが帯の場所を食う
 * (`Stepper` を作ったときと同じ話)。多くても3回で戻る。
 *
 * **行き先が無ければ `null`。** スマホは黒帯しか無いので、
 * 呼ぶ側はこれを見て**ボタンごと出さない**(`PlayerBar`)。
 */
export function nextPlace(place, fitsInBar, padUp = true) {
  const now = placeFor(place, fitsInBar, padUp)
  // 狭い窓は黒帯だけ。**移す先が無いので `null`** —— 呼ぶ側は
  // これを見てボタンごと出さない(効かない操作を見せない)
  if (!fitsInBar) return null
  return now === 'bar' ? 'dock' : 'bar'
}
