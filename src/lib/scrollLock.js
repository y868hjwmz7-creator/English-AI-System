/**
 * ============================================================================
 * うしろの画面を送れなくする鍵。**数える。1か所に置く**
 * ============================================================================
 *
 * 【なぜ要るか】(2026-09 実機・利用者の指摘)
 *
 *   > スクロールを始めるとサイドバーのハンバーガーが触れなくなる
 *
 * 画面ぜんぶを覆うものが4つある(かぶせて開くメニュー・レッスン表示・
 * 集中モード・単語帳の集中モード)。どれも「うしろを送れなくする」ために
 * `document.body.style.overflow = 'hidden'` を置くのだが、
 * **4か所がそれぞれ勝手に前の値を控えて、勝手に戻していた。**
 *
 *     単語帳の復習を開く    … 控え = ''        → hidden
 *     ☰ でメニューを開く    … 控え = 'hidden'  → hidden
 *     メニューから別の画面へ … 単語帳が '' に戻し、そのあと
 *                            メニューが **'hidden' を書き戻す**
 *
 * **`body` が hidden のまま取り残される。** しかもこれは
 * 「ページからページへ移る」というふつうの操作で起きる。
 *
 * 【何が壊れるか】**実測(Chromium・4つの幅すべて)**
 *
 *   | | 帯の上端 | ☰ は押せるか |
 *   |---|---|---|
 *   | ふつう | 8px(貼り付く) | **押せる** |
 *   | hidden が残ったとき | **−592px**(画面の外へ流れ出る) | **押せない** |
 *
 * `overflow: hidden` は箱を「送れる箱」に変えるので、
 * **`position: sticky` が効かなくなる**(CLAUDE.md に書いてあるとおり)。
 * 上の帯が貼り付かなくなり、送るほど ☰ が遠ざかる。
 * **端末によらない**(利用者の実機でも iPhone・iPad・パソコンの3つとも)。
 *
 * 【直し方】**控えを1つにして、数える**
 *
 *   ・最初の1つが掛けたときだけ、前の値を控える
 *   ・最後の1つが外したときだけ、その値へ戻す
 *   ・**外す順は問わない。** 入れ子でも、逆順でも、同じところへ戻る
 *   ・二度外しても壊れない(`done` で1回に絞る)
 *
 * **画面ごとに `body` を触らない。** ここだけを呼ぶこと。
 * `npm run test:bar` が「自前で触っている場所が無いか」を見張り、
 * `npm run test:play` が**入れ子と逆順**を数字で確かめる。
 *
 * 何にも依存しない形にしてある(`playMark.js` / `mp3Join.js` と同じ考え方)。
 * だから**素の node で走らせられる。**
 */

let depth = 0
let saved = ''

/**
 * 送れなくする。**返ってきた関数を呼ぶと外れる。**
 * `useEffect` の戻り値にそのまま渡せる形にしてある。
 *
 * @param {Document} [doc] 検証のために差し替えられるようにしてある
 * @returns {() => void} 外す関数
 */
export function lockScroll(doc = globalThis.document) {
  const body = doc?.body
  if (!body) return () => {}
  // **最初の1つだけが控える。** 2つめ以降が控えると、
  // そこにはもう 'hidden' が入っている(それが取り残しの正体)
  if (depth === 0) saved = body.style.overflow
  depth += 1
  body.style.overflow = 'hidden'

  let done = false
  return () => {
    if (done) return          // 二度外しても数がずれない
    done = true
    depth -= 1
    if (depth > 0) return     // まだ誰かが掛けている
    depth = 0
    body.style.overflow = saved
    saved = ''
  }
}

/** いま何枚掛かっているか。**検証のためだけに出している** */
export function lockDepth() {
  return depth
}
