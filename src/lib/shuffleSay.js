export const SHUFFLE_LABEL = 'シャッフル'

/** いまの状態の呼び名(する / しない) */
export const shuffleState = (on) => (on ? 'する' : 'しない')

/** 読み上げとマウスを乗せたときに出る1文 */
export const shuffleSay = (on) =>
  `${SHUFFLE_LABEL}。いまは ${shuffleState(on)}`
  + `。押すと ${shuffleState(!on)} になります`
