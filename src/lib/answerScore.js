import { spokenRatio } from './transcriptDiff.js'

/**
 * **8割**。ここを境に「できた」とする。
 *
 * **満点にしない。** 聞き取れなかった語が1つあっただけで「まだ」の音が鳴ると、
 * ほとんどの回が「まだ」になる —— **責めない**(CLAUDE.md「まだを責めない」)。
 * **低くもしない。** 半分で「できた」が鳴ると、合図として意味を持たない。
 */
export const ANSWER_OK_RATIO = 0.8

/**
 * 割合から「できたか」を決める。
 * **数でないものは、いつも「まだ」**(0 と `null` を取り違えない・CLAUDE.md)。
 */
export function answerOkOfRatio(ratio) {
  return Number.isFinite(ratio) && ratio >= ANSWER_OK_RATIO
}

/**
 * 照らし合わせの結果から「できたか」を決める。**画面はこれだけを呼ぶ。**
 * @param {Array<{word: string, state: 'ok'|'missed'|'extra'}>} diff
 */
export function answerOkOf(diff) {
  if (!Array.isArray(diff) || !diff.length) return false
  return answerOkOfRatio(spokenRatio(diff))
}
