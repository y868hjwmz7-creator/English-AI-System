/**
 * **いまどのカードが出ているか、を控えで持つ**(第5.445節・②・2026-10-11)。
 *
 * ============================================================================
 * 【なぜ控えが要るのか】
 *
 *   聞き流しは**画面を消しても鳴り続ける**(第5.285節)。間を時計では
 *   なく無音の音で置いてあるので、音の側から合図が来る。
 *
 *   ところが**画面を消すと、React は描き直さない。**
 *   「次へ送る」を `setState` だけで書くと、
 *
 *       鳴り終わった → setAt(i + 1) → 次に鳴らす行を `at` から読む
 *                                      ↑ **まだ前の値**
 *
 *   で、**同じ行を何度も鳴らし続ける。** 2026-09 に実機で踏んでいる
 *   (「一つの単語が4回読み上げられたり…画面に表示されている単語と
 *   メチャクチャにズレてしまってます」)。そのとき `WordRadio` は
 *   **控え(`atRef`)を本体にして**直した。
 *
 *   **その控えを、練習の3画面にも持たせる。**
 *   ただし送り方が2通りある ——
 *
 *   | 画面 | いま出ているもの | 送り方 |
 *   |---|---|---|
 *   | 単語帳 | `queue[0]` | **並びを回す**(先頭を末尾へ) |
 *   | Quick Response の復習 / 教材の中 | `run[at]` | **番号を1つ進める** |
 *
 *   **その2通りを、ここ1か所に持つ。** 画面の中で `[...q.slice(1), q[0]]` や
 *   `(i + 1) % n` と書かない —— **置く場所の数だけ食い違う**(CLAUDE.md)。
 *
 * ============================================================================
 * 【何にも依存しない】
 *
 *   `window` も React も Supabase も触らないので、
 *   **`npm run test:play` が素の node で測れる**
 *   (`playMark.js` / `learnStage.js` / `cardMove.js` と同じ作法)。
 *
 *   **測れない場所に置くと、見張りが1本も書けない** ——
 *   応答問題の問数がきっちり半分になっていたのに気づけなかったのは、
 *   落とす算段が画面の中にあったからである(第5.345節)。
 *
 * ============================================================================
 * 【約束】(どちらの形も同じ)
 *
 *   - `now()`  … いま出ている行。無ければ `null`
 *   - `peek()` … 次に出る行(**温めるためだけ**)。1枚しか無ければそれ自身
 *   - `go()`   … 次へ送って、**送った先の行をその場で返す**
 *   - `back()` … 前へ戻して、戻った先の行をその場で返す
 *
 *   **`go()` / `back()` は、返す前に控えを書き替える。**
 *   だから**描き直しを待たずに**次の行が分かる —— これが、この仕組みの
 *   ぜんぶである。
 *
 *   **1枚しか無いときは動かさない**(効かない操作をしない・CLAUDE.md)。
 *   そのときも**その1枚を返す** —— 聞き流しは、同じものをもう一度鳴らす。
 */

/** 番号を、一覧の中へ回り込ませる。**端で止めない**(行き止まりを作らない) */
const wrap = (i, n) => ((i % n) + n) % n

/**
 * **並びを回す形**(単語帳)。いま出ているのは、いつも先頭である。
 *
 * @param {object} o
 * @param {function} o.get 控えの一覧を返す(`() => queueRef.current`)
 * @param {function} o.set 控えと画面を**一緒に**書き替える(`putQueue`)
 */
export function rotateCursor({ get, set }) {
  const 一覧 = () => (Array.isArray(get()) ? get() : [])
  const 回す = (次) => {
    const l = 一覧()
    /* **1枚しか無ければ動かさない。** それでも、その1枚を返す */
    if (l.length < 2) return l[0] ?? null
    /* **1度だけ組む。** 2度呼ぶと、渡したものと返すものが別の配列になる */
    const n = 次(l)
    set(n)
    return n[0] ?? null
  }
  return {
    now: () => 一覧()[0] ?? null,
    peek: () => {
      const l = 一覧()
      return (l.length > 1 ? l[1] : l[0]) ?? null
    },
    go: () => 回す((l) => [...l.slice(1), l[0]]),
    back: () => 回す((l) => [l[l.length - 1], ...l.slice(0, -1)]),
  }
}

/**
 * **番号を進める形**(Quick Response の復習 / 教材の中)。
 *
 * @param {object} o
 * @param {function} o.list 控えの一覧を返す
 * @param {function} o.at   控えの番号を返す(`() => atRef.current`)
 * @param {function} o.set  控えと画面を**一緒に**書き替える(`putAt`)
 */
export function indexCursor({ list, at, set }) {
  const 一覧 = () => (Array.isArray(list()) ? list() : [])
  const 番号 = () => {
    const l = 一覧()
    return l.length ? wrap(Number(at()) || 0, l.length) : 0
  }
  const 送る = (d) => {
    const l = 一覧()
    if (l.length < 2) return l[番号()] ?? null
    const i = wrap(番号() + d, l.length)
    set(i)
    return l[i] ?? null
  }
  return {
    now: () => 一覧()[番号()] ?? null,
    peek: () => {
      const l = 一覧()
      if (!l.length) return null
      return l[wrap(番号() + 1, l.length)] ?? null
    },
    go: () => 送る(1),
    back: () => 送る(-1),
  }
}
