/**
 * ============================================================================
 * **ほかのアプリの音を、こちらが止めるかどうか**(第5.351節・2026-10-03 利用者の指定)
 *
 *   > このアプリを立ち上げたときにSpotifyなどで聞いている音楽が
 *   > 消えないように出来ないですか
 *
 * ── なぜ消えていたか(**測って分かったこと**)────────────────
 *
 *   **立ち上げただけでは消えない。画面を1回触った瞬間に消えていた。**
 *   iPhone は「利用者が触った流れの中で始めた音」しか鳴らさないので、
 *   **最初の `pointerdown` で先に解錠しておく**仕掛けが2つある。
 *
 *     | どこ | 何をしていたか |
 *     |---|---|
 *     | `audioClips.js` の `prime()` | **0.05 秒の無音を `<audio>` で鳴らす** |
 *     | `sfx.js` の `unlockSfx()` | **`AudioContext` を起こす**(`resume`) |
 *
 *   どちらも**音を1つも出していない**が、iPhone から見れば
 *   「このページが音を鳴らし始めた」ことになる。既定の扱い(`auto`)は
 *   **ほかのアプリの再生を止める側**なので、そこで Spotify が止まる。
 *
 *   **どちらも消せない。** 消すと「押してから探しても間に合わない」に戻り、
 *   Listen が鳴らなくなる(`audioClips.js` にその経緯が書いてある)。
 *
 * ── 直し方 —— **音の種類を宣言する**(Audio Session API)────────
 *
 *   `navigator.audioSession.type` に、このページが出す音の種類を宣言できる。
 *   W3C の下書きで、**いま実装しているのは Safari だけ**(iOS 16.4 以降)。
 *   利用者の iPhone は iOS 18 なので効く。**ほかの端末では何も起きない**
 *   (パソコンのブラウザは、もともと Spotify を止めない)。
 *
 *     | 種類 | ほかのアプリの音 |
 *     |---|---|
 *     | `ambient` | **混ざる。止めない** |
 *     | `auto`(既定) | ブラウザが中身で決める。再生なら**止める側**になる |
 *     | `playback` / `play-and-record` / `transient-solo` | **止める** |
 *
 *   だから**ふだんは `ambient`、本当に鳴らす直前だけ `auto`** にする。
 *
 *     起動 → `ambient`         … 触っても、押しても、Spotify は消えない
 *     Listen を押す → `auto`   … **いまと1ミリも変わらない**(画面を消しても鳴り続ける)
 *
 *   **`playback` を名指ししない。** `auto` はブラウザの既定そのもの ——
 *   つまり**今日の振る舞いに戻すだけ**である。名指しすると、
 *   録音や端末の声のときに**こちらが選んだ種類のほうが邪魔になる**。
 *
 * ── 気をつけること ───────────────────────────────────────
 *
 *   **`ambient` の音は、iPhone の消音スイッチで黙る。**
 *   だから**ボタンの「ポン」は消音中に鳴らなくなる**(そのほうが筋も通る)。
 *   **教材の音声はここに入らない** —— 鳴らす直前に `auto` へ戻すためである。
 *
 *   **鳴り終わっても `ambient` に戻していない。** 戻す道を増やすと、
 *   聞き流しの途中で種類が行き来する。**1回押したらこちらの音が主**で、
 *   そこは利用者が選んだことである。
 *
 * ── 何も取り込まない ────────────────────────────────────
 *
 *   `navigator` しか触らないので、**素の node でそのまま確かめられる**
 *   (`playMark.js` / `silentWav` と同じ作法)。
 * ============================================================================
 */

/** ほかのアプリの音と**混ざる**種類。止めないし、小さくもしない */
export const MIX_TYPE = 'ambient'

/* ══════════════════════════════════════════════════════════════════
   ★ **「小さくする」(`transient`)は、廃止した**(第5.356節 → 第5.362節)

   第5.356節で**仕様を読んで**足したものである。W3C の説明書は
   `transient`(通知音のような一時的な音)について
   「ほかの音の上に重ねて鳴り、**小さくすることもある(maybe)**」と書いてある。
   **「必ず小さくする」とは、どこにも書いていなかった。**

   2026-10-03、利用者に**実機で6つとも試してもらった。**

     > 音楽アプリの音量を小さくする機能が効いていません
     > transient と ambient以外は音楽が止まりました。

   つまり iOS Safari では、

     | 宣言 | ほかのアプリの音楽 |
     |---|---|
     | `transient` | **止まらない。小さくもならない** |
     | `ambient`   | **止まらない。小さくもならない** |
     | ほかの4つ   | 止まる |

   **`transient` は `ambient` とまったく同じ振る舞いだった。**
   同じことをするものを2つ見せない(CLAUDE.md)ので、**1つ消した。**

   **「仕様にそう書いてある」で足してはいけなかった。**
   実装は Safari だけで、そこがどう振る舞うかは**測るまで分からない。**
   (`public/mic-test.html` の「ほかのアプリの音」が、その測り方である)

   **音量は、別の道で上げた**(第5.362節)—— MP3 の `global_gain` を
   置くときに書き換える(`supabase/functions/speak/index.ts`)。
   あちらは `volume` を使わないので **iPhone でも効く。**
   ══════════════════════════════════════════════════════════════════ */

/**
 * **ブラウザに任せる**種類(既定)。
 * これを入れると、**いまの振る舞いとまったく同じ**になる。
 */
export const OWN_TYPE = 'auto'

/** この端末が宣言を受け付けるか。**名前(UA)で見分けない** */
const sessionOf = () => {
  try {
    if (typeof navigator === 'undefined') return null
    return navigator.audioSession ?? null
  } catch { return null }
}

/**
 * ★ **どれを取るかは、利用者が決める**(第5.352 / 5.356節・2026-10-03 利用者の指定)。
 *
 *   > アプリの英語の音声を聴くと音楽が消えてしまいます。
 *   > 音楽アプリの音量が大きくバランスが悪いです。
 *
 * **iPhone では、全部は両立しない。**
 * iOS のアプリが使える「主になりつつ混ぜる」(`mixWithOthers`)は、
 * **Web ページには公開されていない** —— 宣言できるのは種類1つだけである。
 *
 *   | 宣言 | ほかのアプリの音楽 | 画面を消したとき | 消音スイッチ |
 *   |---|---|---|---|
 *   | `auto` | 止まる | **鳴り続ける** | 鳴る |
 *   | `ambient` | **そのまま**(実機で確認) | 止まる | 鳴らない |
 *
 * **小さくする道は無い**(第5.362節で実機で確かめた)。
 * 音量は、置くときに MP3 そのものを大きくして上げてある。
 *
 * だから**設定で切り替える**(利用者の選択)。
 * **既定は「止める」** —— 消音スイッチの入った iPhone で
 * **英語の音声そのものが鳴らない**という事故を、既定では起こさない。
 */
const KEY = 'eas.mixAudio'

/**
 * ★ **選べる3つ**(第5.356節)。**一覧も、呼び名も、宣言する種類も、ここ1か所。**
 *
 * 画面は `MIX_MODES` を並べるだけで、`'ambient'` とも `'止める'` とも書かない
 * (CLAUDE.md「呼び名を2か所に書かない」)。
 *
 * **並びは「止める → そのまま」** —— ほかのアプリの音が**残る度合いの順**である。
 */
export const MIX_MODES = [
  { id: 'off', label: '止める', type: OWN_TYPE,
    hint: '音楽は止まります。画面を消しても英語は鳴り続けます' },
  /* ★ **引きかえに失うものを、そのまま書く**(第5.416節・2026-10-07)。
       ここには「音楽の大きさは変わりません」だけが書いてあった。
       **`ambient` は、画面を消すと止まり、消音スイッチでも鳴らない**
       (すぐ上の表。実機で確かめてある)のに、**どちらも言っていなかった。**
       えらんだ人は、**画面を消すと英語が止まる**ことを
       **知らないまま**そうなる —— **黙って落ちない**(CLAUDE.md)。
       「止める」の側は、はじめから利点を書いてあった(片方だけ古い)。 */
  { id: 'mix', label: 'そのまま', type: MIX_TYPE,
    hint: '音楽の大きさは変わりません。'
      + 'そのかわり、画面を消すと英語は止まり、消音スイッチでも鳴りません' },
]

/**
 * **既定は「止める」**(第5.352節)——
 * 消音スイッチの入った iPhone で**英語の音声そのものが鳴らない**という
 * 事故を、既定では起こさない。
 */
export const DEFAULT_MIX = 'off'

/** その id が宣言する種類。**知らない id は既定に落とす** */
const typeOf = (id) => (MIX_MODES.find((m) => m.id === id) ?? MIX_MODES[0]).type

/** いま宣言しているもの。**同じものを二度入れない** */
let いま = null

const 入れる = (type) => {
  if (いま === type) return いま
  いま = type
  const s = sessionOf()
  /* **受け付けない端末では、覚えるだけ。** 行き止まりを作らない */
  if (!s) return いま
  try { s.type = type } catch { /* 知らない値なら、そのままにする */ }
  return いま
}

/**
 * ★ **ほかのアプリの音と混ぜる**(止めない)。**起動のときに1回**呼ぶ。
 *
 * ── **えらんであるものが「混ざる側」なら、起動のときからそれを宣言する**
 *    (第5.360節・2026-10-03 実機「小さくする機能が効いていません」)──
 *
 *   これまでは**必ず `ambient`** にしていた。すると「小さくする」をえらんだ人は
 *
 *       起動 → `ambient` → **最初の指で解錠(無音を1本鳴らす)** → …
 *       → Listen を押して初めて `transient`
 *
 *   という順になる。**端末が音の扱いを決めるのは、最初に鳴らした時**
 *   なので、**あとから種類を変えても効かない**ことがありうる
 *   (iOS の音の設定は「使い始めるときに決まる」作りである)。
 *
 *   **だから、混ざる側どうしなら、はじめからえらんだほうで宣言する。**
 *   `ambient` も `transient` も**どちらも音楽を止めない**ので、
 *   起動のときに宣言しても第5.351節の約束は破れない。
 *
 *   **「止める」をえらんでいる人は、これまでどおり `ambient` で始める** ——
 *   あちらは**鳴らすまで音楽を止めない**のが約束だからである
 *   (起動しただけで Spotify が消えたのが、そもそもの始まりだった)。
 */
export const mixWithOthers = () => {
  const t = typeOf(mixMode())
  /* **主になる種類では始めない**(音楽を止めてしまう)。
     判断は「鳴らすときの種類が、混ざる側かどうか」1つである */
  return 入れる(t === OWN_TYPE ? MIX_TYPE : t)
}

/**
 * ★ **この端末で、宣言が効くか**(第5.352節)。
 *
 * **名前(UA)で見分けない。** 持っているかどうかを見るだけである
 * (`volumeWorks()` とまったく同じ作法)。
 * **効かない端末に、効かない設定を見せない**(CLAUDE.md)。
 */
export const mixWorks = () => Boolean(sessionOf())

/** いまえらんである id。**覚える。既定は「止める」** */
let えらび = null
export function mixMode() {
  if (えらび === null) {
    let v = ''
    try { v = String(window.localStorage.getItem(KEY) ?? '') } catch { v = '' }
    /* **前の版は「on / off」の2つだった**(第5.352節)。
       `on` を選んでいた人は「そのまま」である —— 黙って既定に戻さない */
    if (v === 'on') v = 'mix'
    えらび = MIX_MODES.some((m) => m.id === v) ? v : DEFAULT_MIX
  }
  return えらび
}

/**
 * えらびを決める。**その場で効かせる** ——
 * 「次に開いたときから」では、切り替えた気がしない(第5.257節と同じ)。
 */
export function setMixMode(next) {
  えらび = MIX_MODES.some((m) => m.id === next) ? next : DEFAULT_MIX
  try { window.localStorage.setItem(KEY, えらび) } catch { /* 使えなくても困らない */ }
  return 入れる(typeOf(えらび))
}

/**
 * ★ **こちらの音を鳴らすときの宣言。本当に鳴らす直前に呼ぶ。**
 *
 * **鳴らす道のぜんぶ**が通ること —— 1つ漏らすと、その道の音が
 * **消音スイッチで黙り、画面を消すと止まる**(第5.285節が壊れる)。
 *
 * ★ **何を宣言するかは、えらびが決める**(第5.352 / 5.356節)。
 * **判断はここ1か所** —— 鳴らす側(`audioClips.js` / `bgm.js` /
 * `speech.js` / `recognition.js`)は、どれであっても**呼ぶだけ**である。
 */
export const takeOverAudio = () => 入れる(typeOf(mixMode()))

/** いま何を宣言しているか(**検証と、画面に出すため**) */
export const audioSessionNow = () => いま

/** 手元の検証用。覚えた値を捨てる */
export const forgetAudioSession = () => { いま = null; えらび = null }
