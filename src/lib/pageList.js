/**
 * **1ページぶんの件数。ここ1か所。**
 *
 * 画面にも問い合わせにも書き写さない —— 書き写すと、
 * 変えた日に片方だけ古くなる(CLAUDE.md)。
 */
export const PAGE_SIZE = 50

/**
 * 読みに行く範囲。**1件だけ余分に読む。**
 *
 * その1件が返ってきたら「まだ先がある」と分かる。
 * **数える問い合わせを増やさない**(往復が2倍になる)。
 *
 * @param {number} offset いま何件まで出しているか
 * @param {number} limit 1ページぶん
 * @returns {[number, number]} `.range(from, to)` に渡す2つ(どちらも含む)
 */
export function pageRange(offset = 0, limit = PAGE_SIZE) {
  const from = Math.max(0, Math.trunc(offset) || 0)
  const size = Math.max(1, Math.trunc(limit) || PAGE_SIZE)
  return [from, from + size]
}

/**
 * 読んできた行を、1ページぶんに切る。
 *
 * @param {Array} rows 読んできた行(1件余分に入っている)
 * @param {number} limit 1ページぶん
 * @returns {{ list: Array, more: boolean }} 出すぶんと、まだ先があるか
 */
export function pageSlice(rows, limit = PAGE_SIZE) {
  const all = Array.isArray(rows) ? rows : []
  const size = Math.max(1, Math.trunc(limit) || PAGE_SIZE)
  const more = all.length > size
  return { list: more ? all.slice(0, size) : all, more }
}
