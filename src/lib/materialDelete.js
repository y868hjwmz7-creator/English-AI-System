/**
 * **教材を消す**(2026-09 利用者の指定)。
 *
 *   > また、ゲストに作った教材を消す方法を作って下さい。
 *   > 全ての場面にて「教材を消す」の機能を追加したいです。
 *   > トレーナーだけの機能です。ゲストには消せません
 *
 * ============================================================================
 * 【なぜここに切り出したのか】
 *
 *   「誰が消せるか」の判断を画面に書くと、**置く場所の数だけ食い違う**
 *   (`remakeModeOf()` を `voiceCast.js` に置いたのと同じ理由)。
 *   しかもこのファイルは**何にも依存しない**ので、
 *   `npm run test:play` が素の node で見張れる。
 *
 * 【消せるのは2人だけ。判断は SQL と同じ】
 *
 *   | 誰 | 消せるか | どこで決まっているか |
 *   |---|---|---|
 *   | 作った本人(トレーナー) | ○ | 0001「教材を作れるのはトレーナーだけ」 |
 *   | 管理者(`owner`) | ○ | **0044**(どの教材でも) |
 *   | ほかのトレーナー | × | どのポリシーにも当たらない |
 *   | ゲスト | × | 同上 |
 *
 *   **画面はこの表を写しているだけで、守っているのは SQL である。**
 *   ここを間違えても、RLS が「0件」で断る(`deleteMaterial()` が
 *   それを失敗として返す)。
 *
 * 【押せないなら、ボタンを出さない】
 *
 *   **選ばせてから断らない**(CLAUDE.md)。人の教材で
 *   「入れ替える」を出さないのと、まったく同じ作法である。
 */

/**
 * この人はこの教材を消せるか。
 *
 * @param material 教材(`created_by` を持つもの)
 * @param me       ログインしている人(`id` / `role`)
 */
export function canDeleteMaterial(material, me) {
  if (!material || !me) return false
  const role = me.role ?? null
  // ゲストは、自分が作った教材というものを持たない。**先に落とす**
  if (role !== 'trainer' && role !== 'owner') return false
  if (role === 'owner') return true           // 0044
  return !!material.created_by && material.created_by === me.id
}

/**
 * 消す前に出す一文。**何が消えて、何が残るのかを書く。**
 *
 * 「本当に消しますか」だけでは、宿題として配った先からも消えることが
 * 伝わらない(教材は既定で全トレーナーの共有物である)。
 *
 * @param shared この教材を共有しているゲストの人数。
 *               **数えられなかったときは `null`** を渡す
 *               —— 0 と取り違えると「誰にも配っていません」と嘘になる
 */
export function deleteWarning(shared = null) {
  const who = shared == null
    ? '共有したゲストの宿題からも消えます。'
    : shared > 0
      ? `共有している ${shared} 人のゲストの宿題からも消えます。`
      : 'まだ誰にも共有していない教材です。'
  return `この教材と、その中の本文・設問・訳を消します。${who}`
    + '単語帳と Quick Response に入れた語・文は消えません。元には戻せません。'
}
