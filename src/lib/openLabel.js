/**
 * ★ **教材をひらくボタンの呼び名**(2026-10-09 利用者の指定)。
 *
 *   > セッションで表示、というのもわかりにくいです。特に初めて触った
 *   > ゲスト。「この教材をひらく」とかそういう方が分かりやすいです。
 *
 * もとは **「セッションで使う(大きく表示)」**(2026-08 の指定)だった。
 * あれは**トレーナーの言葉**である —— レッスンのことを「セッション」と
 * 呼ぶのはスクールの中の話で、**初めて触ったゲストには通じない。**
 * しかも「大きく表示」は**起きることの説明**であって、
 * **何をするボタンなのか**を言っていない。
 *
 * 【なぜ1か所に置くか】
 *   同じボタンが**3か所**にあった(トレーナーの教材・ゲストの宿題・骨組み)。
 *   しかも**言葉が3つとも違った** ——
 *   「セッションで使う(大きく表示)」「大きく表示する」「大きく表示」。
 *   **呼び名を2か所に書かない**(CLAUDE.md)。
 *
 * 【セッションの記録の「大きく表示」は別のもの】
 *   `LessonNotes` の「大きく表示」は**メモを大きくする**ことで、
 *   教材をひらくことではない。**違うものに同じ名前を付けない**ので、
 *   あちらはこの呼び名を使わない。
 */

