/**
 * **落とした理由の呼び名。** 画面でも窓口でも、ここから引く
 * (呼び名を2か所に書かない・CLAUDE.md)。
 */
export const DROP_REASONS = {
  dup: '同じ英文',
  blank: '欄が空',
  shape: '形がちがう',
  giveaway: '答えが見えている',
  used: 'すでに使った英文',
  similar: '意味が近すぎる',
  /* ★ **英語として成り立っていない**(第5.358節)。
       実機で VERSANT Part A に出た
       「What do you call the first meal of a wedding day called a party after it?」
       がこれである —— **訳も正解も正しく、英文だけが壊れていた。**
       **ほかの理由に混ぜない** —— 混ぜると「英文が出尽くした」と
       言ってしまい、作りの問題を「仕方がない」と言うことになる */
  broken: '英語が壊れている',
}

/**
 * **「英文が出尽くした」と言ってよい理由。**
 *
 * 空や形で落ちているのは**作りの問題**であって、英文が尽きたのではない。
 * ここを分けないと、**直せるはずの不具合を「仕方がない」と言ってしまう。**
 */
const EXHAUSTED = new Set(['dup', 'used', 'similar'])

/** 数え方の箱。**空から始める**(0 と「数えていない」を混ぜない) */
export const emptyDropCounts = () =>
  Object.fromEntries(Object.keys(DROP_REASONS).map((k) => [k, 0]))

/**
 * 落とした理由を、画面に出す1行にする。**多い順**。
 *
 * **0 の理由は出さない**(行き止まりの情報を見せない・CLAUDE.md)。
 */
export const dropReasonLine = (counts) => Object.entries(counts ?? {})
  .filter(([, v]) => v > 0)
  .sort((a, b) => b[1] - a[1])
  .map(([k, v]) => `${DROP_REASONS[k] ?? k} ${v}`)
  .join(' / ')

/**
 * その落ち方は「この弱点で英文が出尽くしています」と言ってよいか。
 *
 * **半分以上が「前に出た」系のときだけ。** そうでなければ、
 * 落ちているのは別の理由である ——
 * **分かっていないことを、分かったように書かない**(CLAUDE.md)。
 */
export const isExhausted = (counts) => {
  const 全部 = Object.values(counts ?? {}).reduce((a, b) => a + (Number(b) || 0), 0)
  if (!全部) return false
  const 出尽くし = Object.entries(counts)
    .filter(([k]) => EXHAUSTED.has(k))
    .reduce((a, [, v]) => a + (Number(v) || 0), 0)
  return 出尽くし * 2 >= 全部
}
