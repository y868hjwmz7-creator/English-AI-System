/**
 * ★ **一度きりの説明**(第5.438節・2026-10-09 利用者の指定)。
 *
 *   > 初めての時だけ吹き出しで「覚えたに入れます」の説明が出ますが、
 *   > もう表示しないを選べばその後は表示されない仕様にしたいです。
 *
 * ============================================================================
 * 【「余計な説明書きを置かない」と、どう折り合うか】
 *
 *   共通ルールは「画面の使い方を、文章で説明しない」である。
 *   ここで出すのは**使い方ではなく、取り返しのつく範囲の確認**
 *   (「押すと『覚えた』に入ります」)——
 *   共通ルールが残してよいとしている3つのうちの
 *   **「取り返しのつかない操作の確認」**に近い。
 *
 *   そのうえで**一度きり**にする。二度目からは、押した人はもう知っている。
 *
 * 【覚える先は端末(`localStorage`)】
 *
 *   人ごと・端末ごとでよい。**読めなくても困らない** ——
 *   読めなければ「まだ見ていない」と見なして、もう一度出すだけである
 *   (**既定は「出す」側**。黙って飲み込まない)。
 *
 * 【鍵は1か所】
 *
 *   画面の中で `localStorage.getItem('eas.tips…')` と書かない。
 *   足したい説明が増えても、ここに id を1つ足すだけで済む。
 */

/** 覚えておく場所。**ほかの覚えもの(`eas.review.*`)と並べる** */
const KEY = (id) => `eas.tip.${id}`

/**
 * その説明を、まだ出してよいか。
 * **読めなければ `true`**(出す側に倒す)。
 */
export function tipOpen(id) {
  try { return localStorage.getItem(KEY(id)) !== 'off' } catch { return true }
}

/** 「もう表示しない」。**次からは出さない** */
export function tipClose(id) {
  try { localStorage.setItem(KEY(id), 'off') } catch { /* 使えなくても困らない */ }
}

