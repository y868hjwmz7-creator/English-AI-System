/**
 * **いま出しているものの名前**(第5.187節・2026-09 実機・利用者の指定)。
 *
 * ============================================================================
 *   > Quick responseや単語帳の冊選びから、範囲を絞り込んだ後に出題される
 *   > 内容が選んだものと一致していない気がします。特にNATIVE FLOWと14の型です。
 *   > 選んだ後に選んだものがどこかに明確に表示されてほしいと思います。
 *
 * 【絞り込みそのものは、正しかった】
 *
 *   **呼んで数えて確かめた**(`npm run test:play`)。
 *   Unit 1〜6 も、14 の型の 14 系も、型ひとつも、
 *   **出る数が一覧の数とぴったり合う。**
 *
 *   では何が起きていたか —— **選んだものが、どこにも書いていなかった。**
 *   帯に出るのは冊の名前(「14 の型 ▾」)だけで、
 *   **Unit も、中身も、型も、吹き出しを開き直さないと分からない。**
 *   だから「一致していない**気がする**」になる。
 *   **見えないものは、合っていても信じられない。**
 *
 * 【だから、名前を1本につなぐ】
 *
 *     Native Flow /【Unit 4】4〜6単語の表現
 *     14 の型 / 日本語 → 英語 / ① 1. させる(背中を押す)
 *     単語帳 / 業種べつ / 製造・品質保証
 *
 *   置き場所は**コンテンツの上のタイトル**(`DrillHead`・第5.180節)。
 *   **新しい欄を作っていない** —— そこはもともと冊の名前を出す場所で、
 *   いま出しているものの名前を、**より詳しく**しただけである。
 *
 * 【選んでいないものは、書かない】
 *
 *   「ぜんぶ」のときに「/ ぜんぶ」と足さない。
 *   **足すと、選んだときと見た目が変わらなくなる** ——
 *   見分けが付かないなら、出す意味が無い。
 *
 * 【Supabase を引き連れない】
 *
 *   つなぐ決まりだけなので、`npm run test:play` が素の node で走らせられる
 *   (`playMark.js` / `assignBooks.js` と同じ考え方)。
 * ============================================================================
 */

/**
 * 冊の名前と、その中で選んだものを1本につなぐ。
 *
 * **空は落とす。** 選んでいないもの・数えられなかったものを
 * 「/」だけで表さない(**0 と `null` を取り違えない**・CLAUDE.md)。
 *
 * @param parts 外側から内側の順(冊 → 中身 → 型)
 */
export const nowName = (parts = []) => (Array.isArray(parts) ? parts : [parts])
  .map((s) => String(s ?? '').trim())
  .filter(Boolean)
  .join(' / ')
