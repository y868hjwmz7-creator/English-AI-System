/**
 * **カードを送る / 判定する操作**(第5.417節・2026-10-07 利用者の指定・段階4)。
 *
 * ============================================================================
 * 【決まっていること】
 *
 *   | 操作 | 前へ | 次へ | 覚えた(言える) | まだ |
 *   |---|---|---|---|---|
 *   | **矢印キー** | **←** | **→** | **↑** | **↓** |
 *   | **紙の余白をクリック** | **左の余白** | **右の余白** | — | — |
 *   | **スワイプ**(指の端末だけ) | **左へ** | **右へ** | — | — |
 *   | **ボタン**(残す) | — | — | 「覚えた ↑」 | 「まだ ↓」 |
 *
 *   ★ **スワイプは、判定しない**(2026-10-08 利用者の指定・仕様変更)。
 *
 *     > 左スワイプは「ひとつ前に戻る」右スワイプは「ひとつ先に進む」に
 *     > しましょう。これはパソコンでも同じです。左の余白クリックは
 *     > ひとつ戻る、右の余白のクリックはひとつ進む。
 *     > 「まだ」「言えた」ボタンはそのまま残します。
 *
 *     はじめ**右へはらう = 覚えた / 左へはらう = まだ**にしていたが、
 *     **指と余白とキーで向きの意味が食い違っていた** ——
 *     ← → と余白は「送る」なのに、スワイプだけ「判定」だった。
 *
 *     **横の動きは、どれも「送る」に揃える。**
 *     **判定はボタンと ↑↓ だけ**が持つ(記録に残るのは、押したときだけ)。
 *
 *   - **PC でのドラッグ(スワイプ)は入れない。** 直感的でないうえに、
 *     **語をなぞって単語帳に入れる操作とぶつかる**(第5.17節のなぞり)
 *   - **どの訊き方でも送れる**(4択でも、思い出すでも同じ)
 *
 * 【ここに置いた理由】
 *   `Wordbook.jsx` も `QrCard.jsx` も、**まったく同じ操作**を受け取る。
 *   片方に書くと、必ずもう片方が古くなる(CLAUDE.md「判断は1か所に持つ」)。
 *
 *   **何にも依存しない**(`window` も React も触らない)ので、
 *   `npm run test:play` が**素の node で数字を見張れる** ——
 *   `playMark.js` / `learnStage.js` / `metRange.js` と同じ作法である。
 * ============================================================================
 */

/**
 * ★ **押せる幅の下限**(44px)。
 *
 * 指で狙える大きさの決まり(CLAUDE.md「触る的は 44px 以上」)。
 * **余白がこれより狭いときは、押せる帯を出さない** ——
 * 出しても押せないものは、効かない操作である(CLAUDE.md)。
 *
 * **広い画面では左右が大きく空き、狭い画面ではほとんど無い。**
 * だから**幅を実測して決める。決め打ちにしない**(第5.417節)。
 */
export const TAP_MIN = 44

/**
 * その余白に、押せる帯を出してよいか。
 *
 * @param {number} space カード(紙)の外側の、片側の余白の幅(px)
 */
export const edgeFits = (space) => (Number(space) || 0) >= TAP_MIN

/**
 * 紙の入れ物の幅とカードの幅から、片側の余白を出す。
 *
 * **押せる帯は「紙(カード)の入れ物」の中に置く**(第5.417節)——
 * 窓に対して置くと、**上の帯にも下のタブバーにもかかる。**
 */
export const edgeSpace = (holder, card) => Math.max(
  0, Math.floor(((Number(holder) || 0) - (Number(card) || 0)) / 2),
)

/* ══════════════════════════════════════════════════════════════════
   矢印キー
   ══════════════════════════════════════════════════════════════════ */

/** 矢印キー → 何をするか。**知らないキーは `null`**(既定は「何もしない」) */
const KEYS = {
  ArrowLeft: 'prev',
  ArrowRight: 'next',
  ArrowUp: 'ok',
  ArrowDown: 'yet',
}

/**
 * ★ **押されたキーが、どの操作か**。
 *
 * **文字を打っているときは、1つも効かせない**(`typing`)——
 * つづりの訊き方には入力欄があり、そこで ← → を押すのは
 * **字を直しているだけ**である。カードが飛んだら書き直せない。
 *
 * **飾りのキー(Ctrl / ⌘ / Alt)が押されていたら効かせない** ——
 * ブラウザの「戻る」(⌘ ←)や、ページの送りとぶつかる。
 *
 * @param {object} e  `{ key, ctrlKey, metaKey, altKey }`
 * @param {object} o  `{ typing }` … いま入力欄に字を打っているか
 * @returns {'prev'|'next'|'ok'|'yet'|null}
 */
export function keyMove(e, { typing = false } = {}) {
  if (!e || typing) return null
  if (e.ctrlKey || e.metaKey || e.altKey) return null
  return KEYS[e.key] ?? null
}

/** **キーの印**。ボタンの中に出す(「まだ ↓」「覚えた ↑」) */
export const KEY_MARK = { prev: '←', next: '→', ok: '↑', yet: '↓' }

/**
 * ボタンに出す言葉。**印は呼ぶ側で足さない**(1か所で組む)。
 *
 * **キーの使えない端末では、印を出さない** —— 指しかない端末に
 * 「↑」と書いても、押しようがない(**効かない操作を見せない**)。
 */
export const keyLabel = (text, move, { keys = true } = {}) => (
  keys && KEY_MARK[move] ? `${text} ${KEY_MARK[move]}` : String(text ?? '')
)

/* ══════════════════════════════════════════════════════════════════
   スワイプ(指の端末だけ)
   ══════════════════════════════════════════════════════════════════ */

/**
 * ★ **スワイプと認める最小の横の動き**(px)。
 *
 * 短すぎると、**語をなぞって単語帳に入れる操作**や、ただのタップを
 * 送りと取り違える。長すぎると、片手で届かない。
 *
 * ★ **押せる的の大きさ(`TAP_MIN`)と同じ数にする**(2026-10-08)。
 * もとは 56px の決め打ちで、**指を 56px 引くまで何も起きなかった。**
 * **数は1か所から出す** —— 「指で狙える動き」はどちらも同じ話である。
 */
export const SWIPE_MIN = TAP_MIN

/**
 * ★ **さっとはらったときは、短くても送る**(2026-10-08 利用者の指摘
 * 「スワイプの反応が良くない」)。
 *
 * 指は**速く小さく**動かすほうが自然で、`SWIPE_MIN` まで引く前に
 * 離してしまう。**速さを見れば、その短いはらいも拾える。**
 *
 * `SWIPE_FLICK` px 以上動いていて、`SWIPE_SPEED` px/ミリ秒 以上の速さ。
 */
export const SWIPE_FLICK = 20
export const SWIPE_SPEED = 0.4

/**
 * ★ **指について動き始める距離**(px)。
 *
 * これを超えたら「横に引いている」と見なして、**カードを指につける。**
 * 小さすぎるとタップでも動いてしまい、大きすぎると**引いても
 * 何も起きない時間**ができる(それが「反応が良くない」の正体だった)。
 */
export const DRAG_FROM = 6

/**
 * ★ **横より縦に動いていたら、スワイプではない。**
 *
 * 画面を上下に送っているだけのことが多い。
 * **横が縦の 1.5 倍以上**動いていることを条件にする。
 */
export const SWIPE_SLOPE = 1.5

/**
 * ★ **ゆっくりでも、しっかり引いたなら送る**(2026-10-08)。
 *
 * もとは **1 秒を超えたら送らない**ことにしていたが、
 * **ゆっくり確かめながら引く人の操作が、黙って消えていた。**
 * いまは「`SWIPE_MIN` 引いたか」「さっとはらったか」だけで決める。
 *
 * この数は**速さを出すときの割り算の下限**としてだけ残してある
 * (0 で割らないため)。
 */
export const SWIPE_MS = 1

/**
 * 指の動きが、どの**送り**か。
 *
 * ★ **右へ = ひとつ先へ / 左へ = ひとつ前へ**
 * (2026-10-08 利用者の指定・仕様変更)。
 *
 * **ここは判定を返さない。** 返すのは `'prev'` / `'next'` だけである ——
 * **はらっただけで記録が変わってはいけない。**
 * 判定は「まだ」「言える」のボタンと ↑↓ が持つ。
 *
 * **当てはまらなければ `null`** —— 既定は「何もしない」側である。
 *
 * @param {object} g `{ dx, dy, ms }` 横の動き・縦の動き・かかった時間
 * @returns {'prev'|'next'|null}
 */
export function swipeMove({ dx = 0, dy = 0, ms = 0 } = {}) {
  const x = Number(dx) || 0
  const y = Math.abs(Number(dy) || 0)
  const t = Math.max(Number(ms) || 0, SWIPE_MS)
  /* **横より縦に動いていたら、画面を送っているだけ** */
  if (Math.abs(x) < y * SWIPE_SLOPE) return null
  /* **しっかり引いた**(ゆっくりでもよい) */
  const 引いた = Math.abs(x) >= SWIPE_MIN
  /* ★ **さっとはらった**(短くても速ければ送る・2026-10-08) */
  const はらった = Math.abs(x) >= SWIPE_FLICK && Math.abs(x) / t >= SWIPE_SPEED
  if (!引いた && !はらった) return null
  return x > 0 ? 'next' : 'prev'
}

/**
 * ★ **引いている最中、カードを指につける**(2026-10-08 利用者の指摘)。
 *
 *   > なんかスワイプの反応が良くないです
 *
 * **実測したら、引いている最中のズレは 0px だった** ——
 * 指を動かしても画面は1pxも動かず、離して 300ms 後にようやく飛ぶ。
 * **動かしているあいだ何も起きないものは、効いていないのと同じ**である。
 *
 * **横に引いていると分かってから**(`DRAG_FROM`)、そのぶんだけ動かす。
 * **縦のほうが大きいあいだは動かさない**(画面を送っているだけなので)。
 *
 * @returns {number} カードをずらす px。**0 なら、まだ動かさない**
 */
export function dragShift({ dx = 0, dy = 0 } = {}) {
  const x = Number(dx) || 0
  const y = Math.abs(Number(dy) || 0)
  if (Math.abs(x) < DRAG_FROM) return 0
  if (Math.abs(x) < y) return 0
  return x
}

/**
 * ★ **スワイプで送ったら、その向きへ流して消す**(2026-10-07 利用者の指定)。
 *
 *   > カードが流れて、すぐ次へ
 *
 * **ボタンで押したときは、いまどおり即座に次へ** —— あちらは
 * 指がボタンの上にあるので、動かすと**次の問のボタンが指の下に来る**
 * (共通ルール「押しても、まわりの物が動かない」)。
 *
 * ミリ秒。**CSS の `transition` と同じ値を2か所に書かない**ので、
 * 画面はこの数を `style` に渡す。
 */
export const FLY_MS = 300

/**
 * 流れる向き(`transform` に渡す)。**送りと向きの対応は、ここ1か所。**
 *
 * **指が動いたほうへ流れる** —— 右へはらえば右へ、左へはらえば左へ。
 * 逆を向くと、**引っぱった手と画面が反対に動く。**
 */
export const flyX = (move) => (move === 'next' ? '120%' : '-120%')

