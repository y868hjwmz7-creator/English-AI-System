/**
 * **カードを送る / 判定する操作**(第5.417節・2026-10-07 利用者の指定・段階4)。
 *
 * ============================================================================
 * 【決まっていること】
 *
 *   | 操作 | 前へ | 次へ | 覚えた(言える) | まだ |
 *   |---|---|---|---|---|
 *   | **矢印キー** | **←** | **→** | **↑** | **↓** |
 *   | **紙の余白をクリック** | **左の余白** | **右の余白** | — | — |
 *   | **◀▶ のボタン**(指の端末だけ) | **◀** | **▶** | — | — |
 *   | **ボタン**(残す) | — | — | 「覚えた ↑」 | 「まだ ↓」 |
 *
 *   ★ **スワイプは廃止した**(2026-10-08 利用者の指定)。
 *   指の端末では、**「まだ」「言えた」の行の左右に ◀▶ を置く**。
 *
 *     > 左スワイプは「ひとつ前に戻る」右スワイプは「ひとつ先に進む」に
 *     > しましょう。これはパソコンでも同じです。左の余白クリックは
 *     > ひとつ戻る、右の余白のクリックはひとつ進む。
 *     > 「まだ」「言えた」ボタンはそのまま残します。
 *
 *     はじめ**右へはらう = 覚えた / 左へはらう = まだ**にしていたが、
 *     **指と余白とキーで向きの意味が食い違っていた** ——
 *     ← → と余白は「送る」なのに、スワイプだけ「判定」だった。
 *
 *     **横の動きは、どれも「送る」に揃える。**
 *     **判定はボタンと ↑↓ だけ**が持つ(記録に残るのは、押したときだけ)。
 *
 *   - **PC でのドラッグ(スワイプ)は入れない。** 直感的でないうえに、
 *     **語をなぞって単語帳に入れる操作とぶつかる**(第5.17節のなぞり)
 *   - **どの訊き方でも送れる**(4択でも、思い出すでも同じ)
 *
 * 【ここに置いた理由】
 *   `Wordbook.jsx` も `QrCard.jsx` も、**まったく同じ操作**を受け取る。
 *   片方に書くと、必ずもう片方が古くなる(CLAUDE.md「判断は1か所に持つ」)。
 *
 *   **何にも依存しない**(`window` も React も触らない)ので、
 *   `npm run test:play` が**素の node で数字を見張れる** ——
 *   `playMark.js` / `learnStage.js` / `metRange.js` と同じ作法である。
 * ============================================================================
 */

/**
 * ★ **押せる幅の下限**(44px)。
 *
 * 指で狙える大きさの決まり(CLAUDE.md「触る的は 44px 以上」)。
 * **余白がこれより狭いときは、押せる帯を出さない** ——
 * 出しても押せないものは、効かない操作である(CLAUDE.md)。
 *
 * **広い画面では左右が大きく空き、狭い画面ではほとんど無い。**
 * だから**幅を実測して決める。決め打ちにしない**(第5.417節)。
 */
export const TAP_MIN = 44

/**
 * その余白に、押せる帯を出してよいか。
 *
 * @param {number} space カード(紙)の外側の、片側の余白の幅(px)
 */
export const edgeFits = (space) => (Number(space) || 0) >= TAP_MIN

/**
 * 紙の入れ物の幅とカードの幅から、片側の余白を出す。
 *
 * **押せる帯は「紙(カード)の入れ物」の中に置く**(第5.417節)——
 * 窓に対して置くと、**上の帯にも下のタブバーにもかかる。**
 */
export const edgeSpace = (holder, card) => Math.max(
  0, Math.floor(((Number(holder) || 0) - (Number(card) || 0)) / 2),
)

/**
 * ★ **押せる帯を、空いているところいっぱいに広げる**
 *   (2026-10-09 利用者の指定)。
 *
 *   > クリックできる範囲も画面幅いっぱいに広げてください。
 *
 *   `edgeSpace()` は**カードの入れ物**の中しか見ていなかったので、
 *   広い画面では**本体の止め幅(1100px)で切れていた** ——
 *   その外の黒いところは、見た目は同じなのに押せなかった。
 *
 *   **窓いっぱいにはしない。** 左に柱(`.app-nav`)が並ぶ配色では、
 *   柱の上まで帯が伸びる。**外側は、本体(`.app-body`)まで**にする
 *   —— 柱は本体の外なので、1ミリも重ならない。
 *
 *   **左右は別々に出す。** 本体の中でカードが中央にあるとは限らない。
 *
 * @param {{left:number,right:number}} outer 外の入れ物(本体)の位置
 * @param {{left:number,right:number}} card  カードの位置
 * @returns {{left:number,right:number}} 片側ずつの幅(px)
 */
export const edgeBand = (outer, card) => ({
  left: Math.max(0, Math.floor((Number(card?.left) || 0) - (Number(outer?.left) || 0))),
  right: Math.max(0, Math.floor((Number(outer?.right) || 0) - (Number(card?.right) || 0))),
})

