export const FLY_MS = 600

/**
 * 流れる向き(`transform` に渡す)。**送りと向きの対応は、ここ1か所。**
 *
 * ★ **押したボタンのほうへ、中身が去る**(2026-10-08 利用者の指摘・**向き直し**)。
 *
 *   > 左側の◀を押すと内容が左に流れ、右側の▶を押すと右に流れる。
 *   > 反対の方が良いのではないかと感じます。今は戻っているはずなのに
 *   > 進んでる、進んでいるはずなのに戻っているように感じるんです。
 *
 * はじめは**押したボタンと同じ向き**へ流していた(▶ なら右)。
 * あれは**指ではらったときの向き**(スワイプ)の考え方である ——
 * はらった手に画面がついてくるので、同じ向きが正しかった。
 *
 * **ボタンは、はらう動きではない。** 紙をめくるのと同じで、
 * **次へ進めば、いまの紙は左へ去って、次の紙が右から来る。**
 * だから **▶(次へ)は左へ、◀(前へ)は右へ**流す。
 *
 * **この1行を裏返すと、進む / 戻るの感じがまるごと裏返る。**
 */
export const flyX = (move) => {
  /* **判定は上下だけ。** ここで `0` を返さないと、斜めに飛ぶ
     (`flyY()` を足した日に踏んだ・2026-10-09) */
  if (move === 'ok' || move === 'yet') return '0'
  return move === 'next' ? '-120%' : '120%'
}

/**
 * ★ **判定したら、その向きへ上下に去る**(2026-10-09 利用者の指定)。
 *
 * **向きは `KEY_MARK` と同じ** —— 「言える ↑」は上、「まだ ↓」は下。
 * **送り(`prev` / `next`)では上下に動かさない**(あちらは横)。
 *
 * **ここを裏返すと、どちらに入ったかの感じがまるごと裏返る。**
 */
export const flyY = (move) => {
  if (move === 'ok') return '-120%'
  if (move === 'yet') return '120%'
  return '0'
}

/** その動きで、中身を流すか。**4つとも流す**(向きが違うだけ) */
export const flies = (move) => ['prev', 'next', 'ok', 'yet'].includes(move)

