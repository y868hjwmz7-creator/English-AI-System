/**
 * **カードを送る / 判定する操作**(第5.417節・2026-10-07 利用者の指定・段階4)。
 *
 * ============================================================================
 * 【決まっていること】
 *
 *   | 操作 | 前へ | 次へ | 覚えた(言える) | まだ |
 *   |---|---|---|---|---|
 *   | **矢印キー** | **←** | **→** | **↑** | **↓** |
 *   | **紙の余白をクリック** | **左の余白** | **右の余白** | — | — |
 *   | **ボタン**(残す) | — | — | 「覚えた ↑」 | 「まだ ↓」 |
 *   | **スワイプ**(指の端末だけ) | — | — | **右へ** | **左へ** |
 *
 *   - **PC でのドラッグ(スワイプ)は入れない。** 直感的でないうえに、
 *     **語をなぞって単語帳に入れる操作とぶつかる**(第5.17節のなぞり)
 *   - **どの訊き方でも効く**(2026-10-07 利用者の指定)——
 *     4択・つづりでも ↑↓ とスワイプで判定できる。
 *     **自分の申告が、機械の判定より優先される**
 *
 * 【ここに置いた理由】
 *   `Wordbook.jsx` も `QrCard.jsx` も、**まったく同じ操作**を受け取る。
 *   片方に書くと、必ずもう片方が古くなる(CLAUDE.md「判断は1か所に持つ」)。
 *
 *   **何にも依存しない**(`window` も React も触らない)ので、
 *   `npm run test:play` が**素の node で数字を見張れる** ——
 *   `playMark.js` / `learnStage.js` / `metRange.js` と同じ作法である。
 * ============================================================================
 */

/**
 * ★ **押せる幅の下限**(44px)。
 *
 * 指で狙える大きさの決まり(CLAUDE.md「触る的は 44px 以上」)。
 * **余白がこれより狭いときは、押せる帯を出さない** ——
 * 出しても押せないものは、効かない操作である(CLAUDE.md)。
 *
 * **広い画面では左右が大きく空き、狭い画面ではほとんど無い。**
 * だから**幅を実測して決める。決め打ちにしない**(第5.417節)。
 */
export const TAP_MIN = 44

/**
 * その余白に、押せる帯を出してよいか。
 *
 * @param {number} space カード(紙)の外側の、片側の余白の幅(px)
 */
export const edgeFits = (space) => (Number(space) || 0) >= TAP_MIN

/**
 * 紙の入れ物の幅とカードの幅から、片側の余白を出す。
 *
 * **押せる帯は「紙(カード)の入れ物」の中に置く**(第5.417節)——
 * 窓に対して置くと、**上の帯にも下のタブバーにもかかる。**
 */
export const edgeSpace = (holder, card) => Math.max(
  0, Math.floor(((Number(holder) || 0) - (Number(card) || 0)) / 2),
)

/* ══════════════════════════════════════════════════════════════════
   矢印キー
   ══════════════════════════════════════════════════════════════════ */

/** 矢印キー → 何をするか。**知らないキーは `null`**(既定は「何もしない」) */
const KEYS = {
  ArrowLeft: 'prev',
  ArrowRight: 'next',
  ArrowUp: 'ok',
  ArrowDown: 'yet',
}

/**
 * ★ **押されたキーが、どの操作か**。
 *
 * **文字を打っているときは、1つも効かせない**(`typing`)——
 * つづりの訊き方には入力欄があり、そこで ← → を押すのは
 * **字を直しているだけ**である。カードが飛んだら書き直せない。
 *
 * **飾りのキー(Ctrl / ⌘ / Alt)が押されていたら効かせない** ——
 * ブラウザの「戻る」(⌘ ←)や、ページの送りとぶつかる。
 *
 * @param {object} e  `{ key, ctrlKey, metaKey, altKey }`
 * @param {object} o  `{ typing }` … いま入力欄に字を打っているか
 * @returns {'prev'|'next'|'ok'|'yet'|null}
 */
export function keyMove(e, { typing = false } = {}) {
  if (!e || typing) return null
  if (e.ctrlKey || e.metaKey || e.altKey) return null
  return KEYS[e.key] ?? null
}

/** **キーの印**。ボタンの中に出す(「まだ ↓」「覚えた ↑」) */
export const KEY_MARK = { prev: '←', next: '→', ok: '↑', yet: '↓' }

/**
 * ボタンに出す言葉。**印は呼ぶ側で足さない**(1か所で組む)。
 *
 * **キーの使えない端末では、印を出さない** —— 指しかない端末に
 * 「↑」と書いても、押しようがない(**効かない操作を見せない**)。
 */
export const keyLabel = (text, move, { keys = true } = {}) => (
  keys && KEY_MARK[move] ? `${text} ${KEY_MARK[move]}` : String(text ?? '')
)

/* ══════════════════════════════════════════════════════════════════
   スワイプ(指の端末だけ)
   ══════════════════════════════════════════════════════════════════ */

/**
 * ★ **スワイプと認める最小の横の動き**(px)。
 *
 * 短すぎると、**語をなぞって単語帳に入れる操作**や、ただのタップを
 * 判定と取り違える。長すぎると、片手で届かない。
 */
export const SWIPE_MIN = 56

/**
 * ★ **横より縦に動いていたら、スワイプではない。**
 *
 * 画面を上下に送っているだけのことが多い。
 * **横が縦の 1.5 倍以上**動いていることを条件にする。
 */
export const SWIPE_SLOPE = 1.5

/**
 * ★ **ゆっくりすぎる動きは、スワイプではない**(ミリ秒)。
 *
 * 指を置いたまま考えて、たまたま横へずれた、を拾わないため。
 */
export const SWIPE_MS = 1000

/**
 * 指の動きが、どの判定か。
 *
 * **右へ = 覚えた(言える) / 左へ = まだ**(2026-10-07 利用者の指定)。
 * **当てはまらなければ `null`** —— 既定は「何もしない」側である。
 *
 * @param {object} g `{ dx, dy, ms }` 横の動き・縦の動き・かかった時間
 * @returns {'ok'|'yet'|null}
 */
export function swipeMove({ dx = 0, dy = 0, ms = 0 } = {}) {
  const x = Number(dx) || 0
  const y = Math.abs(Number(dy) || 0)
  const t = Number(ms) || 0
  if (Math.abs(x) < SWIPE_MIN) return null
  if (Math.abs(x) < y * SWIPE_SLOPE) return null
  if (t > SWIPE_MS) return null
  return x > 0 ? 'ok' : 'yet'
}

/**
 * ★ **スワイプで判定したら、その向きへ流して消す**(2026-10-07 利用者の指定)。
 *
 *   > カードが流れて、すぐ次へ
 *
 * **ボタンで押したときは、いまどおり即座に次へ** —— あちらは
 * 指がボタンの上にあるので、動かすと**次の問のボタンが指の下に来る**
 * (共通ルール「押しても、まわりの物が動かない」)。
 *
 * ミリ秒。**CSS の `transition` と同じ値を2か所に書かない**ので、
 * 画面はこの数を `style` に渡す。
 */
export const FLY_MS = 300

/** 流れる向き(`transform` に渡す)。**判定と向きの対応は、ここ1か所** */
export const flyX = (move) => (move === 'ok' ? '120%' : '-120%')

