/**
 * **くり返しの単位の呼び名と、次に移る先**(第5.316節で切り出した)。
 *
 * ============================================================================
 * 【なぜ部品から出したか】
 *
 *   もとは `RepeatUnit.jsx` の中にあった。**純粋な算段なのに、
 *   `.jsx` の中にいるせいで素の node から呼べず**、見張り(`test:bar`)が
 *   4つの呼び名を**書き写す**しかなかった。書き写すと、
 *   呼び名を変えた日に**見張りだけが古くなる**(CLAUDE.md
 *   「値を書き写さない。性質で見る」)。
 *
 *   **描けないものは測れない**ので、算段は何にも依存しない形へ出す
 *   (`playMark.js` / `wholePlay.js` / `speakLabel.js` と同じ扱い)。
 *
 * 【4つある理由】(2026-09 利用者の指定 / 2026-09-30 に再確認)
 *
 *   > リピートしない / 段落ごとにリピート / 文ごとにリピート / 全文をリピート
 *   > 現在の機能と状態管理を確認し、すべて選択できるようにしてください
 *
 *   まねて言う練習は**1文だけ**を回したい。聞き流したい人は**本文ぜんぶ**。
 *   単位が1つしかないと、どちらもできない。
 *
 * 【「段落」か「発言」かは、呼ぶ側が言う】
 *   記事は段落、会話・会議は発言(`countUnit()` の決まり)。**ここで数え直さない。**
 */
import { REPEAT_UNITS } from './wholeAudio.js'

/** その単位の呼び名。**「段落 / 発言」だけが教材で変わる** */
export const repeatLabel = (id, unit = '段落') => ({
  off: 'しない',
  sentence: '文',
  item: unit,
  all: '全文',
}[id] ?? 'しない')

/**
 * **その画面で出す単位**(2026-09-30・第5.322節)。
 *
 *   **呼び名が重なるものは出さない。** スピーチ練習では
 *   **1つの部が1文**なので、`sentence`(文)と `item`(その単位)が
 *   **どちらも「文」**になる —— 押すと「文 → 文」と回り、
 *   何が変わったのか分からない
 *   (**同じことをするものを2つ見せない**・CLAUDE.md)。
 *
 *   **一覧を画面ごとに持たせない。性質で見る** ——
 *   呼び名が同じものを落とすだけなので、単位の名前を変えた日も、
 *   単位を足した日も、ひとりでに付いてくる。
 */
export const repeatUnitsFor = (unit = '段落') => {
  const 見た = new Set()
  return REPEAT_UNITS.filter((id) => {
    const 名 = repeatLabel(id, unit)
    if (見た.has(名)) return false
    見た.add(名)
    return true
  })
}

/**
 * 次に移る先。**並びは `REPEAT_UNITS` 1か所**(2か所に持たない)。
 *
 * ★ **一度消して、また戻した**(第5.318 → 5.320節)。
 *   3つ並べる形にした日に呼ぶ人がいなくなったので消したが、
 *   利用者の指定で**ボタン1つに戻した**(場所を取りすぎるため)。
 *   **消した経緯も残す** —— 次に「並べたい」と言われたときに、
 *   どちらも試したことが分かる。
 *
 * ★ **単位も受け取る**(第5.322節)。呼び名が重なる段は飛ばす。
 */
export const nextRepeat = (id, unit = '段落') => {
  const list = repeatUnitsFor(unit)
  const i = list.indexOf(id)
  return list[(i < 0 ? 0 : i + 1) % list.length]
}

/**
 * **ボタンに出す言い方**(2026-09-30・第5.320節)。
 *
 *   絵だけのボタンなので、**名前は `aria-label` と `title` にしか無い。**
 *   ここを部品の中に書くと、**見張り(`test:bar`)が書き写す**ことになり、
 *   言い方を変えた日に**見張りだけが古くなる**(実際そうなった ——
 *   3つ並べる形をやめた日に、持ちもの一覧が3件で赤くなった)。
 *
 *   **いまの単位と、押したら何になるか**の両方を言う ——
 *   絵だけでは「次に何が起きるか」が分からない。
 */
export const repeatSay = (id, unit = '段落') =>
  `くり返し。いまは ${repeatLabel(id, unit)}`
  + `。押すと ${repeatLabel(nextRepeat(id, unit), unit)} になります`
