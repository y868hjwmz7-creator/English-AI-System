/**
 * **くり返しの単位の呼び名と、次に移る先**(第5.316節で切り出した)。
 *
 * ============================================================================
 * 【なぜ部品から出したか】
 *
 *   もとは `RepeatUnit.jsx` の中にあった。**純粋な算段なのに、
 *   `.jsx` の中にいるせいで素の node から呼べず**、見張り(`test:bar`)が
 *   4つの呼び名を**書き写す**しかなかった。書き写すと、
 *   呼び名を変えた日に**見張りだけが古くなる**(CLAUDE.md
 *   「値を書き写さない。性質で見る」)。
 *
 *   **描けないものは測れない**ので、算段は何にも依存しない形へ出す
 *   (`playMark.js` / `wholePlay.js` / `speakLabel.js` と同じ扱い)。
 *
 * 【4つある理由】(2026-09 利用者の指定 / 2026-09-30 に再確認)
 *
 *   > リピートしない / 段落ごとにリピート / 文ごとにリピート / 全文をリピート
 *   > 現在の機能と状態管理を確認し、すべて選択できるようにしてください
 *
 *   まねて言う練習は**1文だけ**を回したい。聞き流したい人は**本文ぜんぶ**。
 *   単位が1つしかないと、どちらもできない。
 *
 * 【「段落」か「発言」かは、呼ぶ側が言う】
 *   記事は段落、会話・会議は発言(`countUnit()` の決まり)。**ここで数え直さない。**
 */
import { REPEAT_UNITS } from './wholeAudio.js'

/** その単位の呼び名。**「段落 / 発言」だけが教材で変わる** */
export const repeatLabel = (id, unit = '段落') => ({
  off: 'しない',
  sentence: '文',
  item: unit,
  all: '全文',
}[id] ?? 'しない')

/** 次に移る先。**並びは `REPEAT_UNITS` 1か所**(2か所に持たない) */
export const nextRepeat = (id) => {
  const i = REPEAT_UNITS.indexOf(id)
  return REPEAT_UNITS[(i < 0 ? 0 : i + 1) % REPEAT_UNITS.length]
}
