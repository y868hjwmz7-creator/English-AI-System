/**
 * **ファイルに持っている冊を、良い声で読む**(第5.446節・④)。
 *
 *   > elevenlabs が最高すぎてあまりよく聞こえません
 *   (2026-10 利用者の指摘。単語帳と Quick Response の声について)
 *
 * ============================================================================
 * 【これは方針の転換である】
 *
 *   `voiceTier.js` はこう書いてある ——
 *   「文法の穴埋め、和文英訳、**単語・フレーズの読み上げ**は、
 *   読み方が分かることが目的である。ここに良い声は要らない」。
 *
 *   **その判断を、固定の冊についてだけ変える。**
 *   理由は1つで、**固定の冊は増えない**からである。
 *
 *   **文字数は実測した**(`radioTextOf()` が返す英文を、冊ごとに
 *   重複を落として数えた。`npm run test:play` が同じ数え方で見張る)。
 *
 *   | 冊 | 件数 | 文字数 |
 *   |---|---|---|
 *   | 基礎単語(標準 1200 語) | 1,200 | 6,837 |
 *   | Native Flow | 687 | 16,309 |
 *   | コロケーション基本動詞 | 100 | 1,466 |
 *   | 名詞句 | 120 | 2,478 |
 *   | 副詞句 | 66 | 1,024 |
 *   | **小計(単語帳の冊 + Native Flow)** | **2,173** | **28,114** |
 *   | 66 の型(日本語 → 英語) | 3,092 | 143,425 |
 *   | 66 の型(言い換え) | 2,585 | 110,518 |
 *   | **合計** | **7,850** | **282,057** |
 *
 *   ElevenLabs は1文字あたり1クレジットなので、
 *   Pro(月 600,000)に対して **小計で 4.7%・合計で 47%** である。
 *   **1回だけ**で、2回目からは置いてあるものを読むだけの 0 円(CLAUDE.md)。
 *
 *   **9割は「66 の型」である。** 66 の型は、型と束を**掛け合わせて**
 *   問を作るので(docs/notes/23)、ファイルに書いてある数より桁が1つ多い。
 *   **はじめ 39,274 文字(6.5%)と見積もったのは誤りだった** ——
 *   ファイルに書いてある行を数えていて、**掛け合わせたあとを数えていなかった。**
 *
 *   **かかるのは、本当に鳴らしたぶんだけ**である(押したときに作る)。
 *   7,850 問を全部鳴らす人はいないので、47% は**上限**であって見込みではない。
 *   減らしたいときは、`frameQrRows()` から `bookVoice()` の呼び出しを
 *   **1行外す**だけでよい(66 の型だけが標準の声に戻る)。
 *
 * 【自分の単語帳と、業種べつの棚は、これまでどおり標準の声】
 *   あちらは**教材から拾った語**なので、**増え続ける。**
 *   月 2,000 レッスンぶんの語に良い声を当てると、上の「1回だけ」が
 *   「毎月」になる(第5.2.1節・CLAUDE.md「配る数と新しく作る数を混同しない」)。
 *   **言われた冊だけを変える**(CLAUDE.md「直すのは、言われた場所だけ」)。
 *
 * 【声は1つに決め打ちする。**これを変えてはいけない**】
 *   置き場所の鍵に声の id が入っているので、
 *   **ここを別の声に変えた日に、2,342 本ぜんぶが作り直しになる**
 *   (= もう一度 39,274 クレジット)。`CLIP_REV` を進めないのと同じ理由で、
 *   **進めない。**
 *
 *   `us-1`(Jessica・アメリカ・女性)にした。
 *   **1人で読むものはぜんぶ女性**(第5.297節・利用者の指定)で、
 *   アメリカが既定の訛りである(`clipVoices.js`)。
 *
 * 【良い声を作れないときは、何も足さない】
 *   名簿に ElevenLabs の id が1つも無い / この声が引けないときは
 *   **空を返す。** そうすれば、これまでどおり標準の声で鳴る ——
 *   **段と、実際に鳴る声を食い違わせない**(`voiceTier.js` と同じ考え方)。
 *   **既定は「できない」側**(CLAUDE.md)。
 * ============================================================================
 */
import { findVoice, isBaseVoice } from '../data/clipVoices.js'
import { PREMIUM, hasPremiumVoices } from './voiceTier.js'

/**
 * **固定の冊を読む声。1か所に持つ。**
 * **変えない** —— 変えると 2,342 本が作り直しになる(上の節)。
 */
export const BOOK_VOICE = 'us-1'

/** この声で、本当に良い段を作れるか(ElevenLabs の id を持っているか) */
export const bookVoiceReady = () =>
  hasPremiumVoices()
  && !isBaseVoice(BOOK_VOICE)
  && Boolean(String(findVoice(BOOK_VOICE)?.elevenId ?? '').trim())

/**
 * 固定の冊の行に広げる声と段。
 *
 * **名前は、教材の対(`quickResponsePairs()`)と復習の帳(`qrVoiceOf()`)と
 * そろえる** —— そうすれば「聴く」も聞き流しも、
 * どこから来た行かを見分けずに鳴らせる。
 *
 * @returns {{clipVoice?: string, tier?: string}}
 *   良い声を作れないときは**空**(これまでどおり標準の声で鳴る)
 */
export const bookVoice = () =>
  (bookVoiceReady() ? { clipVoice: BOOK_VOICE, tier: PREMIUM } : {})
