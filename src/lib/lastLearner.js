/**
 * ============================================================================
 * 最後に開いていたゲストを覚えておく。**1か所**
 * ============================================================================
 *
 * 【なぜ要るか】(2026-09 実機・利用者の指摘)
 *
 *   > トレーナー側でゲストのページに入っているとき、何か一つ間違えると
 *   > すぐにゲスト一覧に飛んでしまい、ゲストと画面共有中に非常にやりにくい
 *
 * ゲストを開いたまま「教材」や「単語帳」を見に行くと、`TrainerLearners`
 * そのものが画面から外れる。開いているゲスト(`openId`)は
 * `useState` に置いてあるので、**そこで消える。**
 * 戻ってきたときには一覧に立っていて、また名前を探すことになる。
 *
 * レッスンはゲストと画面を共有しながら行うので、
 * **探し直しているところがそのまま相手に見えている。**
 *
 * 【なぜ localStorage ではないのか】
 *   これは設定ではなく、**いまの居場所**である。
 *   端末に残すと、翌日アプリを開いた瞬間に
 *   **前の日のゲストのページが開く**(画面共有の事故になりうる)。
 *   書類(モジュール)に置けば、**読み込み直せば必ず消える。**
 *   `generateJob.js` / `playMark.js` と同じ考え方。
 *
 * 【覚えないとき】
 *   左のメニューで「ゲスト」をもう一度押したとき(2026-08 の指定で
 *   一覧に戻る)と、「← ゲストの一覧に戻る」を押したときは
 *   `rememberLearner(null)` が呼ばれるので、次に来ても一覧から始まる。
 *
 * 何にも依存しない形にしてある。**素の node で確かめられる。**
 */

let openId = null

/** 開いているゲストを控える。`null` で忘れる */
export function rememberLearner(id) {
  openId = id ?? null
}

/** 最後に開いていたゲスト。無ければ `null` */
export function lastLearner() {
  return openId
}
