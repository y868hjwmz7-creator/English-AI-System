/**
 * 説明を出すかどうか(2026-09 利用者の指定)。
 *
 *   > 全てのデザインから言葉による説明を省いてください。
 *   > 目指すのは説明がない、直感的なUIです。
 *   > ここでは「上の「学ぶ分野をえらぶ」で、練習したい分野にチェックを
 *   > 入れてください。」などです。tool tipモードをオンにすれば
 *   > カーソルを当てた時にポップアップするくらいの扱いでOKです。
 *
 * 【消すのではない。既定で出さないだけ】
 *   説明そのものは1文字も消していない。**`tip` の印を付けて畳んである**ので、
 *   ここを `on` にすればその場に出る。**消して作り直さない**
 *   (「単語とフレーズの音」を閉じたときと、まったく同じ作法)。
 *
 * 【「カーソルを当てたら」ではなく「その場に出る」にした理由】
 *   このアプリは iPhone で使われる。**触る端末には「カーソルを載せる」が無い**
 *   (CLAUDE.md)。吹き出しにすると、いちばん読みたい人が読めない。
 *   利用者の言葉は「**くらいの扱いでOK**」なので、
 *   **それより届きやすい形**にしてある。
 *
 * 【何を畳んで、何を残したか】
 *   畳むのは **説明**(こう操作してください・こうなっています)だけ。
 *   **知らせ**は既定でも出す —— どれも、このリポジトリに先に書いてある決まりである。
 *
 *   ・費用(見えない費用は管理できない)
 *   ・取り消せない操作の断り
 *   ・失敗・読み込み中・0件の知らせ(成功と失敗を同じ見た目で終わらせない)
 *   ・書いたものがどこへ行くか(黙って消さない)
 *   ・教材やデータの中身(`{sec.instruction}` など)
 *
 * 色そのものと同じで、ここは「どれを選んだか」を覚えて
 * `<html>` に `data-tips` を付けるだけ。畳み方は styles.css にある。
 */
const KEY = 'eas.tips'

/** 覚えておく鍵。**画面に鍵の名前を書かない**(`TONE_KEYS` と同じ作法) */
export const TIPS_KEY = KEY

export const TIPS = [
  { id: 'off', label: '出さない', hint: '画面から説明の文を畳みます(既定)' },
  { id: 'on', label: '出す', hint: '欄やボタンの説明を、その場に出します' },
]

/**
 * いま選ばれているもの。**既定は「出さない」。**
 * 読めなくても既定に落ちるだけでよい(端末の設定で保存が禁じられていることがある)。
 */
export function loadTips() {
  try {
    const saved = window.localStorage.getItem(KEY)
    return TIPS.some((t) => t.id === saved) ? saved : 'off'
  } catch {
    return 'off'
  }
}

/** 選んだものを覚えて、画面に反映する */
export function applyTips(tips) {
  const root = document.documentElement
  // 既定(出さない)のときは印を付けない。**印が付いているときだけ出す**
  // という書き方にしておくと、説明の側を1か所も書き直さずに済む
  if (tips === 'on') root.setAttribute('data-tips', 'on')
  else root.removeAttribute('data-tips')
  try { window.localStorage.setItem(KEY, tips) } catch { /* 保存できなくても動く */ }
}
