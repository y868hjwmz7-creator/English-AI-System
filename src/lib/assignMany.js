/**
 * **いくつもの教材を、まとめて共有したときの知らせ**(第5.238節)。
 *
 * ════════════════════════════════════════════════════════════════
 * 【なぜ切り出したか】
 *
 *   まとめて共有する場所が**2つ**になった。
 *
 *     ・教材の画面(えらんだ教材 → ゲストを選ぶ)
 *     ・「アサインする」の画面(ゲスト → その他の教材)
 *
 *   どちらも「何件を、何人に、何語入ったか」を言う。
 *   **数え方と言い方を書き写すと、置き場所が食い違う**
 *   (CLAUDE.md「数え方を2通り持たない」「呼び名を2か所に書かない」)。
 *
 * 【Supabase を引き連れない】
 *
 *   窓口を呼ぶのは `materials.js` の `assignMaterials()`。
 *   ここは文だけなので、**`npm run test:play` が素の node で走らせられる**
 *   (`assignBooks.js` / `playMark.js` と同じ考え方)。
 *
 * 【0 と、出した数を取り違えない】
 *
 *   途中で断られたときに「失敗しました」とだけ言うと、
 *   **何件まで通ったのかが分からない。** 通ったぶんは、そのまま言う。
 * ════════════════════════════════════════════════════════════════
 */

/**
 * 全部通ったときの1行。
 *
 * @param done 共有できた教材の件数
 * @param people 相手の人数
 * @param extra 語数の1文(`wordsAddedNote()` が作る)。**空なら足さない**
 */
export const manyDoneText = (done, people, extra = '') => `${Number(done) || 0} 件を `
  + `${Number(people) || 0} 人と共有しました。${extra ?? ''}`

/**
 * 途中で断られたときの1行。**通ったぶんを黙って捨てない。**
 *
 * @param done そこまでに共有できた件数(0 件のこともある)
 */
export const manyStoppedText = (done, err) => `${Number(done) || 0} 件まで共有しました。`
  + `${err?.message ?? err}`
