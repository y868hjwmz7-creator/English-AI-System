/**
 * ============================================================================
 * **問題の箱をタップして、答えに切り替える**(第5.262節)
 *
 * 2026-09-26 利用者の指定。
 *
 *   > 単語帳や quick response の「英語を見る」ボタンは廃止。
 *   > 日本語の表示されているあたりをタップすれば英語に切り替わるように
 *   > してください。タップできる範囲は広めにとってください。
 *
 * ── **押せる範囲は「問題の箱ぜんぶ」**(利用者の指定)─────────────
 *
 *   番号も、話す人の名前も、日本語の行も、その上下の余白も、ぜんぶ。
 *   **狙う場所を探させない** —— 指で使う端末では、
 *   小さいボタンを狙わせること自体が手間である。
 *
 * ── **伏せているときは、本物の `<button>`** ───────────────────
 *
 *   中に押せるものが1つも無いので、**そのまま `<button>` にできる。**
 *   こうすると、キーボードでも読み上げでも**ふつうに押せる** ——
 *   `div` に `role="button"` を付けて回るより、ずっと確かである。
 *
 * ── **出したあとは、中の押せるものを踏まない押しだけ** ─────────────
 *
 *   答えの側には**語ごとに押せる `<button>`**(`EnglishText`)が並ぶ。
 *   箱ごと `<button>` にすると、**押せるものの中に押せるものが入る** ——
 *   正しくない作りだし、語を押したつもりが問題に戻ってしまう。
 *
 *   だから出したあとは素の入れ物にして、**押された場所を見る。**
 *   押せるものを踏んでいたら、切り替えない(`tapToggles`)。
 *
 * ── ここは算段だけ。Supabase も React も持たない ────────────────
 *
 *   **素の node で走らせられる形にしてある**(`playMark.js` と同じ作法)。
 * ============================================================================
 */

/**
 * **タップで切り替えられる出し方**(単語帳)。
 *
 * 2026-09-26 利用者の指定で、**4択は入らない** ——
 * あちらは選択肢を押して答える形で、**切り替える余地がそもそも無い**
 * (「英語を見る」も、もとから出ていない)。
 *
 * **並べ替えない。減らさない**(共通ルール)。
 */
export const TAP_FORMS = ['ja2en', 'recall', 'cloze']

/** その出し方は、タップで切り替えられるか。**判断はここ1か所** */
export const canTapReveal = (form) => TAP_FORMS.includes(form)

/**
 * **中の押せるもの。** ここを踏んだ押しは、切り替えにしない。
 *
 * `summary` まで入れてあるのは、**畳みの札も押せるもの**だからである
 * (単語帳の「出会った文」が `<details>` である)。
 */
export const REVEAL_SKIP
  = 'button, a, select, input, textarea, label, summary, [role="button"]'

/**
 * その押しは、切り替えにあたるか。
 *
 * @param target 押された要素(`e.target`)
 * @returns 押せるものを踏んでいなければ真
 *
 * **`closest` を持たない相手でも落ちない** —— 文字のかたまり
 * (テキストノード)が来ることがあるし、素の node で確かめるときは
 * 偽物を渡す。**分からなければ「切り替える」に倒す**
 * (押したのに何も起きない、を作らない)。
 */
export function tapToggles(target) {
  if (!target || typeof target.closest !== 'function') return true
  return !target.closest(REVEAL_SKIP)
}

/**
 * 読み上げに添える名前(「英語を見る」「意味を隠す」)。
 *
 * **画面で書き分けない。** もとは3つの画面がそれぞれ
 * `form === 'ja2en' ? … : …` と書いていて、**片方だけ古くなる形**だった。
 *
 * @param shown いま答えが出ているか
 * @param kind  `'en'`(英語)/ `'ja'`(意味)/ `'answer'`(答え)
 */
export function revealLabel(shown, kind = 'en') {
  const what = kind === 'ja' ? '意味' : kind === 'answer' ? '答え' : '英語'
  return `${what}を${shown ? '隠す' : '見る'}`
}

/**
 * 単語帳の出し方から、**何が出てくるのか**を決める。
 *
 * - 日本語 → 英語 / 穴埋め … 伏せてあるのは**英語**
 * - 思い出す              … 伏せてあるのは**意味**
 *
 * **判断はここ1か所**(画面で `form === 'ja2en'` と書かない)。
 */
export const revealKindOf = (form) => (form === 'recall' ? 'ja' : 'en')
