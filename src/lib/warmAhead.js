/**
 * **次に鳴らすものを、先に温める**(第5.443節・2026-10-10 利用者の指摘)。
 *
 *   > どうしても単語帳と quick response の音声のロードが遅いです。
 *   > 初めてだと3-4秒かかります。もっと速くならないものですか？
 *
 * ============================================================================
 * 【なぜ 3〜4 秒かかっていたか】
 *
 *   **単語帳と Quick Response は、先読みを1度も呼んでいなかった。**
 *   「聴く」を押した**その瞬間に**窓口へ頼み、窓口が声を作り、
 *   置き場所へ上げ、それから鳴る。教材の画面(`LessonView`)と
 *   聞き流し(`WordRadio`)には先読みが入っていたのに、
 *   **練習の2画面だけが抜けていた。**
 *
 *   ※ **2回目からは 0 円で、すぐ鳴る**(置いてあるものを読むだけ)。
 *     遅いのは「その語を、学校じゅうで誰も1度も鳴らしていない」ときである。
 *
 * 【直し方 —— カードを出した時点で、先を温める】
 *
 *   人がカードを見て、思い出して、答えるまでに数秒ある。
 *   **その数秒を使う。** 押したときには、もう置いてある。
 *
 * 【費用は1円も増えない】
 *   温めるのは**どのみち次に出るもの**である。置いてあれば問い合わせだけ、
 *   無ければ**どのみち押されたときに作る**ものを、先に作るだけである
 *   (`prepareRead()` の節と同じ考え方)。
 *
 * 【どこまで先を温めるか】
 *   **1つ先では足りない**(すぐ押す人がいる)。**多すぎても困る** ——
 *   答えずに閉じた人のぶんが、まるごと無駄になる。
 *   **いま出ているもの + 3つ先**にしてある。
 *
 * ============================================================================
 * **ここは算段だけ。** 鳴らす側(`prepareRead()`)も、英文の取り出し方
 * (`radioTextOf()`)も**よそ1か所**から借りる —— 書き写すと、
 * 画面と温める場所で**別のものを指す**(CLAUDE.md「数え方を2通り持たない」)。
 */
import { radioTextOf } from './wordRadio.js'

/** いま出ているものを入れて、**何本**温めるか */
export const WARM_AHEAD = 4

/**
 * 温める英文を選ぶ。
 *
 * - **いま出ているものも入れる** —— 開いた直後、まだ誰も温めていない
 * - **同じ英文は1回だけ**(同じ語が2回出る回がある)
 * - **末尾では先頭へ回り込む** —— 「次へ」が回り込むのと同じ決まり
 *   (`nextIndex`)。回さないと、最後の数枚で温まらない
 * - 読むものが無い行は飛ばす(`radioTextOf()` が空を返す)
 * - **数えるのは「位置」ではなく「本数」。** 空の行や同じ語が続いても、
 *   温める本数は減らない(**いちばん危ない形で測る**・CLAUDE.md)
 *
 * @param {Array<object>} list いま回している一覧
 * @param {number} at いま出ているものの位置
 * @param {number} want 何本(既定 `WARM_AHEAD`)
 * @returns {Array<string>} 温める英文(重複なし・出す順)
 */
export function warmTargets(list, at = 0, want = WARM_AHEAD) {
  const 一覧 = Array.isArray(list) ? list : []
  const 丈 = 一覧.length
  if (!丈) return []
  const 本数 = Math.max(0, Math.trunc(Number(want) || 0))
  const 頭 = ((Math.trunc(Number(at) || 0) % 丈) + 丈) % 丈
  const 見た = new Set()
  const 出 = []
  /* **一覧より多くは回らない**(止まる条件を持たせる・CLAUDE.md) */
  for (let i = 0; i < 丈 && 出.length < 本数; i++) {
    const t = radioTextOf(一覧[(頭 + i) % 丈])
    if (!t || 見た.has(t)) continue
    見た.add(t)
    出.push(t)
  }
  return 出
}
