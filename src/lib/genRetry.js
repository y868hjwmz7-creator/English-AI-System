/**
 * ============================================================================
 * **通信が途中で切れたときの、やり直しと知らせ**(第5.197節)
 *
 * 2026-09 実機。利用者が Speech練習を作ろうとして、こう出た。
 *
 *   > Speech練習を作れませんでした。内容の理解を作れませんでした。
 *   > 生成の窓口につながりませんでした。
 *   > Supabase に generate-material を配置したか確認してください。
 *
 * **配置はしてあった。** Supabase の画面で確かめてもらったところ、
 *
 *   ・`generate-material` は6日前から置いてある
 *   ・配置してから **172 回呼ばれて、5XX は 0%**(関数は落ちていない)
 *   ・プロジェクトは **Healthy**(止まっていない)
 *
 * **つまり、あの1文は嘘だった。** 利用者に無駄な確認をさせている。
 *
 * ── なぜ、こんな知らせになっていたか ────────────────────────────
 *
 *   窓口は **150秒で切られないように、先に 200 を返してから**
 *   答えができるまで空白を送り続ける(`generate-material` の `streamed()`)。
 *   だから **Supabase から見れば、どの呼び出しも「200 で正常終了」**である。
 *   途中で切れたことは、**呼んだブラウザの側にしか分からない。**
 *
 *   ブラウザに届くのは「返事を受け取れなかった」という1つだけで、
 *   **未配置なのか、途中で切れたのかを、その場では見分けられない**
 *   (`docs/notes/04-起動と窓口と通信.md` に 2026-08 から書いてあった。
 *   **書いてあったのに、文言を直していなかった**)。
 *
 * ── どうやって見分けるか ──────────────────────────────────────
 *
 *   **見分けられる材料は、すでに持っていた。**
 *   アプリは開いたときに窓口へ版を訊きに行っている(`checkGenGateway`)。
 *
 *     版が分かっている → 窓口は**確かに置いてある**。切れたのは通信
 *     版が分からない   → 置いていない**かもしれない**。両方を言う
 *
 *   **分かっていることだけを言う。** 一方に決めつけない。
 *
 * ── なぜ、やり直すのか ────────────────────────────────────────
 *
 *   教材づくりは 30秒〜2分かかる。iPhone は**画面が消えたり裏に回ったり
 *   すると、途中の通信を打ち切る。** 1分待つあいだにロックがかかるのは、
 *   まったく普通のことである。
 *
 *   **やり直しは課金になる**(切れたぶんも、窓口の側では走りきって
 *   Claude に課金されていることがある)。それでも入れるのは、
 *   **押し直すほうが高くつく**からである ——
 *   押し直しは**その教材を最初の段からぜんぶ**作り直すことになる。
 *   切れた1段だけをやり直すほうが、必ず安い。
 *
 *   **1回だけ。** 止まる条件を持たせる(CLAUDE.md「費用」)。
 *   **切れたときだけ。** 断られた(4XX / 5XX)ものは、もう一度送っても
 *   同じように断られる。**同じ金を二度払うだけ**である。
 *
 * ── なぜ、この形で切り出すか ──────────────────────────────────
 *
 *   `materials.js` は Supabase と `import.meta.env` を引き連れており、
 *   **手元で一度も走らせられない。** 算段だけを何にも依存しない形へ出す
 *   (CLAUDE.md「素の node で走らせられる形に切り出す」)。
 *   待ち時間も外から差せるので、**検証は一瞬で終わる。**
 * ============================================================================
 */

/** 何回送るか(はじめの1回 + やり直し1回)。**増やさない** */
export const GEN_TRIES = 2

/** やり直すまでの待ち(ミリ秒)。一瞬の途切れが直るだけの間を置く */
export const GEN_RETRY_WAIT = 1500

/**
 * **返事を1つも受け取れなかったか。**
 *
 * supabase-js は、通信そのものが失敗したときだけ `FunctionsFetchError`
 * (文面は "Failed to send a request to the Edge Function")を返す。
 * 断られたとき(4XX / 5XX)は別の形で来るので、ここには入らない。
 *
 * **見分けを広げない。** ここを緩めると、断られたものまで
 * 「切れた」と読んで**もう一度課金する**ことになる。
 */
export const isGenCut = (error) =>
  /Failed to send a request|FunctionsFetchError/i.test(error?.message ?? '')

/**
 * 切れたときに、押した場所へ出す1文。
 *
 * **画面にそのまま出る文字列なので、`**` を混ぜない**(CLAUDE.md)。
 *
 * @param what 何ができなかったか(「教材の生成」「添削」など)
 * @param rev  窓口の版。**分かっていれば、窓口は確かに置いてある**
 */
export const genCutNote = (what, rev) => (rev
  ? `通信が途中で切れたため、${what}ができませんでした`
    + `(${GEN_TRIES}回試しました)。`
    + '画面を消したり、ほかのアプリに切り替えたりすると、'
    + 'iPhone は途中の通信を打ち切ります。'
    + '画面をつけたまま、もう一度お試しください。'
  : `${what}の窓口に、一度もつながりませんでした`
    + `(${GEN_TRIES}回試しました)。`
    + '通信が切れているか、Supabase に generate-material が'
    + '置かれていない可能性があります。')

/** 既定の待ち方。検証からは差し替える(待たせない) */
const sleep = (ms) => new Promise((done) => { setTimeout(done, ms) })

/**
 * 窓口を呼ぶ。**切れたときだけ、1回だけやり直す。**
 *
 * @param {(n: number) => Promise<{data: any, error: any}>} call
 *   実際に送る。**何回目か**を受け取る(1 から)
 * @param {{wait?: (ms: number) => Promise<void>}} o
 * @returns {Promise<{data, error, cut, tries}>}
 *   `cut` … 返事を1つも受け取れなかった / `tries` … 実際に送った回数
 */
export async function askWithRetry(call, { wait = sleep } = {}) {
  let last = null
  for (let n = 1; n <= GEN_TRIES; n += 1) {
    if (n > 1) await wait(GEN_RETRY_WAIT)
    const got = await call(n)
    // **断られたときも、来たものはそのまま返す。**
    // ここで文面を作ると、窓口ごとの言い分を落としてしまう
    if (!got?.error) return { ...got, cut: false, tries: n }
    last = { ...got, cut: isGenCut(got.error), tries: n }
    if (!last.cut) break
  }
  return last
}
