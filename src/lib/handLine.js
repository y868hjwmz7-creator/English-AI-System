/**
 * ============================================================================
 * **手で描いた線**(第5.375節・2026-10-05)
 *
 *   利用者から、手描きのアイコン集の写真が2度届いた。
 *   こちらの絵と並べて、**違いは題材ではなく「描き方」**だと分かった。
 *
 *     | あちら | こちら(直す前) |
 *     |---|---|
 *     | **線が震えている** | 定規で引いたようななめらかな曲線 |
 *     | **左右がそろっていない** | きっちり左右対称 |
 *
 *   ここは、その**震え**だけを作る。
 *
 * ── **手で1本ずつ揺らさない** ───────────────────────────────
 *
 *   12 人ぶんの線を手で歪ませると、**足した1人だけ妙にきれい**になる。
 *   揺れの作り方を**ここ1か所**に持たせて、形のほうは素直に書く。
 *
 * ── **同じ種なら、いつも同じ形**(ここが大事) ───────────────
 *
 *   `Math.random()` を使うと、**描き直すたびに形が変わる。**
 *   画面を触るたびに相棒が歪み直すのは、気味が悪いだけである。
 *   **種から決まる数**にして、同じ相棒はいつも同じ顔にする。
 *
 * ── **素の node で走る** ────────────────────────────────────
 *
 *   `npm run test:feel` が、画面を描かずに
 *   「本当に震えているか」「同じ種なら同じか」を確かめられる。
 * ============================================================================
 */

/** 種から決まる数(0〜1)。**同じ種なら、いつも同じ並び** */
function 数(seed) {
  let s = (Math.abs(Math.trunc(seed)) % 2147483647) || 1
  return () => {
    s = (s * 48271) % 2147483647
    return s / 2147483647
  }
}

/**
 * 点を少しずつずらす。**これが「手の震え」である。**
 * @param {Array<[number, number]>} pts
 * @param {number} seed 相棒ごとに違う種
 * @param {number} amp どれくらい震えるか(px)
 */
export function ゆらす(pts, seed, amp = 1.3) {
  const r = 数(seed)
  return (pts ?? []).map(([x, y]) => [
    x + (r() - 0.5) * amp * 2,
    y + (r() - 0.5) * amp * 2,
  ])
}

/**
 * 点を**なめらかに結んで閉じる。**
 * 点をそのまま直線で結ぶと、**折り紙のように角ばる** ——
 * 中点を通る曲線にすると、手で一筆書きした線に見える。
 */
export function 閉じる(pts) {
  const n = (pts ?? []).length
  if (n < 3) return ''
  const 中 = (a, b) => [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2]
  const f = (v) => Math.round(v * 10) / 10
  const m0 = 中(pts[n - 1], pts[0])
  let d = `M ${f(m0[0])} ${f(m0[1])}`
  for (let i = 0; i < n; i += 1) {
    const c = pts[i]
    const m = 中(pts[i], pts[(i + 1) % n])
    d += ` Q ${f(c[0])} ${f(c[1])} ${f(m[0])} ${f(m[1])}`
  }
  return `${d} Z`
}

/**
 * 丸い輪郭の点を並べる。**きれいな円は1つも使わない。**
 * @param {number} n いくつの点で描くか(少ないほど、ごつごつする)
 */
export function まる(cx, cy, rx, ry, n = 13, 回し = 0) {
  const out = []
  for (let i = 0; i < n; i += 1) {
    const t = 回し + (i / n) * Math.PI * 2
    out.push([cx + Math.cos(t) * rx, cy + Math.sin(t) * ry])
  }
  return out
}

/** 震えた丸を、そのまま線にする(いちばんよく使う形) */
export function 手のまる(cx, cy, rx, ry, seed, { n = 13, amp = 1.3, 回し = 0 } = {}) {
  return 閉じる(ゆらす(まる(cx, cy, rx, ry, n, 回し), seed, amp))
}

/**
 * **四角の点を並べる。** 角に点を1つずつ置いただけだと、
 * `閉じる` が**辺の半分ぶんを丸めて、ただの楕円になる**
 * (ぬりかべが「壁」に見えなかった・第5.376節。描いて分かった)。
 * **辺の途中にも点を置く**と、角だけが少し丸い四角のまま残る。
 * @param {number} 刻み 1辺を何個の点で持つか(多いほど角が立つ)
 */
export function 四角(x1, y1, x2, y2, 刻み = 3) {
  const out = []
  const 辺 = (ax, ay, bx, by) => {
    for (let i = 0; i < 刻み; i += 1) {
      const t = i / 刻み
      out.push([ax + (bx - ax) * t, ay + (by - ay) * t])
    }
  }
  辺(x1, y1, x2, y1)
  辺(x2, y1, x2, y2)
  辺(x2, y2, x1, y2)
  辺(x1, y2, x1, y1)
  return out
}

/** 震えた四角(壁・下駄・腰巻のように、角が要るもの) */
export function 手の四角(x1, y1, x2, y2, seed, { amp = 1, 刻み = 3 } = {}) {
  return 閉じる(ゆらす(四角(x1, y1, x2, y2, 刻み), seed, amp))
}

/** 震えた好きな形(点を自分で並べたいとき) */
export function 手の形(pts, seed, amp = 1.3) {
  return 閉じる(ゆらす(pts, seed, amp))
}

/**
 * 震えた**開いた線**(ひげ・触角・ひびなど)。
 * 閉じないので、`閉じる` は通さない。
 */
export function 手の線(pts, seed, amp = 1.1) {
  const p = ゆらす(pts, seed, amp)
  const f = (v) => Math.round(v * 10) / 10
  if (p.length < 2) return ''
  let d = `M ${f(p[0][0])} ${f(p[0][1])}`
  for (let i = 1; i < p.length - 1; i += 1) {
    const m = [(p[i][0] + p[i + 1][0]) / 2, (p[i][1] + p[i + 1][1]) / 2]
    d += ` Q ${f(p[i][0])} ${f(p[i][1])} ${f(m[0])} ${f(m[1])}`
  }
  const e = p[p.length - 1]
  return `${d} L ${f(e[0])} ${f(e[1])}`
}
