/**
 * 自分のアイコンとして選べるもの(2026-09 利用者の指定)。
 *
 *   > 空いたスペースには、ゲストが選んだアイコンを入れれるとよいです。
 *
 * 【なぜ絵文字なのか】
 *   このアプリでは、ふだん**絵文字を使わない**(CLAUDE.md)。
 *   端末ごとに形も色も違い、隣の文字と大きさがそろわないためである。
 *
 *   **アイコンだけは別。** ここで出すのは文字の中の飾りではなく、
 *   **その人を表す絵そのもの**で、丸の中に1つだけ置く。
 *   隣の文字とそろえる必要がないので、端末ごとの違いは害にならない。
 *   写真を上げてもらう形にすると、置き場所(Storage)も要り、
 *   **顔写真は個人情報**になる。選ぶだけなら、その心配がない。
 *
 * 【並べ方】
 *   組ごとに分けてある。30個以上を1つの箱に並べると、
 *   「何があるのか」が読み取れない。
 *
 * 【印そのものを保存する】
 *   `profiles.avatar` に**この文字をそのまま**入れる(0029)。
 *   id と絵の対応表を持つと、表を書き換えたときに
 *   すでに選んだ人の絵が変わってしまう。
 */
export const AVATAR_GROUPS = [
  { label: 'いきもの', items: ['🐶', '🐱', '🐼', '🐨', '🦊', '🐧', '🐤', '🦉', '🐢', '🐬', '🦋', '🐝'] },
  { label: 'しぜん', items: ['🌷', '🌻', '🌲', '🍀', '🌙', '⭐', '🌈', '⛰️'] },
  { label: 'たべもの', items: ['🍎', '🍓', '🍰', '🍩', '☕', '🍵'] },
  { label: 'すきなこと', items: ['⚽', '🎾', '🏀', '🎸', '🎹', '📚', '🎨', '✈️', '🚲', '📷'] },
]

/** 全部をひとつなぎにしたもの(選べるかどうかの判定に使う) */
export const AVATARS = AVATAR_GROUPS.flatMap((g) => g.items)

/**
 * 名前から作る「頭文字」。**アイコンを選んでいない人のため。**
 *
 * 空の丸を置くと、選び忘れなのか読み込み中なのか分からない。
 * 頭文字なら、選んでいなくても**誰のカードかが分かる。**
 */
export const initialOf = (name) => {
  const s = (name ?? '').trim()
  if (!s) return '?'
  // 絵文字や結合文字で切れないよう、文字の単位で1つ取る
  return [...s][0]
}
