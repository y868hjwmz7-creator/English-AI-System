/** 本文を1本作る種類(記事・会話・会議)かどうか。問数ではなく長さで考える */
export const isPassageKind = (kind) =>
  kind === 'reading' || kind === 'dialogue' || kind === 'meeting'
  || kind === 'speech'

/**
 * **会話の形をした種類**(会話・会議)かどうか。
 *
 * この2つは中身が同じで、**出てくる人数だけが違う。**
 * だから「話す人を選ぶ」「場面を選ぶ」「発言で数える」は、どちらにも要る。
 * **`kind === 'dialogue'` と書かない。** 書くと会議で必ず抜ける。
 */
export const isDialogueKind = (kind) => kind === 'dialogue' || kind === 'meeting'

/**
 * **語句をならべる種類**(単語 / フレーズ)かどうか。
 *
 * 2026-09 に `word` と `phrase` を `vocab` 1つにまとめた(0047)が、
 * **旧い2つで作った教材はそのまま残っている。**
 * だから「単語帳から名指しで渡された語を先頭から使う」
 * 「これまでの宿題から復習する語を混ぜる」は、3つとも同じに効かせる。
 *
 * **`kind === 'word'` と書かない。** 書くと `vocab` で必ず抜ける
 * (会議で `kind === 'dialogue'` と書いて踏んだのと同じ落とし穴)。
 */
export const isVocabKind = (kind) =>
  kind === 'vocab' || kind === 'word' || kind === 'phrase'

/**
 * **文型ドリル**かどうか(2026-09)。
 *
 * ここだけ「使う語を、単語帳から絞って指定する」欄が出る
 * (利用者の指定「文型トレーニングに、どの単語帳からどのレベルの
 * どの品詞を使用するか、を指定できるようにしたい」)。
 *
 * **画面の中で `kind === 'pattern'` と書かない。**
 * 置く場所の数だけ食い違う(`isDialogueKind` と同じ考え方)。
 */
export const isDrillKind = (kind) => kind === 'pattern'

/** 画面に出す短い呼び名(「記事」「会話」「会議」「スピーチ」)。文の中で使う */
export const bodyWord = (kind) => (
  kind === 'reading' ? '記事'
    : kind === 'meeting' ? '会議'
      : kind === 'speech' ? 'スピーチ'
        : '会話'
)

/**
 * **場面(シチュエーション)を選ぶ種類**かどうか。
 *
 * 記事は「話題(ジャンル)」、会話・会議・スピーチは「場面」で選ぶ。
 * **`isDialogueKind` を流用しない。** あれは
 * 「話す人が2人以上いる」ことを意味しており、
 * スピーチ(1人)に当てると人数の欄まで一緒に出てしまう。
 */
export const usesScene = (kind) => isDialogueKind(kind) || kind === 'speech'

/**
 * **「細かい指定」に書いたら、それが主になる**(第5.232節・2026-09 利用者の指摘)。
 *
 *   > ダイアローグや会議、モノローグ、記事で内容の詳細を指定しているのに、
 *   > 「切り口」や他の選択肢の要素が強制的に選ばれてしまうので
 *   > 意図しない話になってしまいます。たとえば一番新しい教材は、
 *   > 唐揚げの加工工場の話だと指定したら、「悪い知らせをする」という
 *   > 切り口が強制的に選ばれ、そのような話になってしまいました。
 *
 * 場面・話題(ジャンル)・切り口は、どれも**どんな話にするか**を決める欄で、
 * 細かい指定と**同じ役目**である。両方を渡すと、書いた中身と食い違うものが
 * 勝手に混ざる。
 *
 * **判断はここ1か所。** 画面の中で `kind === 'speech' && subject…` と
 * 書かない(CLAUDE.md「判断は1か所に持つ」)。
 * **既定は「選ぶ」側** —— 細かい指定が空なら、これまでどおりである。
 *
 * 第5.228節はモノローグの場面だけに当てていた。**同じ困り方が
 * 会話・会議・記事でも起きていた**ので、本文を持つ4種類すべてに広げた。
 */
export const freeFromSubject = (kind, subject) =>
  isPassageKind(kind) && String(subject ?? '').trim().length > 0

