/**
 * **ゲストごとに「出すもの」を決める**(0055・2026-09 利用者の指定)。
 *
 *   > ゲストの画面から
 *   > 基礎英文法講座と基本単語を取り除いてください。
 *   > これは、トレーナー側から指定したゲストにのみ映るようにしてください
 *
 * ============================================================================
 * 【なぜ一覧をここに置くのか】
 *
 *   入れ物(`learner_features`・0055)には**名前の一覧を持たせていない。**
 *   持たせると、1つ足すたびに SQL を貼り直してもらうことになる
 *   (`material_sections_type_check` で二度踏んだ落とし穴)。
 *   だから**名前の一覧は、ここ1か所だけ**が持つ。
 *
 * 【なぜ `src/lib/` ではないのか】
 *
 *   あちらは Supabase を引き連れていて、**素の node で一度も走らせられない**
 *   (`playMark.js` / `mp3Join.js` と同じ考え方)。
 *   一覧と**判断**はここに置き、`npm run test:play` が確かめる。
 *
 * 【既定は「出さない」】
 *
 *   役割が分からないうち(読み込みの途中・引けなかったとき)も出さない。
 *   `canSeeSystemDetail()` / `canAskReview()` とまったく同じ作法である。
 */

/** 文法30日集中講座 + 基礎単語(0052 / 0053)。**2つで1つ** */
export const BASICS = 'basics'

/**
 * **型の Quick Response 帳**(第5.179節・2026-09 利用者の指定)。
 *
 *   > Native Flow や 14 の型は指定したゲストにだけ出るようにしたいです。
 *
 * Native Flow は Unit ごとに `nf:<番号>` で出し分けている(0055)。
 * こちらは**冊まるごと1つ**なので、名前も1つでよい。
 * **名前はここ1か所**(画面にも `frameQr.js` にも書き写さない)。
 */
export const FRAME_QR = 'frame'

/**
 * トレーナーが、ゲストごとに出す / 出さないを決められるもの。
 *
 * **足したら、ここに1行足すだけでよい**(SQL は要らない)。
 * `npm run test:play` が、id の重なりと文言を見張る。
 */
export const LEARNER_FEATURES = [
  {
    id: FRAME_QR,
    /** **どちらの帳面の冊か**(第5.181節)。画面で振り分けない */
    group: 'qr',
    label: '14 の型(Quick Response)',
    /* **どこに出るのかまで書く。** 「出しました」だけでは、
       ゲストがどこを開けば練習できるのか分からない(`ShelfBuilder` と同じ) */
    hint: '日本語 → 英語(2,872 問)と、言い換え(2,585 問)です。'
      + 'このゲストの Quick Response の本棚に「14 の型」が出ます。',
  },
  {
    id: BASICS,
    group: 'word',
    label: '文法30日集中講座と基礎単語',
    /* **2つを別々に出さない。** 利用者は「単語と基礎的な文法の仕組みを」と
       言っており、別々に置くと片方だけやって終わる(0052 の決まり) */
    hint: 'Pre-Basic・Basic の人向けです。左のメニューの「30日講座」と、'
      + '単語帳の「基礎単語から入れる」が、このゲストの画面に出ます。',
  },
]

/** id から1行を引く。知らない id は `null`(**当てずっぽうで返さない**) */
export function featureOf(id) {
  return LEARNER_FEATURES.find((f) => f.id === id) ?? null
}

/**
 * **その帳面の冊だけを並べる**(第5.181節・2026-09 利用者の指定)。
 *
 *   > 新しい冊をアサインするのは各ゲストの単語帳もquick response帳、
 *   > もしくは「アサインする」の機能を作り…
 *
 * 決める場所と、出る場所をそろえる —— 基礎単語は**単語帳のタブ**、
 * 型の冊は **Quick Response のタブ**に出す。
 * **画面の中で `id === 'basics'` と書き分けない**(置く場所の数だけ食い違う)。
 *
 * **知らない組を渡したら空。** 当てずっぽうで全部返さない
 * (既定は「出さない」側・CLAUDE.md)。
 */
export const featuresIn = (group) => LEARNER_FEATURES.filter((f) => f.group === group)

/**
 * **文法30日集中講座と基礎単語を、この人に出すか。**
 *
 * 判断はここ1か所。画面の中で `role === 'learner'` と書かない ——
 * 置く場所の数だけ食い違う(`remakeModeOf()` / `canAskReview()` と同じ)。
 *
 * - **ゲスト以外には、これまでどおり出す。**
 *   言われたのは「**ゲストの画面から**取り除く」であって、
 *   トレーナー自身の単語帳の話ではない(トレーナーも日々英語を学んでいる)
 * - **ゲストには、トレーナーが入れたときだけ出す**
 * - **役割が分からないうちは出さない**(既定は「出さない」)
 *
 * @param role     `profiles.role`(分からなければ null)
 * @param features 開いているものの集合(`Set`)。読めていなければ null
 */
export function showsBasics({ role = null, features = null } = {}) {
  if (role && role !== 'learner') return true
  return !!features && features.has(BASICS)
}

/**
 * **型の Quick Response 帳を、この人に出すか**(第5.179節)。
 *
 *   > Native Flow や 14 の型は指定したゲストにだけ出るようにしたいです。
 *
 * **形は `showsNfUnit()` とまったく同じ**にしてある ——
 * あちらと同じ「Quick Response の冊」であり、利用者の指定も同じ
 * (指定したゲストにだけ / **トレーナーには既定で出す**)。
 *
 * **棚(`showsShelf`)には寄せない。** あちらは 2026-09 の指定で
 * トレーナーも「出された冊だけ」になった —— 指定がはっきり分かれている
 * (CLAUDE.md「似ているからと、あちらに寄せない」)。
 *
 * - **ゲスト以外(トレーナー・管理者)には出す**
 * - **ゲストには、トレーナーが出したときだけ**
 * - **役割が分からないうちは出さない**(既定は「出さない」側)
 */
export function showsFrameQr({ role = null, features = null } = {}) {
  if (role && role !== 'learner') return true
  return !!features && features.has(FRAME_QR)
}
