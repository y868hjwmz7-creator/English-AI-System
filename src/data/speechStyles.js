/**
 * **話し方の型**(2026-09 利用者の指定)。
 *
 *   > あと、著名人のスピーチなどを教材にできませんか?
 *   > イーロンマスク、スティーブ・ジョブスなどビジネスから
 *   > 映画スター、スポーツ選手など
 *
 * ============================================================================
 * 【なぜ「原稿そのもの」を入れないのか】
 *
 *   有名なスピーチの原稿には**著作権がある。** 全文を教材に入れて
 *   ゲストへ共有するのは複製と配布にあたり、引用の範囲を超える。
 *   声も同じで、**実在の人物の声は作らない**(ElevenLabs の声は
 *   許諾のある声優の声である・`clipVoices.js`)。
 *
 * 【では何を学ぶのか ——「話し方の型」である】
 *
 *   利用者が本当に真似したいのは、原稿の**文言**ではなく
 *   **話し方**である。1文をどれくらい短く切るか、数字をいくつ出すか、
 *   物語から入るか結論から入るか、間をどこに置くか。
 *   **そこは著作物ではない。** だから型だけを取り出して、
 *   **AI に新しい原稿を書かせる。**
 *
 * 【決まりごと】
 *
 *   ・**実在の人物の名前を書かない。** 型は「どの世界の話し方か」
 *     (製品発表・試合前・授賞式)で示す。人名を入れると、
 *     その人の言葉をなぞらせることになる
 *   ・**場面(`SPEECH_SCENES`)とは役目が違う。**
 *     あちらは「どこで話すか」、こちらは「どう話すか」。
 *     だから掛け合わせられる(学会発表を、物語で語る、など)
 *   ・**id は保存しない。** 型は原稿の書き方に効くだけで、
 *     出来上がった本文は教材に残る。**表も列も増やさない**
 *     (話し手の名前・会社名と同じ扱い)
 *   ・**何にも依存しない**ので、`npm run test:play` が
 *     名前と説明を機械的に見張れる(`speechDraft.js` と同じ考え方)
 */

