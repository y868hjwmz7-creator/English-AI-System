/**
 * ============================================================================
 * **「応答」が、本当に応答になっているか**(第5.344 / 5.346 / 5.357節)
 *
 * ── はじめ(2026-10-02・第5.344節)——「独り言はなし」 ──────────
 *
 *   > 変ですよね、独り言はなしにしましょう！
 *   > 純粋に応答としてふさわしいものを解答にします
 *
 *   実機ではこの2つが出ていた。**どちらも応答になっていない。**
 *
 *     | 読み上げた英文 | 正解 | 何が起きているか |
 *     |---|---|---|
 *     | Mom, I want to show you my new dance moves! | Look at me. | **同じ子どもの続きのセリフ** |
 *     | Will you be paying with cash or credit card today? | Cash or charge? | **同じ店員の言い換え** |
 *
 *   そこで「**話す人が必ず入れ替わる**」と書いた。
 *
 * ── いま(2026-10-03・第5.357節)—— **続きも認める。ただし自然に** ──
 *
 *   > 「応答問題」のはずなのに、「自分の発言→プラスアルファで似たような
 *   > ことを言い換え」になっている設問がかなり多く散見されます。
 *   > それはそれで意図は見えるので良いのですが、
 *   > **それであればもっと自然になるようにしてください。**
 *
 *   **利用者が、自分の前の指定を広げた。**
 *   禁じるのをやめ、**何があれば自然になるか**を書く。
 *
 *     | | 形 | 自然になる条件 |
 *     |---|---|---|
 *     | ① | **応答**(話す人が入れ替わる) | 基本。これが作れるならこちら |
 *     | ② | **言い足し**(同じ人が続ける) | **前の1文に無い中身を1つ足す** + **ふだんのつなぎ方で始める** |
 *
 *   **おうむ返しは、どちらの形でも禁じたまま。**
 *   上の2つの実例は、**どちらも「新しいことが1つも増えていない」** ——
 *   そこが悪かったのであって、「同じ人が話した」ことが悪かったのではない。
 *
 * ── **決まりは2つある。混ぜない** ─────────────────────────
 *
 *   | 定数 | 誰が使うか | なぜ |
 *   |---|---|---|
 *   | `REPLY_RULE` | **応答問題**(0073・`responseDrill.js`) | 利用者が②を認めた |
 *   | `REPLY_RULE_SWAP` | **TOEIC L&R Part 2**(`examPrep.js`) | **本番が「2人の会話」と決まっている。** 広げると試験対策にならない |
 *
 *   **広げるのは、言われた場所だけ**(CLAUDE.md)。
 *   **両方に効く決まり**(おうむ返し禁止・読み上げに答えを入れない)は
 *   `共通` 1か所に置く —— **2か所に書くと、必ず片方だけ古くなる。**
 *
 *   **何も取り込んでいない。** `examPrep.js` は
 *   「Supabase を引き連れない」ことを約束しているので、
 *   ここも**同じく何も取り込まない**まま保つこと。
 * ============================================================================
 */

/**
 * **どちらの形でも守ること。**
 *
 * **欄の名前をここに書いているのは、2つとも同じ欄だからである**
 * —— 片方だけ別の欄になった日は、呼ぶ側が差し替える。
 */
const 共通 = [
  /* ★ **おうむ返しは、どちらの形でも禁じる**(第5.344節のまま)。
       **「同じ人が話した」ではなく「新しいことが増えていない」**で言う ——
       第5.357節で②を認めたので、話す人では見分けられなくなった */
  '**どちらの形でも、同じことを言い直すだけにしない。**',
  'answer には、audio_text に**書いていない中身が必ず1つ**要る',
  '（例:「Will you be paying with cash or credit card today?」→',
  '「Cash or charge?」は、同じ店員が同じことを言い直しているだけで、',
  '**新しいことが1つも増えていない**。',
  '「Mom, I want to show you my new dance moves!」→「Look at me.」も同じで、',
  '**言い換えただけ**である）。',
  /* ★ **答えを読み上げの中に入れない**（第5.350節・2026-10-02 実機の指摘）。

       > 読み上げられる分の最後に、回答となるはずのフレーズが
       > 丸ごと入ってしまっているケースが多いです

     「おうむ返しにしない」の**次の段**である ——
     あちらは「言い換えて繰り返す」だったが、こちらは
     **answer をそのまま audio_text の末尾に足している。**
     聞いた時点で答えが分かるので、問題になっていない。

     **画面の側でも落とす**（`stripHeardAnswer()`）——
     **指示は読み飛ばされうる**ので、形はこちらで確かめる
     （CLAUDE.md「道具の形で強制する」）。 */
  '**audio_text の中に answer を入れない。**',
  'answer と同じ文を、読み上げる英文の最後（や途中）に足さない',
  '（例:「Could you give me a hand with these boxes?',
  ' I appreciate your help.」のように足すと、',
  '**聞いた時点で答えが分かってしまう**）。',
  '**audio_text は、1人が言う1文だけで終わらせる。**',
].join('')

/**
 * ★ **必ず話す人が入れ替わる**(TOEIC L&R Part 2)。
 *
 * **本番がそう決まっている試験だけ**に使う ——
 * 「ある人の問いかけに、別の人が3つの応答のうち1つで返す」が Part 2 である。
 * **ここを広げると、試験対策でなくなる**(第5.357節で広げなかった理由)。
 */
export const REPLY_RULE_SWAP = [
  '**2人の会話である。** audio_text は**相手**が言う1文、',
  'answer は**こちらが返す1文**。**話す人が必ず入れ替わる。**',
  '**同じ人の続きのセリフにしない。**',
  '**その表現が「返事」として自然に出てくる場面のほうを作る。**',
  共通,
].join('')

