/**
 * **「単語とフレーズの音」を出すかどうか**(2026-09 利用者の指定)。
 *
 *   > 発音の機能は一度廃止してください。
 *   > いつでも戻せるように
 *
 * ============================================================================
 * 【何を廃止したのか — 廃止していないもの】
 *
 *   スピーチ練習の画面(`pages.id = 'pronunciation'`)には、2つ入っている。
 *
 *     ・**わたしのスピーチ**(`SpeechBoard`・0054)  ← **残す**
 *     ・**単語とフレーズの音**(`SoundPractice`)    ← **これを廃止した**
 *
 *   利用者が言った「発音の機能」は後者である。前者は数日前に
 *   利用者自身が頼んだもので(0054)、画面の名前もスピーチ練習である。
 *   **画面そのものも、メニューの項目も消していない。**
 *
 * 【なぜ「消す」のではなく、この1行なのか】
 *
 *   利用者の指定は「**いつでも戻せるように**」である。
 *   消してしまうと、戻したい日に画面を書き直すことになり、
 *   そのときには「なぜ廃止したのか」の経緯も失われている。
 *
 *   だから**道はそのまま残し、既定を閉じる。**
 *   ゲストの添削(`LEARNER_WRITING_REVIEW`)とまったく同じ考え方である。
 *
 *   **戻す日は、下の1行を `true` にするだけ。**
 *   置き直しも SQL も、コードの書き直しも要らない。
 *
 * 【なぜ `src/lib/` ではないのか】
 *
 *   あちらは Supabase を引き連れていて、**素の node で一度も走らせられない**
 *   (`playMark.js` / `learnerFeatures.js` と同じ考え方)。
 *   判断をここに置けば、`npm run test:play` が
 *   「既定で閉じているか」「画面が本当にここへ任せているか」を見張れる。
 *
 * 【なぜ「値を偽にするだけ」でよいのか】
 *
 *   ふだんは**道具ごと消す**のが決まりである
 *   (「サンプルデータに戻す」・`withSkip`)。**残すと、次に見た人が
 *   『まだ使うのかもしれない』と読む**からだった。
 *   ここは逆で、**利用者が「戻せるように」と言っている。**
 *   だから「まだ使うかもしれない」が**正しい読み**になる。
 *   その意図が伝わるよう、ここに経緯ごと書いてある。
 */

/**
 * **単語とフレーズの音の練習を出すか。**
 *
 * **戻す日は、ここを `true` にするだけ。**
 */
export const SOUND_PRACTICE_ON = false

/**
 * 出すか。**画面の中で `SOUND_PRACTICE_ON` と直に書かない** ——
 * 置く場所の数だけ食い違う(`remakeModeOf()` / `canAskReview()` と同じ)。
 */
export function soundPracticeOn() {
  return SOUND_PRACTICE_ON === true
}
