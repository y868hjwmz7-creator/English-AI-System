/**
 * その教材の種類で選べる切り口。
 *
 * **`kind === 'dialogue'` と書かない**(会議で必ず抜ける)。
 * 記事とスピーチは1人が書く / 話すので記事の側、
 * 会話と会議は相手がいるので会話の側である。
 * **スピーチには出さない**(話し方の型がその役をしている)。
 */
export const anglesFor = (kind) => {
  if (kind === 'dialogue' || kind === 'meeting') return DIALOGUE_ANGLES
  if (kind === 'reading') return READING_ANGLES
  return []
}

/** id から切り口を引く。**無ければ `null`**(消えた id で落ちない) */
export const angleOf = (id) =>
  [...READING_ANGLES, ...DIALOGUE_ANGLES].find((a) => a.id && a.id === id) ?? null

/** 名前を引く。**知らない id はそのまま返す**(空欄にしない) */
export const angleLabel = (id) => angleOf(id)?.label ?? (id ? String(id) : '')

/**
 * 窓口へ渡す指定を組み立てる。
 *
 * **画面が組み立てて渡す**(`speechBrief` と同じ考え方)。
 * 窓口の中に一覧を持たせると、切り口を1つ足すたびに
 * 利用者に置き直してもらうことになる。
 */
export const angleBrief = (id) => {
  const a = angleOf(id)
  return a ? `${a.label} — ${a.brief}` : ''
}

/**
 * **まだ使っていない切り口から1枚引く**(おまかせ)。
 *
 * 使い切ったら、また全部から引く(行き止まりを作らない)。
 * `rand` を外から渡せるようにしてあるのは、**素の node で
 * 確かめられるようにするため**である(`npm run test:play`)。
 *
 * @param kind 教材の種類
 * @param used これまでに使った切り口の id(`materials.angle`)
 */
export function pickAngle(kind, used = [], rand = Math.random) {
  const list = anglesFor(kind)
  if (!list.length) return null
  const seen = new Set((used ?? []).filter(Boolean))
  const fresh = list.filter((a) => !seen.has(a.id))
  const pool = fresh.length ? fresh : list
  return pool[Math.min(Math.floor(rand() * pool.length), pool.length - 1)] ?? pool[0]
}
