/**
 * **話の切り口**(2026-09 利用者の指定)。
 *
 *   > 全て同じ条件で教材を作成した時に過去の内容に被らないものを
 *   > 作成できるシステムである必要があります。似たようなシチュエーションと
 *   > いうのも避けたいです。選んだシチュエーションや場面が同じでも、
 *   > 全然違う感じになって欲しいわけです。
 *
 * ============================================================================
 * 【なぜ要るのか ——「出力の揺らぎ」に頼れない】
 *
 *   同じ入力を渡せば、AI は同じあたりへ寄る。しかも
 *   **Sonnet 5 は `temperature` を指定できない**(指定すると失敗する・
 *   `generate-material/index.ts` の `MODEL` の注記)。
 *   つまり**「毎回ばらつかせる」を出力の側に頼れない。**
 *   ばらつかせたければ、**入力そのものを毎回変えるしかない。**
 *
 *   そこで「同じ場面を、どの角度から書くか」を**閉じたリスト**で持ち、
 *   作るたびに1枚引く。同じ「面接」でも、
 *   「意見が割れる」と「悪い知らせを伝える」ではまったく別の会話になる。
 *
 * 【`SPEECH_STYLES`(話し方の型)とまったく同じ形にしてある】
 *
 *   あちらは**どう話すか**、こちらは**何を書くか**。
 *   決まりごとも同じ。
 *
 *   ・**閉じたリストで持つ。** AI に「毎回ちがう切り口で」と頼まない
 *     (頼んでも、寄るものは寄る)
 *   ・**`hint` は `<option>` にそのまま出る。**
 *     強調の書き方(`**`)を混ぜない(Markdown として解釈されない)
 *   ・**一度入れた切り口は、指示がないかぎり減らさない**
 *     (業種・趣味・場面と同じ・共通ルール)
 *   ・**何にも依存しない。** だから `npm run test:play` が
 *     素の node で見張れる(`playMark.js` と同じ考え方)
 *
 * 【`SPEECH_STYLES` と違うところ ——「保存する」】
 *
 *   話し方の型は保存していない(書き方に効くだけ)。
 *   けれども切り口は **`materials.angle` に保存する**(0046)。
 *   保存しないと「**まだ使っていない切り口から引く**」ができず、
 *   おまかせが同じものを続けて引いてしまう。
 *
 * 【場面ごとの絞り込みは、あえて作っていない】
 *
 *   話し方の型には `SCENE_STYLES`(場面 → 型)がある。
 *   こちらには**作れない。** 場面は 83分野 × 平均21場面で
 *   **1,700通り**あり、その全部に手で対応表を書くことはできない。
 *   **書けない表は作らない**(あやふやなことを言わない、と同じ)。
 *
 *   代わりに**本文の種類で分けてある。** 記事の切り口(数字で見る・
 *   昔と今)と会話の切り口(意見が割れる・断る)はそもそも別物なので、
 *   ここで分ければ「面接なのに数字で見る」のような組は出ない。
 *
 * 【Speech練習には出さない】
 *
 *   あちらには **`SPEECH_STYLES`(話し方の型)がすでにある。**
 *   役目が重なるものを2つ並べると、選ぶものが増えるだけである
 *   (**同じことをするものを2つ見せない**)。
 *   スピーチの「被らない」は、過去の話を避けさせる側(`avoidTopics`)が担う。
 */

