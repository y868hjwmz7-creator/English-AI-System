/**
 * 組(`sentenceFrames.js` の `groups[].id`)→ やること。
 *
 * **組を足したら、ここにも足す。** 足すまで `npm run test:shift` が赤い ——
 * `check.sql` と移行の関係とまったく同じ作法である
 * (**足し忘れても静かに動いてしまう**のがいちばん悪い)。
 */
export const MOVE_OF_GROUP = new Map([
  /* ① 無生物主語。**7組とも、やることは同じ** */
  ['push', 'inanimate'],
  ['block', 'inanimate'],
  ['need', 'inanimate'],
  ['result', 'inanimate'],
  ['state', 'inanimate'],
  ['show', 'inanimate'],
  ['it', 'inanimate'],
  /* ② 主語の席 */
  ['ways', 'subject'],
  /* ③ それ以外。**やることが1つずつ違う** */
  ['focus', 'focus'],
  ['topic', 'topic'],
  ['connect', 'connect'],
  ['extend', 'extend'],
  ['soften', 'soften'],
  ['compare', 'compare'],
  /* ④ 名詞句を入れ替える。**`sentenceFrames.js` の組ではない** ——
     組は 14 のままで、練習だけが1つ多い */
  ['swap', 'swap'],
  /* ⑤ 見分ける。これも `sentenceFrames.js` の組ではない */
  ['quiz', 'quiz'],
])

/** 組から「やること」を引く。知らない組は `null`(**当てずっぽうで返さない**) */
export function moveOfGroup(groupId) {
  const id = MOVE_OF_GROUP.get(groupId)
  return id ? (SHIFT_MOVES.find((m) => m.id === id) ?? null) : null
}

