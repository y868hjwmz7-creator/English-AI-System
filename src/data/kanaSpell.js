/**
 * ============================================================================
 * **かな → 英語風のつづり**(第5.266節・2026-09-26 利用者の指定)
 *
 *   > UMITO のような会社の名前をしてして記事やダイアローグを作ろうとすると、
 *   > 英語の読みが「ゆーえむあいてぃーおー」と言われてしまいます。
 *   > 他のケースでもうまく対応できるよう汎用性のある解決策を考えてください。
 *   > 例えば「細かい指定」内に読み方も含めればOKなど
 *
 * ── **なぜローマ字ではないのか** ──────────────────────────
 *
 *   `UMITO` をそのまま渡すと、読み上げは**大文字の並び**と見て
 *   1文字ずつ読む(`U M I T O`)。これが「ゆーえむあいてぃーおー」である。
 *
 *   では素のローマ字(`Umito`)ならよいかというと、そうでもない ——
 *   英語の読み上げは `u` を「ユー」、`i` を「アイ」と読みがちで、
 *   **「ユーマイト」**のようになる。
 *
 *   だから**英語の綴りの感覚に寄せた書き方**(respelling)にする。
 *
 *     ウ → oo    ミ → mee    ト → toh      →  oo-mee-toh
 *
 *   これは辞書が発音を示すときの書き方と同じ考え方で、
 *   **英語の読み上げに、いちばん素直に届く。**
 *
 * ── **音のまとまりごとに区切って並べる** ──────────────────
 *
 *   長いものから先に見る(`キャ` を `キ` + `ャ` に割らない)。
 *   **ここに無い字が混ざったら、`spellKana()` は `null` を返して黙る**
 *   —— 当てずっぽうで音を作らない(CLAUDE.md
 *   「分かっていないことを、分かったように書かない」)。
 *
 * ── **一覧は減らさない**(共通ルール)────────────────────
 *
 *   足すのはよい。減らすと、**いままで読めていた名前が読めなくなる。**
 * ============================================================================
 */

