/**
 * **ひらがなをカタカナに寄せる。**
 * 利用者はどちらでも書く —— **書き方の違いで読めなくなるのは、こちらの都合**である。
 */
export const toKatakana = (s) => String(s ?? '').replace(
  /[ぁ-ゖ]/g,
  (c) => String.fromCharCode(c.charCodeAt(0) + 0x60),
)
