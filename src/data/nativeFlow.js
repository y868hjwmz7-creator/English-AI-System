/* ==========================================================================
 * 覚え具合と突き合わせて、Quick Response の1行にする
 *
 * **`qr_items()`(0048)が返すのと、1つ残らず同じ形**にしてある。
 * だから `QrReview.jsx` は、冊が変わっても**1文字も書き分けていない** ——
 * 出題も絞り込みも聞き流しも紙も、そのまま効く
 * (`basicRows()` / `shelfReviews.js` とまったく同じ考え方)。
 *
 * **Unit の切り替えを作らない。** `material_title` に Unit を入れてあるので、
 * Quick Response の復習にもともとある「**教材の名前で絞る**」が
 * そのまま効く(棚が `material_industry` を使い回したのと同じ話)。
 * ========================================================================== */
import { normEn } from '../lib/textNorm.js'

/** その Unit。**範囲の外は null**(当てずっぽうで返さない) */
export const unitOf = (id) =>
  NATIVE_FLOW_UNITS.find((u) => u.id === Number(id)) ?? null

/**
 * 絞り込みに出す名前。**`material_title` に入れる。**
 *
 * 「Native Flow」を頭に付けてあるので、自分の Quick Response 帳の
 * 教材名と並んでも**どちらの冊の問か、ひと目で分かる。**
 */
export const unitTitle = (id) => {
  const u = unitOf(id)
  return u ? `Native Flow Unit ${u.id} ${u.label}` : 'Native Flow'
}

/**
 * ファイルの 690 件 × その人の覚え具合。
 *
 * **行の無い問は「まだ・箱0・今日出す」。** 待たせる理由がない
 * (`basicRows()` と同じ)。
 *
 * @param seen    `qr_items()` が返した行(`en_norm` で引く)
 * @param today   きょうの日付。`due_on` の既定になる
 */
export function nativeFlowRows(seen = [], { today = '' } = {}) {
  const map = new Map(
    (seen ?? []).map((r) => [String(r?.en_norm ?? ''), r]).filter(([k]) => k),
  )
  return NATIVE_FLOW.map((x) => {
    const key = normEn(x.en)
    const s = map.get(key) ?? null
    return {
      en_norm: key,
      en: x.en,
      ja: x.ja,
      /* **話す人はいない。** 会話から溜めた問と違い、ここは1問ずつの表現である */
      speaker: null,
      status: s?.status ?? 'unknown',
      box: s?.box ?? 0,
      learn_streak: s?.learn_streak ?? 0,
      due_on: s?.due_on ?? today,
      added_at: s?.added_at ?? null,
      updated_at: s?.updated_at ?? null,
      /* **教材にしていない**ので、id は持たない(`materials` に行が無い) */
      material_id: null,
      material_title: unitTitle(x.u),
      material_industry: null,
      material_kind: null,
      material_genre: null,
      material_scene: null,
      material_level: null,
    }
  })
}
