/**
 * **業種べつの単語帳(棚)**(0057・2026-09 利用者の指定)。
 *
 *   > 何冊も違う単語帳を持てるようにしてほしいんです。基本は自分の単語帳、
 *   > Quick Response が表示され、他の独立した業種や趣味別の単語帳とは
 *   > そもそも混ざらないようにしたいんです。「自分の単語帳に追加する」
 *   > みたいのを押したものだけ自分の単語帳に追加されてほしいんです。
 *   > …そして、ゲストにはトレーナーが指定した単語帳のみが追加されるのです。
 *
 * ============================================================================
 * 【まず数えた。**1,700冊は作れない**】
 *
 *   利用者は「すべての業界、趣味について、すべてのシチュエーションと
 *   場面を想定したもの」と言った。そこで実際に数えた。
 *
 *   | 何 | 数 |
 *   |---|---|
 *   | 分野ぜんぶ | 83 |
 *   | **親だけ** | **35**(お仕事 26 / 趣味 9) |
 *   | 場面(共通と、種類ぶんを含む) | **合計 883**(棚あたり平均 25.2) |
 *   | **分野 × 場面** | **約 1,700**(種類まで数えたとき) |
 *
 *   **棚あたりの場面は、ばらつきが大きい**(実測)。
 *   エネルギー 80・格闘技 69 に対し、ビジネス全般・ゲーム・ファッションは 14。
 *   種類(`parent` を持つ行)を抱えている親ほど、`ownOf` が
 *   その種類ぶんの場面まで集めるためである。
 *
 *   CLAUDE.md には、まさにこの数について
 *   「**場面は 1,700通りあり、手で書けない。書けない表は作らない**」と
 *   書いてある。棚を場面ごとに作ると、そこへ戻ることになる。
 *
 *   だから利用者に数字を出して尋ね、こう決まった。
 *
 *   > 単語帳は業種ごと、出し方の中に場面やシチュエーションで絞り込み、
 *   > あなたのおすすめ通りでお願いします。
 *
 *   **棚は親の分野ごとに1冊 = 35冊。**
 *
 * ============================================================================
 * 【**場面べつは、やめた**】(2026-09 利用者の指定)
 *
 *   > 場面別はやめましょう。細かすぎる。35冊、これだけにしましょう。
 *
 *   はじめは「冊の中を場面で絞り込む」形にして、
 *   **作るのも場面ごと**(883回)にしていた。細かすぎた。
 *
 *   | | 前 | いま |
 *   |---|---|---|
 *   | 作る単位 | **場面**(883 回) | **冊**(35 冊 × 10 回) |
 *   | 1冊の語数 | 場面の数しだい(14〜80 場面 × 12 語) | **どの冊も 200 語** |
 *   | ばらつき | エネルギー 960 語 / ゲーム 168 語 | **無い** |
 *
 *   - **場面の一覧そのものは捨てない。** 窓口へ
 *     「この業種にはこういう場面がある」と**まとめて渡す**
 *     (`shelfSceneNames()`)。**偏らせないための手がかり**であって、
 *     区切りではない
 *   - **`shelf_words.scene` の列も、すでに入っている行も残す**
 *     (一度入れたものを勝手に減らさない・共通ルール)。
 *     これから作る語には入らないだけである
 *
 * ============================================================================
 * 【**別の一覧を作らない**】
 *
 *   棚の一覧は `industries.js` の**親そのもの**である。ここで並べ直さない。
 *
 *   - 分野を足せば、棚も**ひとりでに1冊増える**
 *     (利用者の「業界や趣味を追加するたびに単語帳も追加する」)
 *   - **種類(`parent` を持つ行)は棚を作らない。**
 *     `parentOf()` が親へ落とすので、
 *     「カテゴリーがかぶるものであれば既存のものに追加」が
 *     **条件を1つも書かずに**満たされる
 *   - 「一度入れたものを勝手に減らさない」もそのまま効く
 *     —— 減らす手立てがこちらに無い
 *
 * 【なぜ `src/lib/` ではないのか】
 *
 *   あちらは Supabase を引き連れていて、**素の node で一度も走らせられない**
 *   (`playMark.js` / `mp3Join.js` と同じ考え方)。
 *   一覧と**判断**はここに置き、`npm run test:play` が確かめる。
 */

import { INDUSTRIES, industriesIn, industryLabel, parentOf } from './industries.js'
import { scenesFor } from './genres.js'
import { cefrIndex } from './cefr.js'

/** 棚の組。**`INDUSTRY_GROUPS` と同じもの**(名前を2か所に持たない) */
export const SHELF_GROUPS = [
  { id: 'work', label: 'お仕事' },
  { id: 'hobby', label: '趣味・娯楽' },
]

/**
 * 棚の一覧。**親の分野そのもの**(お仕事 → 趣味・娯楽の順)。
 *
 * `industriesIn()` が「1つめの欄に出す分野」= 親だけを返すので、
 * **ここでは並べ直しも絞り込みもしない。**
 */
export const shelfList = () =>
  SHELF_GROUPS.flatMap((g) => industriesIn(g.id).map((i) => ({
    id: i.id,
    label: i.label,
    hint: i.hint ?? '',
    group: g.id,
  })))

/** その id の棚が在るか */
export const isShelf = (id) => !!id && INDUSTRIES.some((i) => i.id === id && !i.parent)

/**
 * その分野の語は、どの棚に入るか。
 *
 * **種類(コンサル(建設)など)は親の棚に入る。**
 * 利用者の言う「カテゴリーがかぶるものであれば既存のものに追加」が、
 * `parentOf()` 1つでそのまま満たされる。
 * 知らない分野・汎用(null)は `null`(**当てずっぽうで棚に入れない**)。
 */
export const shelfOf = (industry) => {
  if (!industry) return null
  const p = parentOf(industry)
  return isShelf(p) ? p : null
}

/** 棚の名前。**`industryLabel()` に任せる**(名前を2か所に持たない) */
export const shelfLabel = (id) => industryLabel(id)

/**
 * その棚に関わる場面。**窓口へ渡す手がかりであって、区切りではない。**
 *
 * **`scenesFor()` をそのまま使う。** あれは
 * 「その分野に特化した場面 + どこにでもある場面」を返し、しかも
 * **種類を持つ親では、種類ぜんぶの場面を集める**(`ownOf`)。
 * 棚は親なので、ここがちょうど欲しいものになる。
 */
export const shelfScenes = (id) => (isShelf(id) ? scenesFor(id) : [])

/**
 * 窓口へ渡す場面の名前。**偏らせないためだけに使う。**
 *
 * 多い棚では 80 件あるので上限を置く —— これは指示ではなく手がかりで、
 * **入力側は 100 語で 1 回 0.1 円に満たない**が、
 * 際限なく長くする理由も無い。
 */
export const SCENE_HINT_MAX = 30
export const shelfSceneNames = (id) =>
  shelfScenes(id).slice(0, SCENE_HINT_MAX).map((s) => s.label)

/**
 * **1冊に入れる語句の数。どの冊も同じ。**
 *
 * 200 にしたのは、基礎単語の「標準1200語」がすべての業種に共通の土台で、
 * 業種べつはその上に載る**その分野だけの語**だからである。
 * 200 語あれば、その業種の会議・やりとりで出てくる語はおおむね覆える。
 *
 * **場面の数で変えない**(2026-09 利用者の指定「場面別はやめましょう」)。
 * 変えると、エネルギー 960 語・ゲーム 168 語のように**冊ごとに桁が違う**
 * ものができ、選ぶ人には理由が分からない。
 */
export const WORDS_PER_BOOK = 200

/**
 * 1回の生成で頼む数。
 *
 * **1冊まるごと(200 語)を1回で頼まない。** 長すぎて途中で切られる
 * (`max_tokens`)。**区切れば、途中で失敗してもそこまでは残る。**
 *
 * 20 にしたのは、窓口の上限が 30 で、
 * **例文つきで 30 語を返させると `max_tokens` に触れることがある**ため。
 * 少し余裕を持たせてある。
 */
export const WORDS_PER_JOB = 20

/**
 * その棚をぜんぶ作ったとき、何語になるか。
 *
 * **押す前に語数と金額を出す**(見えない費用は管理できない・CLAUDE.md)
 * ために使う。実際にできる数は AI の返し方で前後する。
 */
export const shelfTarget = () => WORDS_PER_BOOK

/**
 * **まだ足りないぶんだけ**を、20 語ずつに割って並べる。
 *
 * - **すでに足りていれば空**。だから**何度押しても安全**である
 * - **作るのは足りないぶんだけ。** 手で入れた語も数に入る
 * - 最後の1回は端数になる(**20 語で割り切れなくても、超えて作らない**)
 *
 * @param id   棚の id
 * @param have いまその棚に入っている語数(**数**。場面ごとには数えない)
 */
export function shelfTodo(id, have = 0) {
  if (!isShelf(id)) return []
  const now = Math.max(0, Number(have) || 0)
  const need = Math.max(0, WORDS_PER_BOOK - now)
  const jobs = []
  for (let done = 0; done < need; done += WORDS_PER_JOB) {
    const count = Math.min(WORDS_PER_JOB, need - done)
    jobs.push({
      shelf: id,
      count,
      /** 何語目から何語目までか(帯に出す) */
      from: now + done + 1,
      to: now + done + count,
    })
  }
  return jobs
}

/**
 * **その棚に何語あるか。読む側は、入れ物の形を知らなくてよい。**
 *
 * ══════════════════════════════════════════════════════════════════
 * 【なぜ要るのか】(2026-09 実機・利用者の指摘)
 *
 *   > なぜ０語になっているのですか？
 *
 *   単語帳 → 業種べつ の画面で、**同じ画面の中で数が食い違っていた。**
 *
 *       学ぶ分野  [ ビジネス全般(0 語) ]     ← ここだけ 0
 *       まだ 190 / 覚えかけ 10 / 覚えた 0     ← 合わせて 200 語
 *       200 語から 5 語を出す / 聞き流す(200 語) / 印刷(200 語)
 *
 *   出どころは1行。`loadShelfCounts()` が返すのは **`Map`** なのに、
 *   `ShelfBooks` が **`counts[s.id]`** と**オブジェクトのつもりで**
 *   読んでいた。Map をそう読むと**必ず `undefined`** になり、
 *   `?? 0` で **0 語**に落ちる。**35 冊ぜんぶが 0 語**だった。
 *
 *   `npm run lint` も `npm run build` も通る。**数が出ているので、
 *   壊れているようにも見えない** —— 空の棚と見分けが付かない。
 *
 * 【CLAUDE.md に、まったく同じ落とし穴が書いてある】
 *
 *   > `wordStatuses` は Map である。`statuses[w]` と書かない
 *   > … オブジェクトのつもりで書くと**常に `undefined` になり、
 *   > 黙って 0 が並ぶ。**
 *
 *   **二度踏んだ。** だから今度は「気をつける」ではなく、
 *   **読む側が形を知らなくてよい形**にする。
 *
 * 【数えられなかったときは `null`。0 と取り違えない】
 *
 *   `loadShelfCounts()` は、数えられなかったら `null` を返す
 *   (「**数えられなかったら `null`** —— 0 と取り違えると
 *   『まだ1語もありません』という嘘になる」)。ここもそのまま通す ——
 *   **呼ぶ側が「語数そのものを出さない」を選べる。**
 * ══════════════════════════════════════════════════════════════════
 *
 * @param counts `Map` でも、素のオブジェクトでもよい。`null` なら数えていない
 * @param id     棚の id
 * @returns {number|null} 語数。数えていなければ `null`
 */
export function shelfCountOf(counts, id) {
  if (!counts || !id) return null
  const got = typeof counts.get === 'function' ? counts.get(id) : counts[id]
  const n = Number(got)
  return Number.isFinite(n) && n >= 0 ? n : 0
}

/**
 * 1回(20 語)を作るのにかかるおよその額(ドル)。
 *
 * **押す前に語数と金額を出す**(見えない費用は管理できない・CLAUDE.md)
 * ために使う。実測ではなく、Sonnet 5 の単価と 20 語ぶんの出力から
 * 見積もった幅である。**実際にかかった額は、作ったあとに出す。**
 */
export const JOB_COST = { min: 0.03, max: 0.06 }

/* ==========================================================================
 * ゲストへの指定 —— **新しい表を作らない**
 *
 *   「ゲストにはトレーナーが指定した単語帳のみが追加される」は、
 *   0055 の `learner_features`(ゲスト × 名前で1行)と**同じ形**である。
 *
 *   あの表は **`feature` に check を置いていない。**
 *   0055 の comment にこう書いてある ——「次に1つ足すたびに SQL を
 *   貼り直してもらうことになるので、名前の一覧はコード側が持つ」。
 *   だから **`shelf:<分野の id>` という名前で、そのまま入れられる。**
 *
 *   - 新しい表も、新しい RPC も、新しい RLS も要らない
 *   - `set_learner_feature()` の門番(`teaches()` / `is_owner()`)がそのまま効く
 *   - `erase_learner()` が**すでに消している**(表を足したら消す側にも足す、
 *     を守る必要がない)
 *
 *   **名前の作り方は、ここ1か所。** 画面で `'shelf:' + id` と書かない ——
 *   置く場所の数だけ食い違う(`remakeModeOf()` と同じ考え方)。
 * ========================================================================== */

/** `learner_features.feature` に入れる名前の頭 */
export const SHELF_PREFIX = 'shelf:'

/** 棚 → 名前。**知らない棚には名前を作らない** */
export const shelfFeature = (id) => (isShelf(id) ? `${SHELF_PREFIX}${id}` : null)

/** 名前 → 棚。棚でないもの・別の名前(`basics` など)は `null` */
export const shelfIdOfFeature = (name) => {
  const s = String(name ?? '')
  if (!s.startsWith(SHELF_PREFIX)) return null
  const id = s.slice(SHELF_PREFIX.length)
  return isShelf(id) ? id : null
}

/**
 * **この人に、その棚を出すか。**
 *
 * 判断はここ1か所。画面の中で `role === 'learner'` と書かない。
 *
 * ── **誰でも「出された冊だけ」**(2026-09 利用者の指定・**方針の変更**)──
 *
 *   もとは「**ゲスト以外にはぜんぶ出す**」だった(2026-09 利用者の指定
 *   「これらの単語帳はトレーナーアカウントでは独立した単語帳として
 *   自由に学習できるようにして下さい」)。**それを利用者が改めた。**
 *
 *     > その代わり、業種別単語帳のページではトレーナーは
 *     > 自分自身にアサイン出来るように改良してください。
 *
 *   「その代わり」は、**トレーナーの単語帳も絞る**ことへの引き換えである。
 *   実機で見ると、35 冊のプルダウンは**自分が学びたい1冊を選ぶ場所**
 *   としては多すぎた。
 *
 *   - **役割で分けない。** 出すかどうかは `learner_features` だけが決める
 *     ので、判断そのものが1行に減った
 *   - **トレーナーは、自分で自分に出す**(`ShelfBuilder` の「この単語帳を
 *     出す人」に**自分**が並ぶ。窓口は 0059)
 *   - **行き止まりを作らない。** 1冊も出していないトレーナーの単語帳からは
 *     「業種べつ」が消えるが、左のメニューの**業種べつの単語帳**から
 *     いつでも自分に出せる
 *   - **役割が分からないうちは出さない**(既定は「出さない」・
 *     `showsBasics()` / `canAskReview()` とまったく同じ作法)。
 *     `features` が読めていなければ `null` なので、そのまま満たされる
 *
 * @param features 開いているものの集合(`Set`)。読めていなければ null
 * @param shelf    棚の id
 */
export function showsShelf({ features = null } = {}, shelf = null) {
  if (!isShelf(shelf)) return false
  return !!features && features.has(shelfFeature(shelf))
}

/** その人に出す棚だけを並べる。**画面で `filter` を書き写さない** */
export const shelvesFor = (who = {}) => shelfList().filter((s) => showsShelf(who, s.id))

/* ==========================================================================
 * **チェックを入れた分野だけを学ぶ**(0058・2026-09 利用者の指定)
 *
 *   > 最終的にこうやって混ぜたくないんですよ。これは独立した単語帳に
 *   > したいんです。…チェックを入れた分野だけ単語が学べるようにしたいです
 *
 *   棚は 35 冊・語は 1万を超える(上の表)。**ぜんぶを一度に開かない。**
 *   チェックを入れた分野の語だけを読み、その中で練習する。
 *
 *   - **覚える。** 毎回選び直させない(「一度選んだら覚える」)
 *   - **出せなくなった棚は、黙って落とす**(`pickedShelves`)。
 *     トレーナーが指定を外した棚が残っていると、
 *     **見えていない冊の語が出題に混ざる**
 *   - 鍵の名前は**ここ1か所。** 画面に書かない
 * ========================================================================== */

/** チェックを入れた棚を覚えておく鍵 */
export const SHELF_PICK_KEY = 'eas.shelfPick'

/**
 * 覚えているチェックを、**いま出してよい棚だけに絞って**返す。
 *
 * @param saved   覚えていた id の一覧(壊れていてもよい)
 * @param allowed いま出してよい棚(`shelvesFor()` の返り値でも、id の一覧でもよい)
 */
export function pickedShelves(saved, allowed = []) {
  const okIds = new Set(
    (allowed ?? []).map((s) => (typeof s === 'string' ? s : s?.id)).filter(Boolean),
  )
  const list = Array.isArray(saved) ? saved : []
  const out = []
  for (const id of list) {
    const s = String(id ?? '')
    if (okIds.has(s) && !out.includes(s)) out.push(s)
  }
  return out
}

/** 覚えているチェックを読む。**壊れていても落ちない** */
export function loadShelfPick(allowed = []) {
  try {
    const raw = globalThis.localStorage?.getItem(SHELF_PICK_KEY)
    return pickedShelves(raw ? JSON.parse(raw) : [], allowed)
  } catch { return [] }
}

/** チェックを覚える */
export function saveShelfPick(ids) {
  try {
    globalThis.localStorage?.setItem(
      SHELF_PICK_KEY, JSON.stringify((ids ?? []).map(String)),
    )
  } catch { /* 覚えられなくても、その場では使える */ }
}

/**
 * **段ごとの語数**(2026-09 利用者の指定「レベルは絞り込みで指定できればOK」)。
 *
 * 絞り込みでレベルを選べるのは、**その冊に段の散らばりがあるとき**だけ
 * である(`WordbookFilter` は、選べるものが1つ以下の欄を出さない)。
 * ところが 200 語がぜんぶ B1 になっても、**画面には何も出ない** ——
 * 押しても段の欄が現れないだけで、なぜなのか分からない。
 *
 * だから**作っている場所に、そのまま数を出す。** 350 回まわす前に、
 * 1冊目の 20 語で偏りに気づける(**見えない費用は管理できない**)。
 *
 * **並びはやさしい順**(`cefrIndex`)。知らない段はいちばん後ろへ回す ——
 * 当てずっぽうで真ん中に混ぜない。
 *
 * @param rows `{ level }` を持つ行の一覧(棚の語でも、下書きでもよい)
 * @returns `[{ id, count }]`
 */
export function levelTally(rows) {
  const n = new Map()
  for (const r of rows ?? []) {
    const id = String(r?.level ?? '').trim()
    if (!id) continue
    n.set(id, (n.get(id) ?? 0) + 1)
  }
  const rank = (id) => { const i = cefrIndex(id); return i < 0 ? 999 : i }
  return [...n.entries()]
    .map(([id, count]) => ({ id, count }))
    .sort((a, b) => rank(a.id) - rank(b.id))
}
