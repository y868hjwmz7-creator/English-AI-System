/**
 * 既定の調子。**まん中の「カジュアル」から始める。**
 *
 * ディスカッションと想定される質問は**口に出して話す**練習なので、
 * いちばんよく使うのはふだんの会話の言い方である。
 * **一度選んだら覚える**(`loadWritingTone`)ので、
 * 仕事の英語だけを練習する人は、2回目から自分の調子で始まる。
 */
export const DEFAULT_TONE = 'casual'

/** id から調子を引く。**無ければ既定**(消えた id で落ちない) */
export const writingToneOf = (id) =>
  WRITING_TONES.find((t) => t.id === id)
  ?? WRITING_TONES.find((t) => t.id === DEFAULT_TONE)
  ?? WRITING_TONES[0]
