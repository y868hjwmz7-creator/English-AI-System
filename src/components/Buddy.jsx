/**
 * 顔。**どの顔でも口を曲げない**(第5.378節で、3回「真顔」と書きながら
 * 口だけ笑わせていた)。表情は**目の大きさとまぶた**だけで出す。
 */
function 顔パーツ(顔, face) {
  const out = []
  const 大 = face === 'cheer' ? 1.3 : face === 'listen' ? 1.12 : 1
  const 閉 = face === 'glad' || face === 'proud'
  const 片 = face === 'think'
  /* 閉じた目は**真横の直線。** 上向きの弧にしたら、それが笑顔である */
  const 線 = (x, y, w) => ({ r: 'eyeline', d: `M${x - w} ${y} L${x + w} ${y}` })
  const { 目, 口 } = 顔
  if (目.one) {
    const o = 目.one
    const R = 目.rr * 大
    if (閉) out.push(線(o.x, o.y, R * 0.8))
    else {
      out.push({ r: 'ring', cx: o.x, cy: o.y, rr: R })
      out.push({ r: 'dot', cx: o.x, cy: o.y, rr: R * 0.34 })
    }
  } else {
    const { l, r, rr } = 目
    if (閉) { out.push(線(l.x, l.y, rr * 1.3)); out.push(線(r.x, r.y, rr * 1.3)) }
    else {
      out.push(片 ? 線(l.x, l.y, rr * 1.3) : { r: 'dot', cx: l.x, cy: l.y, rr: rr * 大 })
      out.push({ r: 'dot', cx: r.x, cy: r.y, rr: rr * 1.1 * 大 })
    }
  }
  if (口) {
    if (face === 'listen' || face === 'cheer') {
      const w = (face === 'cheer' ? 0.42 : 0.3) * 口.w
      const h = face === 'cheer' ? 7 : 4.5
      out.push({ r: 'hole', d: `M${口.x - w} ${口.y - h / 2} L${口.x + w} ${口.y - h / 2}`
        + ` L${口.x + w} ${口.y + h / 2} L${口.x - w} ${口.y + h / 2}Z` })
    } else if (face === 'think') {
      out.push({ r: 'mouth', d: `M${口.x - 口.w / 2} ${口.y + 1.4} L${口.x + 口.w / 2} ${口.y - 1.4}` })
    } else {
      out.push({ r: 'mouth', d: `M${口.x - 口.w / 2} ${口.y} L${口.x + 口.w / 2} ${口.y - 0.6}` })
    }
  }
  if (face === 'think') {
    for (const [cx, cy, rr] of [[84, 13, 2], [91, 8, 2.5], [97, 3, 3]]) out.push({ r: 'dots', cx, cy, rr })
  }
  if (face === 'proud') {
    for (const d of ['M6 4 L6 14', 'M1 9 L11 9', 'M92 6 L92 13', 'M88.5 9.5 L95.5 9.5']) {
      out.push({ r: 'spark', d })
    }
  }
  return out
}

/** 1本を描く。`d` があれば線、無ければ丸 */
const 描く = (p, i, extra) => (p.d
  ? <path key={i} {...extra} d={p.d} />
  : <circle key={i} {...extra} cx={p.cx} cy={p.cy} r={p.rr} />)

/**
 * @param {object} p
 * @param {string} p.face  `buddyFace()` が決めた顔
 * @param {string} [p.size] `'sm'` / `'md'` / `'lg'`
 * @param {string} [p.kind] **ふだんは渡さない**(選ばれているものを自分で読む)
 */
export default function Buddy({ face = 'rest', size = 'md', kind, className = '' }) {
  const 選び = useBuddyKind()
  const id = buddyKindOf(kind ?? 選び)
  const 妖怪 = 形[id] ?? 形[BUDDY_KIND_DEFAULT]
  /* ★ **「出さない」をえらんだ人には、何も描かない**(第5.383節)。
       **フックより後ろで返す** —— 早い return を上に置くと、
       読み込み中と読み込み後でフックの数が変わる(CLAUDE.md 第5.220節)。
       置き場所(ホーム・やり終えた1枚)は `gap` で離してあるので、
       **1体ぶんの空き地は残らない**(共通ルール「隙間は `gap` で作る」)。 */
  if (!buddyShown(id)) return null
  /* **管は、太い墨の線 + 紙色の細い線**に展開する(幅が変わらない) */
  const 本体 = 妖怪.parts.flatMap((p) => (p.r === 'tube' ? [p, { ...p, r: 'tube-in' }] : [p]))
  const すべて = [...本体, ...顔パーツ(妖怪.顔, face)]
  return (
    <span
      className={`buddy buddy--${size} buddy--${face} buddy--k-${id}`
        + (buddyBreathes(face) ? ' is-breathing' : '')
        + (className ? ` ${className}` : '')}
      role="img"
      aria-label={buddyAlt(face)}
    >
      {/* **横は 0〜100、縦は 0〜104。** 箱を正方形にするため、左右に 2 ずつ足して
          中央に寄せてある —— `viewBox` は3体とも同じで、箱は 1px も動かない */}
      <svg viewBox="-2 0 104 104" focusable="false" aria-hidden="true">
        {/* ① 暖色の版。**少しずらして、先に刷る**(昔の2色刷りの、版ずれ) */}
        <g className="buddy-off">
          {本体.filter((p) => p.r !== 'tube-in').map((p, i) => 描く(p, i, {
            className: p.r === 'tube' ? 'buddy-off-tube' : undefined,
          }))}
        </g>
        {/* ② 墨の版 */}
        <g className="buddy-ink">
          {すべて.map((p, i) => 描く(p, i, { className: `buddy-${p.r}` }))}
        </g>
      </svg>
    </span>
  )
}
