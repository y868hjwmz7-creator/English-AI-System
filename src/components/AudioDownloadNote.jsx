/**
 * 音声をまとめたあとの知らせ。**文言は、この1か所。**
 *
 * 【なぜ切り出すか】(2026-09 利用者の指定)
 *
 *   > 各ゲストのアカウント内でも教材の音声がダウンロードできるように
 *   > してください。
 *
 *   出す場所が2つになった(トレーナーの「教材」/ ゲストの「今週の宿題」)。
 *   **同じ文を2か所に書き写さない**(CLAUDE.md) ——
 *   書き写すと、直したときに片方だけ古くなる。
 *
 * 【成功と失敗を、同じ見た目で終わらせない】
 *   できたときは**何が渡ったのか**を、足りないときは
 *   **何本足りないのか・どうすればよいのか**まで書く。
 *
 * 【置き場所は、呼ぶ側が決める】
 *   **押した場所のすぐ下に出す**(CLAUDE.md)。
 *   ここは `<p>` を1つ返すだけにしてあるので、
 *   行の外にも中にも置ける(`.btn-row` の中に入れると
 *   横に並んでしまうので、行の**外**に置くこと)。
 *
 * 【**できない操作を案内しない**】
 *   足りないときの逃げ道は、**画面によって違う。**
 *   「読み上げ音声を作り直す」はトレーナーの画面にしか無いので、
 *   ゲストに書くと**そこに無いボタンを探させる**ことになる。
 *   だから `trainer` で書き分ける ——
 *   **文そのものは、どちらもここにしかない。**
 *
 * @param done `useAudioDownload()` の `done`(まだなら null)
 * @param materialId いま出している教材。**別の教材の知らせを出さない**
 * @param trainer トレーナーの画面か(足りないときの逃げ道が1つ増える)
 */
export default function AudioDownloadNote({ done, materialId, trainer = false }) {
  if (!done || done.id !== materialId) return null

  return (
    <p className={`notice${done.ok ? ' notice--ok' : ' notice--warn'}`}>
      {done.ok
        ? <>{/* **1本にまとまっている教材は、それをそのまま渡す。**
                「音声 1 本をまとめました」では何のことか分からない */}
            {done.whole
              ? <>本文の音声(<strong>1本にまとめたもの</strong>)を渡しました</>
              : <>音声 <strong>{done.total} 本</strong>を1つにまとめました</>}
            ({Math.round(done.bytes / 1024 / 102.4) / 10} MB)。
            端末の「ダウンロード」に入っています。</>
        : done.missing > 0
          ? <>まだ作られていない音声が <strong>{done.missing} 本</strong>あります
              (全 {done.total} 本)。
              <br />
              {trainer
                ? <>先に「セッションで使う(大きく表示)」で
                    <strong>Listen (全体)</strong> を通して聴くか、
                    「読み上げ音声を作り直す」で作ってから、もう一度押してください。</>
                : <>先に「大きく表示する」で <strong>Listen (全体)</strong> を
                    通して聴いてから、もう一度押してください。</>}</>
          : <>音声をまとめられませんでした。{done.error}</>}
    </p>
  )
}
