/**
 * **くり返す / 1回**(2026-09 利用者の指定)。
 *
 *   > Listenボタンの横にはオートリピートのボタンをつけてください。
 *   > 意味音読、オーバーラッピング、シャドーイングも段落内の再生ボタンの
 *   > 横にはリピートボタンを配置してください。
 *
 * まねて言う練習(オーバーラッピング・シャドーイング・意味音読)も、
 * Quick Response の答え合わせも、**同じ英文を続けて何度も聴く。**
 * そのたびに押し直すのでは、口が追いつく前に止まってしまう。
 *
 * ディクテーションの各文には前からあったので(2026-09)、
 * **その形をそのまま部品にした。** 見た目も文言も変えていない。
 * **同じ見た目を何か所にも書き写さない**(CLAUDE.md)。
 *
 * 【決まりごと】
 * ・**覚えない。** 鳴りっぱなしになる指定なので、
 *   次に開いたときは必ず「1回」に戻す(呼ぶ側が状態を持つ)
 * ・**押している印は、色と文字の両方で出す。** 色だけに頼らない
 * ・止まる条件は `SpeakButton` の側にある
 *   (0.3秒に満たずに終わったら失敗とみなしてやめる)
 */
import { RepeatIcon } from './Icons.jsx'
/* **中身が変わっても、場所を動かさない**(第5.281節)——
   「くり返す」(4文字)と「1回」(2文字)で幅が変わると、
   折り返す行では**3つ目が上の段へ上がる**(実機で起きた) */
import SteadyLabel from './SteadyLabel.jsx'
/* **色は1か所で決める**(第5.242節)。押す前が白だと、押せるものに見えない */
import { toneOn } from '../lib/btnTone.js'

/**
 * 出す言葉。**一覧はここ1つ**(`[1回, くり返す]` の順)。
 * 書き写すと、片方だけ古くなる(CLAUDE.md)——
 * **場所を取るのにも、出すのにも、この同じ一覧を使う。**
 */
const 文言 = ['1回', 'くり返す']

export default function RepeatToggle({ on = false, onChange, className = '' }) {
  return (
    <button type="button"
            className={`btn btn--small ${toneOn(on, className)}${className ? ` ${className}` : ''}`}
            aria-pressed={on}
            title={on
              ? '止めるまでくり返します(押すと1回だけに戻ります)'
              : '1回だけ鳴らします(押すとくり返します)'}
            onClick={() => onChange?.(!on)}>
      <RepeatIcon /><SteadyLabel keep={文言}>{文言[on ? 1 : 0]}</SteadyLabel>
    </button>
  )
}
