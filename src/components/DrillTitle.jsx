/**
 * **いま開いている帳面の名前を、全文で出す**
 * (第5.176節・2026-09 実機・利用者の指定)。
 *
 * ============================================================================
 *   > つまり、タブが画面幅に収まるようにすると、冊のタイトルが長いものは、
 *   > 省略されて表示されることになる。
 *   > その分コンテンツの方にタイトルとして全文をきちんと表示する。
 *
 * 【なぜ2つに分けるのか】
 *
 *   帯の `冊名 ▾`(`BookPick`)は**押すもの**である。ほかの持ちもの
 *   (☰ と「出しかた」)と1行に並ぶので、**幅に収まるところで
 *   「…」に切れる。** 切れた名前だけでは「どの帳面か」が分からない。
 *
 *   **押すところと、読むところを分ける。**
 *   押すのは帯の札、読むのはこの1行である。
 *
 * 【単語帳と Quick Response で、同じものを使う】
 *
 *   利用者の指定「単語帳と同じ仕様に」。**書き写すと片方だけ古くなる**
 *   (CLAUDE.md)。props で受け取るだけなので、骨組み(Supabase 無し)でも
 *   そのまま描ける。
 *
 * 【冊が1つしか無い人にも出す】
 *
 *   `BookPick` は**冊が1つなら何も出さない**(えらぶ場所が要らないため)。
 *   そのときこそ、帯には名前がどこにも出ない —— **ここが唯一の名前**になる。
 *
 * @param label いま開いている冊の名前。**空なら、行ごと出さない**
 * ============================================================================
 */
export default function DrillTitle({ label = '' }) {
  const t = String(label ?? '').trim()
  if (!t) return null
  /* **見出しとして読ませる。** 読み上げソフトは見出しをたどるので、
     ただの `<p>` にすると「いまどの帳面か」を拾えない */
  return <h3 className="drill-title">{t}</h3>
}
