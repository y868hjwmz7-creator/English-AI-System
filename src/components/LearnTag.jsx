/**
 * **覚え具合の札**(第5.417節・2026-10-08 利用者の指定)。
 *
 * ============================================================================
 * 【点をやめて、丸く囲った文字にした】
 *
 *   > 単語帳の覚度合いのメーターが、出している数のメーターに被っちゃって
 *   > ますよね…。覚え度合いはやはり丸く囲った文字で表現しましょう。
 *
 *   はじめ**4つの小さな横棒**で描いたが、すぐ上にある**進み具合の帯**
 *   (`.drill-bar`)が**まったく同じ形・同じ金色の横棒**だった ——
 *   2つが1本の壊れた帯に見えた。**実機で見るまで気づかなかった。**
 *
 *   **同じ画面に、同じ見た目のものを2つ置かない。**
 *   形が同じなら、意味が違っても1つに見える。
 *
 * 【置き場所は、もとからある札の行】
 *   「単語」「副詞」と同じ `.wordcard-tags` の中に入れる。
 *   **新しい行を作らない**ので、進み具合の帯とは**構造として**離れる
 *   (どこかの余白を変えた日に、また寄っていくことがない)。
 *
 * 【段の決め方は `learnStage.js` 1か所】
 *   ここでは `status` も `box` も見ない。**`stageOf(row)` を呼ぶだけ**である
 *   —— 見る場所の数だけ食い違う(CLAUDE.md「判断は1か所に持つ」)。
 *
 * 【色だけに頼らない】
 *   **段の名前を、そのまま字で出す**(「覚えかけ」)。
 *   読み上げを使う人にも、色の見分けにくい人にも、同じものが届く。
 * ============================================================================
 */
import { stageLabel, stageOf } from '../lib/learnStage.js'

export default function LearnTag({ row = null }) {
  /* **段が決まらない行には、何も出さない。** 当てずっぽうで
     「未学習」を描くと、**まだ読めていないだけの語が苦手に見える**
     (CLAUDE.md「0 と `null` を取り違えない」) */
  const 名 = row ? stageLabel(stageOf(row)) : ''
  if (!名) return null

  return <span className="wc-tag wc-tag--stage">{名}</span>
}
