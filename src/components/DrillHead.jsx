/**
 * **帳面の名前と、進み具合**(第5.180節・2026-09 実機・利用者の指定)。
 *
 * ============================================================================
 *   > quick response のようにコンテンツの上部にタイトルを、
 *   > そして単語帳 のように個数のバーを。それで統一してください。
 *
 * 【2つの画面で、置き場所も形も違っていた】
 *
 *   | | 名前 | 進み具合 |
 *   |---|---|---|
 *   | 単語帳 | **カードの外**(地の上) | **1問 = 1つの区切り**(個数が分かる) |
 *   | Quick Response | **カードの中の上** | **ひと続きの帯**(個数が分からない) |
 *
 *   どちらも第5.176節で足したものだが、**別々に置いた**ので形が割れた。
 *   利用者の指定は「**名前は Quick Response のほう、バーは単語帳のほう**」
 *   である。
 *
 * 【だから、2つまとめて1つの部品にした】
 *
 *   名前だけを部品(`DrillTitle`)にして、バーは画面ごとに書いていたのが
 *   割れた理由である。**並びで1つ**なのだから、**入れ物ごと1つ**にする。
 *   こうすれば、次に触る人はどちらの画面を見ても同じものを見る。
 *
 * 【個数のバーは、1問=1つの区切り】
 *
 *   ひと続きの帯は「だいたい半分」までしか言えない。
 *   区切りなら**残り何問かが目で数えられる** ——
 *   「あと3つなら続ける」を支えているのはこちらである(第5.167節)。
 *
 * 【自分では何も読まない】
 *
 *   `props` で受け取るだけなので、骨組み(Supabase 無し)でも描ける
 *   (**描けないものは測れない**・CLAUDE.md)。
 * ============================================================================
 *
 * @param label 帳面の名前(全文)。空なら名前の行ごと出さない
 * @param total その回に出す数。**0 ならバーを出さない**(空の帯を出さない)
 * @param done  いくつ終えたか
 */
import DrillTitle from './DrillTitle.jsx'

export default function DrillHead({ label = '', total = 0, done = 0 }) {
  /* **数えられない値を、0 として描かない。** 文字や NaN が来たときに
     区切りが1つだけ出ると、「1問しかない」と読めてしまう */
  const n = Number.isFinite(Number(total)) ? Math.max(0, Math.floor(Number(total))) : 0
  const at = Math.min(n, Number.isFinite(Number(done))
    ? Math.max(0, Math.floor(Number(done))) : 0)

  /** **どちらも無ければ、入れ物ごと出さない**(空の行で場所を取らない) */
  if (!String(label ?? '').trim() && n === 0) return null

  return (
    <div className="drill-head">
      <DrillTitle label={label} />
      {/* **数を出さない。** 「1 / 30」は帯からはずした(第5.176節)——
          目で数えられるものを、もう一度数字で言わない */}
      {n > 0 && (
        <div className="drill-bar" role="presentation">
          {Array.from({ length: n }, (unused, i) => (
            <span key={i}
                  className={i < at ? 'is-done' : i === at ? 'is-now' : ''} />
          ))}
        </div>
      )}
    </div>
  )
}
