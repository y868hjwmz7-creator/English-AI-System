/**
 * **覚え具合の4つの点**(第5.417節・2026-10-07 利用者の指定・段階4の案A-3)。
 *
 * ============================================================================
 * 【なぜカードの中の点なのか】
 *
 *   いま開いている語が「未学習 / 苦手 / 学習中 / 覚えた」のどれなのかは、
 *   **押す前に知りたい** —— 「もう覚えた語がまた出てきた」のか
 *   「はじめて見る語」なのかで、答え方が変わる。
 *
 *   **札(「学習中」)も、4段のメーター(名前つき)も描いて選んでもらった**
 *   (案A-2)。選ばれたのは **A-3 の「カードの中の小さな4つの点」**である ——
 *   段階3で「項目が多すぎる」を削ったばかりなので、
 *   **同じ画面にまた札と帯を足すと元に戻る。**
 *
 * 【段の決め方は `learnStage.js` 1か所】
 *   ここでは `status` も `box` も見ない。**`stageOf(row)` を呼ぶだけ**である
 *   —— 見る場所の数だけ食い違う(CLAUDE.md「判断は1か所に持つ」)。
 *
 * 【数を書き写さない】
 *   点の数は `LEARN_STAGES` の長さそのもの。**4 と書かない** ——
 *   段を増やした日に、ここだけ古くなる(第5.406節で
 *   CSS に `repeat(3, …)` と決め打ちして、4枚めが2段めに落ちた)。
 *
 * 【色だけに頼らない】
 *   点は色の濃さでしか違わないので、**`aria-label` に言葉で入れる**
 *   (CLAUDE.md「色だけに頼らない」)。目で読む人には点が、
 *   読み上げを使う人には「覚え具合 学習中(4段のうち3段め)」が届く。
 * ============================================================================
 */
import { LEARN_STAGES, stageLabel, stageOf } from '../lib/learnStage.js'

export default function LearnDots({ row = null }) {
  /* **段が決まらない行には、何も出さない。** 当てずっぽうで
     「未学習」を描くと、**まだ読めていないだけの語が苦手に見える**
     (CLAUDE.md「0 と `null` を取り違えない」) */
  const id = row ? stageOf(row) : ''
  const at = LEARN_STAGES.findIndex((s) => s.id === id)
  if (at < 0) return null

  const 言葉 = `覚え具合 ${stageLabel(id)}(${LEARN_STAGES.length} 段のうち ${at + 1} 段め)`

  return (
    <p className="learn-dots" role="img" aria-label={言葉} title={言葉}>
      {LEARN_STAGES.map((s, i) => (
        <span key={s.id} className={`learn-dot${i <= at ? ' is-on' : ''}`} />
      ))}
    </p>
  )
}
