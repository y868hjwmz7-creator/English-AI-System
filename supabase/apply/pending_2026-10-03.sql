-- ============================================================================
-- 0074 教材に「用件 × 感情 × 相手への態度 × 会話上の反応」を覚えさせる
--      (第5.361節)
--
-- 【なぜ要るのか】(2026-10-03 利用者の指定)
--
--   > 感情を表す・相手に働きかける・反応するという観点でも、軸を広げられる。
--   > ただし、これらは全部を「話す目的」という一つの欄に詰め込むより、
--   > 次のように分けると教材の組み合わせを作りやすい。
--   >   ・発話の目的：頼む、断る、謝る、知らせる、説得する
--   >   ・感情・状態：怒っている、弱っている、喜んでいる、不安がある
--   >   ・相手への態度：叱る、励ます、嫌味を言う、気遣う
--   >   ・会話上の反応：反論する、受け流す、言い訳する、共感する
--   >
--   > たとえば「仕事のミスを報告する」場面でも、「焦って言い訳する」
--   > 「落ち込んで謝る」「怒って責任を追及する」「冷静に再発防止策を
--   > 提案する」と、感情や態度を変えるだけで会話の内容が大きく変わる。
--
--   **覚えておかないと「まだ使っていないものから引く」ができません。**
--   おまかせが同じ組み合わせを続けて引いてしまい、せっかく軸を増やしても
--   被ります。0046(切り口 `angle`)とまったく同じ理由・同じやり方です。
--
-- 【何が起きるか】
--   `materials` という表に、**`stance` という列を1つ増やすだけ**です。
--   **表は1つも増えません。行も1つも書き換わりません。**
--   いまある教材は、この欄が**空のまま**残ります(それで困りません)。
--
--   中身は `pu_apologize|em_down|at_openup|re_excuse` のような
--   短い文字列です(4つの軸の id を縦棒でつないだもの)。
--   **4つの列に分けていないのは、貼っていただく SQL を1つで済ませるため**です。
--
-- 【どこまで影響するか】
--   教材の本文・宿題・ゲストの情報・音声には、いっさい触れません。
--   **いままでできたことは、1つも減りません。**
--   この列を貼る前でも、教材はこれまでどおり作れます
--   (画面が「この列が無い」と気づいて、送らずに進みます)。
--
-- 【あわせて必要な作業】
--   **ありません。** 窓口(`generate-material`)の置き直しは要りません ——
--   4つの軸は**画面が作って渡す文字列**なので、窓口は何も知らなくて済みます
--   (切り口 `angle` とまったく同じ作法)。
--
-- 【成功の目安】
--   `Success. No rows returned` と出れば成功です。
-- ============================================================================

alter table public.materials
  add column if not exists stance text;

comment on column public.materials.stance is
  '用件 × 感情 × 相手への態度 × 会話上の反応(src/data/speechAxes.js の id を | でつないだもの)。'
  '保存しないと、おまかせが同じ組み合わせを続けて引く';
