-- ============================================================================
-- 0026 スコアの範囲を、実際の試験に合わせる
--
-- 【なぜ直すのか】(2026-08 利用者の指定)
--
--   > VERSANTの新形式は10-90点満点
--   > TOEICは100-990です
--
--   0005 で入れた範囲は **TOEIC 10〜990 / VERSANT 20〜80** だった。
--   どちらも実際と違う。
--
--     ・TOEIC は 100 点未満が出ない(リスニング・リーディングとも最低 5 点、
--       合計の下限は 10 ではない)
--     ・VERSANT は**新形式で 10〜90**。20〜80 のままだと、
--       10 点台・80 点台を**打ち込めない**
--
--   打ち間違いを止めるための決まりが、**正しい点数を拒む**側に回っていた。
--
-- 【何をするか】
--   `learner_scores_range` を付け替えるだけ。
--
-- 【どこまで影響するか】
--   ・**いま入っている点数は1件も変わらない。** 消えも直りもしない
--   ・教材・宿題・単語帳・取り組みには**いっさい触れない**
--   ・広げる方向の変更なので、**いまの行が新しい決まりに反することはない**
--     (前の範囲は新しい範囲に収まっている。TOEIC 10〜99 だけは
--      例外なので、そこだけ先に数えて知らせる)
--
-- 【何度貼っても安全】
--   `drop constraint if exists` → `add constraint`。
-- ============================================================================

do $$
declare
  v_bad int;
begin
  -- **先に数える。** 直せない行があるなら、黙って落とさずに知らせる
  select count(*) into v_bad
    from public.learner_scores
   where test_type = 'toeic' and score < 100;

  if v_bad > 0 then
    raise notice
      'TOEIC で 100 点未満の記録が % 件あります。新しい決まり(100〜990)には'
      ' 反しますが、**すでに入っている行はそのまま残します。**'
      ' 直すときは「レベルとスコア」から入れ直してください。', v_bad;
  end if;
end $$;

alter table public.learner_scores
  drop constraint if exists learner_scores_range;

-- **これから入る行にだけ効く**(`not valid` を付けているので、
-- すでにある行は検査しない)。過去の記録を消さずに、
-- これからの打ち間違いだけを止められる。
alter table public.learner_scores
  add constraint learner_scores_range check (
    (test_type = 'toeic'   and score between 100 and 990)
    or (test_type = 'versant' and score between 10 and 90)
    or (test_type = 'other')
  ) not valid;

comment on table public.learner_scores is
  'TOEIC / VERSANT などのスコアの履歴。TOEIC は 100-990、VERSANT は 10-90(新形式)。'
  '0026 で範囲を実際の試験に合わせた。すでに入っている行は検査しない(not valid)。';
