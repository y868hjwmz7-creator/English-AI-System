-- ============================================================================
-- 0068 単語 / フレーズに「例文」を持たせる(第5.254節)
--
-- 【なぜ要るのか】(2026-09-23 利用者の指定)
--
--   > 基本的には、単語、またはフレーズ毎に以下のようにまとめます。
--   > ■見出し: 単語 または フレーズ
--   > ■意味、解説
--   > ■練習する3〜6問 (作成時に指定)
--   >
--   > 基本、例文が小見出しとして3つくらいあってから日→英があるとベスト。
--   > 例文は折りたたみ式に。日→英も折りたたみ。
--
--   単語とフレーズが「英語・発音記号・意味」の一覧だったものを、
--   **1語ずつのまとまり**に組み直します。
--
--       ┌──────────────────────────────┐
--       │ come up with        /kʌm/    │  ← 見出し
--       │ 〜を思いつく                  │  ← 意味
--       │ 「上がってくる」= 考えが浮かぶ │  ← 解説
--       │ ▸ 例文(3)                    │  ← 畳んである
--       │ ▸ 日本語 → 英語(3〜6)        │  ← 畳んである
--       └──────────────────────────────┘
--
-- 【何が起きるか】
--   `material_items` に **`examples` という欄を1つ足すだけ**です。
--   中身は `[{"en": 英文, "ja": 訳}]` の形で、3つほど入ります。
--
--   **練習(日本語 → 英語)は、すでにある `practice` をそのまま使います**
--   (0065 で「かたまり」のために作った欄です)。
--   **同じものを2つの欄に持たせない**(CLAUDE.md)。
--
-- 【どこまで影響するか】
--   **表は1つも増えません。行も1行も増えません。**
--   すでにある教材・宿題・ゲストの情報には、いっさい触れません。
--   欄が1つ増えるだけで、古い教材ではその欄が空のままです
--   (空なら、画面は「例文」の札を出しません ——
--    **効かない操作を見せない**)。
--
-- 【成功の目安】
--   `Success. No rows returned` と出れば成功です。
--
-- 【何度貼っても安全か】
--   安全です。`add column if not exists` だけです。
-- ============================================================================

alter table public.material_items
  add column if not exists examples jsonb;

comment on column public.material_items.examples is
  '単語 / フレーズの例文(0068)。[{"en": 英文, "ja": 訳}] を3つほど。'
  '**読み上げは、開いたときに画面が頼む** —— '
  '畳んだままの例文に先に音を作ると、聴かれないものに課金することになる';
