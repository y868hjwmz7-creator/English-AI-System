-- ============================================================================
-- 0065 本文から拾った「かたまり」に、分類・本文の文章・練習を持たせる
--
-- 【なぜ要るか】(2026-09 利用者の指定)
--
--   > 「本文に出た語句」ですが、これを語句というよりも、コロケーション、
--   > 句動詞、イディオム、決まり文句、つなぎ言葉、丁寧な言い回し、
--   > 言い換え表現などに分類されるものをピックアップし、
--   > それぞれに練習問題を追加してほしいです。
--   > …それぞれ５問～１０問ずつ「日→英」を練習できるようにしたいです。
--   > …単語単体はここには載せない。
--   > あくまで２語以上のチャンクを練習する場とする
--
--   これまでの「本文に出た語句」は、語句・意味・例文を**読むだけ**だった。
--   読んで終わるページは、めくられるだけで終わる。
--   **その場で日→英を言える**ようにすると、練習の場になる。
--
-- 【何が起きるか】
--   `material_items` の表に、**列が3つ増えます。**
--
--     chunk_kind … 7分類のどれか(句動詞・イディオム など)
--     source_en  … 本文の中で、実際にそう使われていた1文
--     practice   … 日→英の練習(5〜10問)
--
--   **3つとも空から始まります。すでに入っている行は1つも書き換わりません。**
--   **何度貼っても同じ結果になります。**
--
-- 【どこまで影響するか】
--   教材・宿題・単語帳・ゲストの情報・取り組みの記録には触れません。
--   RLS(見える範囲の決まり)も変えません。
--   演習の種類(`material_sections_type_check`)も**1文字も変えません** ——
--   足すのは列だけで、`vocab_note` はもともと在ります。
--
-- 【貼る前でも壊れない】
--   画面は `runTolerant()` が、まだ無い列を外して読み直します(第5.23節)。
--   貼る前は**分類の札と本文の引用と練習が出ないだけ**で、
--   教材はこれまでどおり開けます。
--
-- 【分類の一覧を、ここに書かない】
--   `check (chunk_kind in ('collocation', …))` は**置きません。**
--
--   呼び名と並びは `src/data/chunkKinds.js` の**1か所**が持っています
--   (CLAUDE.md「呼び名・色・幅・鍵の名前を2か所に書かない」)。
--   ここにも書くと、分類を1つ直した日に
--   **利用者へ SQL の貼り直しを頼むことになります。**
--   知らない値が入っても、画面は**札を出さないだけ**です
--   (**当てられなければ黙る**・既定は「見せない」側)。
--
-- 【成功の目安】
--   `Success. No rows returned` と出れば成功です。
-- ============================================================================

alter table public.material_items
  add column if not exists chunk_kind text,
  add column if not exists source_en  text,
  add column if not exists practice   jsonb;

comment on column public.material_items.chunk_kind is
  'かたまりの分類(0065)。src/data/chunkKinds.js の id がそのまま入る。'
  '**値の一覧も、画面に出す名前も、あちら1か所**が持つ。'
  'ここには書かない —— 分類を1つ直した日に、この注記だけが古くなる';
comment on column public.material_items.source_en is
  '本文の中で、実際にそう使われていた1文(0065)。'
  '**読み上げは付けない** —— 本文の側ですでに音になっており、二度課金になる';
comment on column public.material_items.practice is
  'かたまりの練習(0065)。[{"ja": 日本語のお題, "en": 解答の英文}] を5〜10問。'
  '**教材を作るときに一緒に作る** —— レッスン中の待ち時間を 0 秒にするため';
