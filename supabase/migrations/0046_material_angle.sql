-- ============================================================================
-- 0046 教材に「切り口」と「何の話だったか」を控える
--
-- 【なぜ要るか】(2026-09 利用者の指定)
--
--   > 全て同じ条件で教材を作成した時に過去の内容に被らないものを
--   > 作成できるシステムである必要があります。似たようなシチュエーションと
--   > いうのも避けたいです。選んだシチュエーションや場面が同じでも、
--   > 全然違う感じになって欲しいわけです。
--
--   これまで「被らない」を守っていたのは**英文の単位だけ**だった
--   (0008 の一字一句の照合と、0009 の意味の近さ)。ところが
--
--     A: 会議に遅れた新人が、上司に謝りに行く話
--     B: 打ち合わせに遅れた新人が、先輩に謝りに行く話
--
--   この2本は**英文が1つも一致しない。** それでもゲストから見れば
--   「また同じような話」である。**見ている単位が「文」で、
--   人が似ていると感じるのは「話」だった。**
--
-- 【この2列が何をするか】
--
--   angle … その教材を**どの切り口で作ったか**(`src/data/materialAngles.js`)。
--           「意見が割れる」「悪い知らせを伝える」など。
--           **保存しないと、おまかせが同じ切り口を続けて引く。**
--   gist  … その教材が**何の話だったか**を日本語1〜2行。
--           作るときに AI が一緒に書く(`headline_ja` と同じ道)。
--           次に同じ業界・同じ場面で作るとき、**これを渡して避けさせる。**
--
--   どちらも**教材を選ぶための情報**であって、ゲストの画面には出さない。
--
-- 【何が起きるか】
--   `materials` の表に**列が2つ増えるだけ**です。
--   **すでに入っている教材は1行も書き換わりません**(2列とも空になります)。
--   空でも困りません —— 見出し(`headline`)と話題(`topic`)は
--   前から入っているので、**貼ったその日から「避ける」は効きます。**
--
-- 【どこまで影響するか】
--   宿題・単語帳・ゲストの情報・取り組みの記録・音声には触れません。
--   RLS(見える範囲の決まり)も変えません。
--   `materials` を読み書きする決まりは 0001 / 0002 / 0044 のままです。
--
-- 【何度貼っても安全です】
--   `add column if not exists` なので、2回貼っても同じ結果になります。
--
-- 【あわせて必要な作業】
--   **`generate-material`(教材を作る関数)の置き直しが要ります。**
--   置き直すまで、切り口も「避ける話」も窓口に届きません
--   (教材はこれまでどおり作れます)。画面が赤く知らせます。
--
-- 【成功の目安】
--   `Success. No rows returned` と出れば成功です。
-- ============================================================================

alter table public.materials
  add column if not exists angle text,
  add column if not exists gist  text;

comment on column public.materials.angle is
  '話の切り口(src/data/materialAngles.js の id)。保存しないと、おまかせが同じ切り口を続けて引く';

comment on column public.materials.gist is
  'その教材が何の話だったか(日本語1〜2行)。次に同じ業界・場面で作るとき、これを渡して同じ筋を避けさせる';

-- ────────────────────────────────────────────────────────────────
-- 探すのを速くする
--
--   「同じ業界 × 同じ場面の、新しい順に15本」を毎回引く。
--   教材が増えても軽く済むように、索引を1つだけ置く。
--   **列は増やさない**(すでにある industry / kind / created_at で足りる)。
-- ────────────────────────────────────────────────────────────────
create index if not exists materials_industry_kind_idx
  on public.materials (industry, kind, created_at desc);
