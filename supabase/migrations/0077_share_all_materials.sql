-- ════════════════════════════════════════════════════════════════
-- 0077 「自分だけ」の教材を、全トレーナーで共有に戻す
--
-- 【なぜ要るのか】(2026-10-06 利用者の指摘・第5.395節)
--
--     ゲスト画面で「この人に教材を作る」にして作った教材を
--     他の人に共有する方法を考えてください。
--     「一人と共有する」という選択肢はなくしましょう。
--     その人に作ったとしても「教材」のところには保管されるべきです
--
--     間違えてそのゲストだけに作ると、そのあと他の人と共有する方法がなく、
--     不便です
--
--   教材を作る画面には「公開範囲: 全トレーナーで共有 / 自分だけ」という
--   切り替えがありました。**「自分だけ」を押すと、ほかのトレーナーからは
--   その教材が永久に見えなくなります。**
--
--   しかも **あとから直す場所が、画面に1つもありませんでした。**
--   データベース側では**作った本人なら変えられます**が
--   (`for all … created_by = auth.uid()`)、
--   **ほかのトレーナーからは見えもしないし、直せもしません。**
--   だから、この SQL でまとめて戻します。
--
--   ゲストのページから作ると、発行のボタンが
--   **「発行して 1人と共有する」** と出ます。その人専用に作るものだと
--   読めるので、「自分だけ」を押してしまいます。
--
--   **教材は既定で全トレーナーが共有するもの**です(CLAUDE.md 冒頭)——
--   50人で共有すれば必要な教材が7週でそろう、というのが
--   この仕組みが回るための前提そのものです。
--
-- 【何が起きるか】
--   ・いま `visibility = 'private'`(自分だけ)になっている教材が、
--     **ぜんぶ `'school'`(全トレーナーで共有)に変わります**
--   ・**変わるのはこの1つの欄だけ**です。教材名・本文・設問・訳・音声・
--     弱点タグ・宿題(どのゲストに出したか)には、いっさい触れません
--   ・**0 件のこともあります。** 1度も「自分だけ」を押していなければ、
--     何も変わりません(それで正しい状態です)
--
-- 【どこまで影響するか】
--   ・表も列も増えません。消えるものもありません
--   ・ゲストから見えるものは**1つも変わりません**(ゲストは、自分に
--     出された宿題だけが見える仕組みで、公開範囲とは別の話です)
--   ・**何度貼っても同じ結果**になります
--
-- 【あわせて必要な作業】
--   **ありません。** 画面の側はすでに「公開範囲」の欄ごと無くしてあるので、
--   これから作る教材が「自分だけ」になることはありません。
--
-- 【成功の目安】
--   `Success. No rows returned` と出れば成功です。
--
-- 【制約(`materials_visibility_check`)は、わざと狭めていません】
--   `in ('private', 'school')` のままにしてあります。
--   狭めると**一方通行**になり、あとで「やはり自分だけも要る」と
--   なったときに戻せません。**画面から押せない**ようにするだけで、
--   この指摘は解けます(CLAUDE.md「方針の転換は、勝手に行わない」)。
-- ════════════════════════════════════════════════════════════════

update public.materials
   set visibility = 'school'
 where visibility is distinct from 'school';

-- ── 起動画面が「まだです」と出すための、小さな問い合わせ ──────────
--
--   アプリの起動画面は「貼る SQL が、まだ最後まで届いていません」を
--   出すために、**いちばん新しい移行の印**を1つ見ています。
--   この移行は表も列も増やさない(行を書き換えるだけ)ので、
--   **見るものを、ここで1つ用意します。**
--
--   **関数にする理由。** `materials` は RLS(行ごとの見える・見えない)で
--   守られていて、**ほかのトレーナーが「自分だけ」で作った教材は、
--   そもそも問い合わせても返ってきません。** 表をそのまま数えると
--   「隠れている教材は0件です」と、いつでも答えてしまいます。
--   `security definer`(作った人の権限で動く)の関数なら、
--   **スクール全体で1件も残っていないか**を正しく答えられます。
--
--   **返すのは1語だけ**です。教材名も、誰が作ったかも返しません。
create or replace function public.material_visibility()
returns text[]
language sql
stable
security definer
set search_path = public
as $$
  select case
    when exists (select 1 from public.materials
                  where visibility is distinct from 'school')
    then array['has_private']::text[]
    else array['school_only']::text[]
  end
$$;

grant execute on function public.material_visibility() to authenticated;
